/*
 * Возврат контрольной точки, у которой нет файла сборки, а основа с тех пор изменилась (приёмка слабого ПК, 22.11.2026).
 *
 * Точка хранит слои снимка и отпечаток сборки, но саму сборку — только путём в кэше. «Одна запись вместо двух» (`ASTRAL_INSTALL_MOVE_BUILD`) переносит сборку в игру, и файла в кэше нет: возврат
 * пересобирает его из основы и слоёв снимка. Основа берётся ТЕКУЩАЯ, а она могла вобрать правку мастерской (перебазирование на следующей установке), обновление игры или проверку файлов — пересборка
 * выходит другой, и прежде отказ звучал «Файл контрольной точки повреждён». Точка помнит отпечаток основы (`snapshot.compositionBases`, `engine-state.js`); основа другая и файла нет — отказ до
 * пересборки и до записи в игру, с этим кодом. Старая запись без поля и точка с файлом сборки на месте ведут себя как прежде.
 *
 * Слова — русские, как у прочих ошибок движка: окно сейчас точки только перечисляет (`library-numbers.js`) и `restorePoint` из интерфейса не вызывает, до человека текст не доходит. Появится
 * кнопка возврата — слова на шесть языков идут через `utils/installFailure.js` по коду.
 */

export const RESTORE_POINT_BASE_CHANGED = "restore-point-base-changed";

/** Отказ «основа игры изменилась»; `relativePath` — архив, у которого сборки нет, а основа другая. */
export function restorePointBaseChanged(relativePath) {
  return Object.assign(
    new Error(
      "Эту точку вернуть нельзя: после неё основа игры изменилась (правка мастерской, обновление игры или проверка файлов), а сборки точки в кэше больше нет. " +
        `Пересборка из новой основы положила бы в игру другой файл, а не тот, что хранит точка (${relativePath}). Игра не тронута. Выберите более свежую точку или нажмите «Починить».`,
    ),
    { code: RESTORE_POINT_BASE_CHANGED, relativePath },
  );
}

/**
 * Основа архива сейчас не та, на которой собраны слои точки. `null` в ответ — сравнивать нечем (старая запись без запомненной основы или основа не названа): поведение прежнее.
 * @param {{ snapshot: object, relativePath: string, resource: object }} input `resource` — ресурс в текущем состоянии.
 */
export function basesDiffer({ snapshot, relativePath, resource }) {
  const was = String(snapshot?.compositionBases?.[relativePath] || "").toLowerCase();
  const now = String((resource?.compositionBase || resource?.base)?.sha256 || "").toLowerCase();
  if (!was || !now) return null;
  return was !== now;
}
