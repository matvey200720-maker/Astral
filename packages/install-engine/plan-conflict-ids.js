/*
 * Какие конфликты плана заменяются ЦЕЛИКОМ — ОДИН помощник на всех потребителей `plan.conflicts` → `replaceModIds` (22.11.2026, решение лида 1: граница по стволам).
 *
 * Конфликт плана (`plan-install.js`) несёт `keeps` — слоты прежней работы, которых нет у нового пакета (прежний ганпак из трёх стволов, новый на один). Такую работу целиком не заменяем:
 * новая ложится слоем поверх общих записей, остальные стволы остаются, снятие новой возвращает прежний ствол. Правило одно и то же для ганпаков и скинов мастерской, и для РАБОТ КАТАЛОГА
 * с другими стволами («не терять чужие стволы», лид 1): `keeps` считается по слотам любой установленной работы, а не только `local-*`.
 * Пустой `keeps` (одно место — одежда, татуировка, скин с тем же стволом) — заменяется, как раньше.
 *
 * Новый путь `plan.conflicts` → `replaceModIds` берёт этот помощник, а не свой `map`/`filter`: иначе фильтр `keeps` теряется на третьем пути (так было у `weapon-skin.js`).
 *
 * `accept(conflict)` — дополнительное условие потребителя, оно отбирает ПРЕЖНЮЮ работу (`conflict.modId`), а не новую: скин мастерской берёт только прежние скины (`local-weapon-skin-…`) — СКИН НИКОГДА НЕ СНИМАЕТ
 * ГАНПАК, ни свой, ни каталожный, они остаются под ним слоем (решение лида 1, 23.11.2026; в 1.0.2 в хосте так и было); ганпак мастерской фильтра не имеет: по правилу стволов его заменяет всё, чьи слоты покрыты. `keeps` проверяется всегда.
 *
 * Остаются только работы, у которых остаётся СТВОЛ (23.11.2026, второе чтение `install-plan-keeps`): движок кладёт `keeps` любому конфликту, а у обычной работы каталога слот свой (`catalog-<id>`),
 * у одежды `clothing-…` — такие заменяются, как в 1.0.2. Ганпак каталога в Astral Weapons DLC и так обязан нести слоты `weapon-…` (`direct-weapon-dlc-v1`).
 */
const keepsGun = (conflict) => Array.isArray(conflict?.keeps) && conflict.keeps.some((slot) => /^weapon-/.test(String(slot)));
export function conflictsReplacedWhole(plan, accept = () => true) {
  const ids = (plan?.conflicts || []).filter((conflict) => !keepsGun(conflict) && accept(conflict)).map((conflict) => conflict.modId);
  return [...new Set(ids)].sort();
}
