const RECORD_FIELDS = {
  highways: ["id", "name", "points"],
  roads: ["id", "points"],
  urban: ["id", "name", "points"],
  runways: ["id", "points", "width"],
  beaches: ["id", "points"],
};

// Строка «x y x y …» -> замороженный список изменяемых точек { x, y }.
function line(coordinates) {
  const values = coordinates.trim().split(/\s+/).map(Number);
  const points = [];
  for (let at = 0; at + 1 < values.length; at += 2) points.push({ x: values[at], y: values[at + 1] });
  return Object.freeze(points);
}

// Замороженный список записей вида kind: у каждой записи заморожены и её точки.
function records(kind, rows) {
  const fields = RECORD_FIELDS[kind];
  return Object.freeze(
    rows.map((row) =>
      Object.freeze(
        Object.fromEntries(fields.map((field, at) => [field, field === "points" ? line(row[at]) : row[at]])),
      ),
    ),
  );
}

const peaks = PEAKS.map(([id, name, x, y, radius]) => Object.freeze({ id, name, x, y, radius }));

export const MAP_SCHEMATIC = Object.freeze({
  coastline: line(COASTLINE),
  water: Object.freeze([line(LAKE)]),
  rivers: Object.freeze(RIVERS.map(line)),
  highways: records("highways", HIGHWAYS),
  roads: records("roads", ROADS),
  urban: records("urban", URBAN),
  runways: records("runways", RUNWAYS),
  beaches: records("beaches", BEACHES),
  peaks: Object.freeze(peaks),
});
