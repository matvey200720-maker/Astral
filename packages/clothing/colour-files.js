/*
 * Файлы расцветок вещи игры: порядок и заглушки по размеру (22.11.2026; владелец: «Прятать»).
 *
 * ПОРЯДОК. Расцветка N вещи — N-й по порядку файл её расцветок, по имени файла, `localeCompare` (так оглавление игры строит `item.textureFiles`, и так считает `textureByIndex` для вещей из оглавления,
 * `apps/desktop/src/clothing-models.js`); тот же порядок у снимка плитки расцветки (`apps/desktop/src/game-item-shot.js`) и у `colourStubs`. Один сравниватель на всех (`compareColourFiles`), подключён и в `texturesOf`; сходство держит
 * `tests/clothing-colour-files.test.js`, в том числе на именах `x_a`, `x_a_uni`, `x_a_bla`, где код-юниты и локаль расходятся (`.` против `_`).
 *
 * ЗАГЛУШКИ. В базовой игре у ~500 вещей Rockstar оставил слот расцветки с заглушкой (шахматка). Размер файла есть в оглавлении у каждого файла расцветки, поэтому окно знает о заведомых заглушках без чтения:
 * плитки заглушек не рисуются, значок числа расцветок и число «Вещи GTA · N» считают остальные. Порог — `STUB_FILE_BYTES` = 1024 Б, и он ТОЛЬКО для заведомых заглушек. Замер на оглавлении владельца (22.11.2026, 34 274 файла
 * расцветок): меньше 1000 Б — 1892 файла в двух кластерах, ~200 Б (пустой файл) и ~800 Б (шахматка 4×4: 798–801 Б); 1000–1999 Б — 22; 2000–4095 Б — 124; 4096–8191 Б — 270; 8192–16 383 Б — 445; от 16 КБ — 31 521. То есть 1892 из 1914 файлов
 * ниже 2000 Б — заглушки двух кластеров. Всё, что от 1024 Б и выше, по размеру не судится: настоящая однотонная текстура 64×64 в DXT1 весит 2–3 КБ, и правило размера спрятало бы её навсегда. Такой файл читается, и заглушку по пикселям называет
 * `isStubPicture` (`resolved.stub` в Desktop) — плитка уходит после ответа «такой расцветки нет».
 */

/** Файл расцветки меньше этого — заведомо заглушка; от этого размера решает чтение файла (`isStubPicture`). */
export const STUB_FILE_BYTES = 1024;

/** Размер файла говорит «заглушка»; неизвестный размер (0, нет) — не заглушка. Граница — в сторону «читать»: ровно `STUB_FILE_BYTES` и выше не заглушка. */
export const isStubFileSize = (size) => Number(size) > 0 && Number(size) < STUB_FILE_BYTES;

/**
 * Локаль сравнения закреплена: «en». Голый `localeCompare` берёт язык системы человека, и на эстонской, литовской и латышской локалях (et, lt, lv) порядок латинских букв другой (`z` и `s` встают иначе) — расцветки сдвигались бы
 * относительно других машин. Для ru, uk, en, de, pl, fr (и ещё ~20 проверенных) порядок «en» тот же, что у голого `localeCompare`: прежние выборы людей и поставленные заменёнки не сдвигаются (`tests/clothing-colour-files.test.js`).
 */
export const COLOUR_ORDER_LOCALE = "en";
const COLLATOR = new Intl.Collator(COLOUR_ORDER_LOCALE);

/**
 * Порядок имён файлов расцветок — ОДИН источник (`Intl.Collator("en")`): по нему строится оглавление игры (`texturesOf`, `apps/desktop/src/game-clothing-index.js` → `item.textureFiles`) и список расцветок базовой папки слота
 * (`textureNames`, `apps/desktop/src/clothing-models.js` → `item.textures` → `textureByIndex`, установка заменёнки, «Надето»). Кодовые единицы (`.sort()`) на именах `x_a`, `x_a_uni` дают другой порядок (`.` < `_`).
 */
export const compareColourNames = (left, right) => COLLATOR.compare(String(left), String(right));

/** Порядок записей-файлов расцветок (`{ name }`) — тот же сравниватель имён. */
export const compareColourFiles = (left, right) => compareColourNames(left.name, right.name);

/** Файлы расцветок вещи в порядке расцветок: расцветка N — элемент N. */
export const colourFilesInOrder = (files = []) => [...files].sort(compareColourFiles);

/** Номера расцветок (по порядку файлов), у которых в игре лежит заведомая заглушка по размеру файла. */
export const stubColourIndices = (files = []) => colourFilesInOrder(files).flatMap((file, index) => (isStubFileSize(file.size) ? [index] : []));
