/*
 * Контракт прицела: одна геометрия на редактор и на компилятор.
 *
 * Редактор рисует прицел, компилятор пишет его в `hud_reticle.gfx`, и
 * договариваются они здесь — так же, как мини-карта договаривается в
 * `@modovik/minimap-contract`. Пока каждый считал «где стоят линии» сам,
 * они разошлись: превью меряло сцену 720×410, которой в файле нет, а риски
 * снайперки, пересекавшие линию, в игре выходили с дырой посередине.
 *
 *  • `stage.js` — сцена `hud_reticle.gfx`, снятая с файла игры: 1280×720,
 *    линза оптики, штатные отметки попадания и кратности.
 *  • `config.js` — поля обычного и снайперского прицела: значения по
 *    умолчанию, границы, старые проекты.
 *  • `geometry.js` — фигуры и их обводка; `layers.js` — из каких фигур
 *    прицел по слоям; `region.js` — объединение фигур контурами без
 *    перекрытий, как их ждёт Scaleform.
 *  • `colour.js` — цвета обычного прицела так, как их красит игра.
 *  • `styles.js`, `presets.js` — виды (форма) и готовые прицелы целиком.
 *  • `stock.js` — штатные метки игры для превью.
 *  • `weapons.js` — свой прицел на ствол: имена стилей в weapons.meta.
 *  • `ammo.js` — счётчик патронов: блок оружия `hud.gfx` по своим местам.
 *  • `target-health.js` — полоска HP над игроком: метка игрока
 *    `mp_gamer_info.gfx` своим видом (задача 2 ТЗ 11.10.2026). С того же
 *    дня это свой редактор мастерской «Полоска HP», а не инструмент прицела;
 *    договор остался здесь — шрифты у него общие со счётчиком патронов.
 *  • `damage-counter.js` — счётчик урона: сумма попаданий поверх прицела;
 *    `server-damage.js` — таблицы урона серверов из их вики.
 *  • `reload.js` — индикатор перезарядки: заливка у прицела по числам
 *    патронов, которые игра шлёт блоку оружия (владелец, 14.11.2026).
 */

