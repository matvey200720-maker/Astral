/*
 * Узоры покраски.
 *
 * Узор — процедурный: его нет картинкой в поставке, он считается по сиду и
 * четырём цветам. Поэтому один «лесной камуфляж» даёт тысячу разных рисунков
 * (сид 0…999, как paint seed у скинов CS2), и любой из них воспроизводится
 * у друга из кода работы байт в байт.
 *
 * Здесь только каталог: имена, подписи и заводские цвета. Как узор
 * рисуется — дело окна (`gun-patterns.js`): ему нужен холст.
 *
 * Роли цветов у всех узоров одни и те же, чтобы смена узора не превращала
 * подобранную палитру в кашу: первый — основа, второй и третий — пятна,
 * четвёртый — блик или прожилка.
 */

/* Как называются четыре цвета в «Выбранном узоре». У флага это полосы, у
   градиента — начало и конец, а «пятно» там ничего не объясняет; `null` —
   цвет узор не использует, и поля для него нет. */
export const PATTERN_ROLES = Object.freeze([
  "Основа",
  "Пятно",
  "Пятно 2",
  "Блик",
]);

const pattern = (id, ru, hint, colours, group, roles = PATTERN_ROLES) =>
  Object.freeze({
    id,
    group,
    label: Object.freeze({ ru }),
    hint: Object.freeze({ ru: hint }),
    colours: Object.freeze(colours),
    roles: Object.freeze(roles),
  });

