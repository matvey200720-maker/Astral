/*
 * Что тип погоды делает на земле: осадки, снег, вода, молния, низовой туман.
 *
 * ПОЧЕМУ ЭТОГО НЕТ В ТАЙМЦИКЛЕ
 *
 * Файл `w_*.xml` — это свет и цвет: четыре сотни чисел про небо, туман и
 * освещение. Ни дождя, ни снега на земле, ни мокрого асфальта в нём нет ни
 * одним параметром. Их игра включает по типу погоды и держит в другом файле —
 * `common/data/levels/gta5/weather.xml`, который редактор неба не читает и не
 * правит. Поэтому здесь модель, а не копия чисел Rockstar: величины подобраны
 * так, чтобы кадр читался тем же типом погоды, что и в игре.
 *
 * ПОЧЕМУ ОНА ОДНА НА ОБА ВИДА
 *
 * Погоду показывают два кадра: купол редактора неба (`sky-renderer.js`) и вид
 * с земли (`weather/`). Две таблицы означали бы две разные погоды в одном
 * редакторе: снег на куполе идёт, а на земле его нет — и человек не знает,
 * какому кадру верить. Таблица здесь, в пакете, потому что оба вида уже зависят
 * от него, а он от них — нет.
 *
 * ЧТО ЭТО НЕ ЗНАЧИТ
 *
 * Ни одно значение отсюда не уезжает в мод: проект правок собирается из файла
 * таймцикла и только из него. Снег в кадре — это подсказка «какую погоду вы
 * сейчас правите», а не правка. Кадр обязан говорить об этом прямо, иначе
 * человек примет снег за то, что он поставил в игру.
 */

import { findWeather } from "./samples.js";

/**
 * Погода на земле в единицах 0…100 — той же шкале, в которой их показывает
 * сцена (`WEATHER_RANGES`). Доли единицы понадобились бы шейдеру, но тогда
 * число в таблице перестало бы читаться человеком.
 *
 * Поля:
 *  • `precipitation` — вид осадков и насколько плотно они идут;
 *  • `wind` — им сносит осадки и ведёт облака;
 *  • `snow` — сколько снега лежит на земле и крышах;
 *  • `wetness` — мокрый асфальт: он темнеет и начинает отражать небо;
 *  • `lightning` — как часто бьёт молния;
 *  • `mist` — низовой туман: слой у самой земли, из которого торчат башни.
 *
 * Порядок полей и умолчание нулём: погода, у которой поле не названо, ничего
 * такого не делает. Пятнадцать полных строк по шесть чисел читались бы хуже,
 * чем список исключений.
 */
const CONDITIONS = Object.freeze({
  /* Ясная погода: сухо и ничего сверх таймцикла. Ветер всё же есть — в ясный
     день облака идут, и полный ноль остановил бы небо намертво. */
  EXTRASUNNY: { wind: 16 },
  CLEAR: { wind: 16 },
  NEUTRAL: { wind: 16 },

  CLOUDS: { wind: 30 },
  OVERCAST: { wind: 36 },

  /* Смог Лос-Сантоса стоит в воздухе, а не летит: ветра почти нет, зато у
     земли висит муть. */
  SMOG: { wind: 8, mist: 40 },
  FOGGY: { wind: 4, mist: 100 },

  RAIN: { rain: 62, wind: 48, wetness: 85 },
  THUNDER: { rain: 88, wind: 82, wetness: 100, lightning: 100 },
  /* «Проясняется» — это конец дождя: капли уже редкие, а вода на асфальте ещё
     стоит. Без мокрой земли этот тип не отличить от «облачно». */
  CLEARING: { rain: 22, wind: 44, wetness: 60 },

  SNOW: { snowfall: 55, wind: 34, snow: 70, mist: 15 },
  BLIZZARD: { snowfall: 92, wind: 90, snow: 100, mist: 45 },
  SNOWLIGHT: { snowfall: 26, wind: 22, snow: 45 },
  /* Рождество в GTA V — это заснеженный Лос-Сантос: снег лежит везде, а сыплет
     умеренно. Снег на земле здесь главнее снегопада. */
  XMAS: { snowfall: 38, wind: 18, snow: 85 },
  /* Хеллоуин — событийная погода: осадков нет, а низовой туман есть, и именно
     он вместе с цветом таймцикла делает кадр тем, чем он должен быть. */
  HALLOWEEN: { wind: 12, mist: 65 },
});

const value = (row, key) => Math.min(Math.max(Number(row?.[key] ?? 0), 0), 100);

/** Куда дует. Угол в градусах по часовой стрелке от севера. */
export const WEATHER_WIND_ANGLE = 235;

/**
 * Условия на земле для типа погоды.
 *
 * Неизвестный тип отдаёт сухую тихую погоду, а не бросает: сюда приходит и
 * `initialWeather` из каталога, и имя из чужого мода, и падать из-за опечатки в
 * идентификаторе предпросмотру незачем.
 */
export function weatherConditions(weatherId) {
  const id = findWeather(weatherId)?.id || "CLEAR";
  const row = CONDITIONS[id] || {};
  const rain = value(row, "rain");
  const snowfall = value(row, "snowfall");
  return Object.freeze({
    weather: id,
    /* Вид один: дождь со снегом игра не показывает, и таблица его не задаёт.
       Сильнейшее из двух — на случай, если задаст. */
    precipitation: Object.freeze({
      kind:
        rain >= snowfall && rain > 0 ? "rain" : snowfall > 0 ? "snow" : "none",
      amount: Math.max(rain, snowfall),
    }),
    wind: value(row, "wind"),
    windAngle: WEATHER_WIND_ANGLE,
    snow: value(row, "snow"),
    wetness: value(row, "wetness"),
    lightning: value(row, "lightning"),
    mist: value(row, "mist"),
  });
}

const fract = (value) => value - Math.floor(value);

/**
 * Вспышка молнии в этот момент времени: 0 — темно, 1 — разряд.
 *
 * Считается, а не разыгрывается. Кадр предпросмотра рисуется десятки раз в
 * секунду и обязан давать одно и то же на одну и ту же секунду — иначе вместо
 * разряда, который бьёт и гаснет, получилось бы мельтешение на каждом кадре.
 * Отсюда и детерминированный бросок: он привязан к номеру разряда, а не к
 * вызову.
 *
 * Ноль на нулевой секунде — условие, а не совпадение: предпросмотр
 * останавливает время кнопкой паузы и передаёт сюда ноль, а остановленный кадр
 * не должен застыть в белой вспышке.
 */
export function lightningFlash(seconds, strength = 0) {
  const power = Math.min(Math.max(Number(strength) || 0, 0), 100) / 100;
  const time = Number(seconds) || 0;
  if (power <= 0 || time <= 0) return 0;
  /* Гроза бьёт неровно: период — это верхняя граница, а попадёт ли разряд в
     очередной период, решает бросок. При полной силе бьёт почти каждый. */
  const period = 9 - 5 * power;
  const index = Math.floor(time / period);
  const roll = fract(Math.sin((index + 1) * 12.9898) * 43758.5453);
  if (roll > 0.25 + 0.6 * power) return 0;
  /* Внутри периода разряд стоит не на его границе: иначе гроза отбивает такт
     метрономом, а она бьёт вразнобой. */
  const inside = time - index * period - fract(roll * 91.7) * (period - 0.6);
  if (inside < 0) return 0;
  /* Разряд — не одна вспышка, а несколько за четверть секунды: главный удар и
     отголоски. Огибающая гаснет экспонентой, мигание сидит на ней сверху. */
  const decay = Math.exp(-inside * 7);
  const blink = 0.55 + 0.45 * Math.sin(inside * 46 + roll * 6.283185);
  return Math.min(Math.max(decay * blink * (0.35 + 0.65 * power), 0), 1);
}

/**
 * Чем этот тип погоды отличается от голого таймцикла — словами, для подписи в
 * кадре. Пустая строка означает «ничем»: осадков нет, снега нет, и всё, что
 * видно, приехало из файла.
 *
 * Подпись живёт здесь, а не в кадре, потому что она — прямое следствие
 * таблицы: добавили погоде снег, а подпись забыли, и кадр начал врать молча.
 */
export function weatherExtras(weatherId) {
  const it = weatherConditions(weatherId);
  const parts = [];
  if (it.precipitation.kind === "rain") parts.push("дождь");
  if (it.precipitation.kind === "snow") parts.push("снегопад");
  if (it.snow > 0) parts.push("снег на земле");
  if (it.wetness > 0 && it.precipitation.kind !== "rain")
    parts.push("мокрый асфальт");
  if (it.lightning > 0) parts.push("молния");
  if (it.mist >= 40) parts.push("низовой туман");
  return parts.join(", ");
}
