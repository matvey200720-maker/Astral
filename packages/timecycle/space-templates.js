/*
 * Шаблоны неба «космос» (Гигант над городом, Сатурн с кольцами, Красная планета, Чужое небо) и планеты вместо луны в этой альфе скрыты (22.11.2026, кадры стенда: три набора неснятых шаблонов).
 *
 * Причина. Тело кладётся в слот Луны листа `skydome.ytd` (128×128), и игра режет его маской фазы Луны: «Гигант» выходит половинкой диска с зубчатым краем (лист мелкий, на fov 40 видны ступеньки пикселей)
 * и читается как полосатая Луна, «Сатурн» — обрубком в форме буквы D (диск и кольца обрезаны пополам), «Красная планета» и «Чужое небо» — тот же механизм. Принять их по этим кадрам нельзя.
 * Вернуть можно после альфы: большие листы (`ytd-texture-replace`, ветка claude/sky-ytd-texture-replace-2211) и разбор, как снять фазу со слота Луны.
 *
 * Пока `SPACE_TEMPLATES_AVAILABLE = false`:
 *   - полки «Шаблоны неба: космос» в окне нет, планет в списке «Небесное тело» нет — остаётся «Луна игры» и «Луна» (карта NASA, фаза рисуется игрой и принята кадрами);
 *   - проект, который уже хранит планету (шаблон космоса применяли раньше или тело выбрано вручную), открывается и не падает: поле `moonBody` хранится как есть, но и в кадре окна, и при «Применить» тело считается
 *     отсутствующим (`appliedMoonBody` → null), то есть остаётся штатная Луна игры. Лист звёзд, цвета неба, ночной свет и облака шаблона — обычные настройки вида и ложатся как есть.
 * Тело-Луна (`kind: "moon"`) флаг не трогает.
 */
export const SPACE_TEMPLATES_AVAILABLE = false;

/** Тело, которое реально ляжет в слот Луны и в кадр окна: планету при выключенном флаге не кладём, штатная Луна игры остаётся. */
export function appliedMoonBody(body) {
  if (!body || typeof body !== "object") return null;
  if (!SPACE_TEMPLATES_AVAILABLE && body.kind !== "moon") return null;
  return body;
}
