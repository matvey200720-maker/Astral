/*
 * Обложки карты, мини-карты и зон — без поля (13.11.2026).
 *
 * Окно страницы мода увеличивает кадр до «рамки рисунка», а рисунком на матовом поле считает только то, что заметно от поля
 * отличается (больше 20 по каналу, `frame-fill.js`). Тёмная карта автора и тело панели мини-карты такими не являются, и окно
 * подгоняло кадр под яркие подписи, отрезая остальное (владелец: «миникарта и большая карта … фоточки обрезал … зоны
 * показываются не полностью»).
 *
 * Первое решение — серая рамка-карточка вокруг содержимого, которую окно брало за рамку рисунка, — владелец не принял в тот же
 * вечер: «обводку серую, толстую убери, она не должна быть в превьюшке». Теперь у таких обложек поля нет вовсе: оно
 * прозрачное. Кадр с прозрачным краем окно меряет иначе — по непрозрачным точкам (`borderField` → `transparent`), то есть ровно
 * по содержимому, и показывает его целиком на своём фоне. Ничего вокруг содержимого не рисуется.
 *
 * Здесь — только место под содержимое в кадре: его делят печь (`map-card-cover.js`) и окно-съёмщик (`zones-island-cover.js`).
 */

/** Зазор от содержимого до края кадра, доли ширины: кадр без поля, запас нужен только чтобы сглаженный край не упёрся в границу. */
export const COVER_GAP = 0.02;

/**
 * Размер, до которого вписывается содержимое, и отступ от края кадра (точки).
 * @param {{ width: number, height: number }} size
 * @returns {{ width: number, height: number, margin: number }}
 */
export function contentRoom(
  size,
  { gap = Math.round(size.width * COVER_GAP) } = {},
) {
  return {
    width: size.width - gap * 2,
    height: size.height - gap * 2,
    margin: gap,
  };
}
