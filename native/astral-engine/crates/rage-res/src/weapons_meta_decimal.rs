//! Число с шестью знаками после точки так, как его пишет помощник в `weapons.meta`.
//!
//! Помощник читает число запроса как `decimal` (точная десятичная запись) и печатает `ToString("0.000000")`: на
//! седьмом знаке «пять и больше» округляет вверх. Движок получает то же число как `f64`, а `format!("{:.6}")` округляет
//! двоичное значение: `0.1234565` выходит `0.123456`, а у помощника `0.123457`; расходится запись, у которой седьмой знак
//! — ровно пять. Здесь число берётся в кратчайшей десятичной записи, которая читается обратно в то же `f64` (то есть так,
//! как его набрали), и округляется по правилу помощника.
//!
//! Что не лечится числом `f64`: запись длиннее семнадцати значащих цифр (`1.0000000000000001` для `decimal` больше
//! единицы, для `f64` — ровно единица). Приложение шлёт числа, округлённые до тысячных (`muzzle-look.js`, `round3`).

/// Число с шестью знаками после точки по правилу помощника (см. описание модуля); минус пишется, пока результат не нуль.
pub fn decimal6(value: f64) -> String {
    if !value.is_finite() {
        return format!("{value:.6}");
    }
    // `Display` у `f64` — кратчайшая запись, читаемая обратно в то же число, и порядка (`e`) не пишет.
    let text = format!("{}", value.abs());
    let (whole, fraction) = text.split_once('.').unwrap_or((text.as_str(), ""));
    let mut fraction: Vec<u8> = fraction.bytes().map(|byte| byte - b'0').collect();
    fraction.resize(fraction.len().max(7), 0);
    let round_up = fraction[6] >= 5;
    let mut digits: Vec<u8> = whole
        .bytes()
        .map(|byte| byte - b'0')
        .chain(fraction.into_iter().take(6))
        .collect();
    if round_up {
        // Единица в последний разряд; девятки переносятся влево, и если дошли до края — число стало на разряд длиннее.
        let mut at = digits.len();
        loop {
            if at == 0 {
                digits.insert(0, 1);
                break;
            }
            at -= 1;
            if digits[at] == 9 {
                digits[at] = 0;
            } else {
                digits[at] += 1;
                break;
            }
        }
    }
    let point = digits.len() - 6;
    let sign = if value.is_sign_negative() && digits.iter().any(|digit| *digit != 0) {
        "-"
    } else {
        ""
    };
    let text: String = digits
        .iter()
        .map(|digit| char::from(b'0' + digit))
        .collect();
    format!("{sign}{}.{}", &text[..point], &text[point..])
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Запись в запросе -> то, что записал помощник (`parity/host-port/weapons-meta-modes/decimals.mjs`, 16.11.2026,
    /// настоящий файл оружия, поле `look.lightRgbMin`). Вторая колонка — что даёт `{:.6}` у `f64`, где оно другое.
    const ORACLE: &[(&str, &str)] = &[
        ("0", "0.000000"),
        ("0.5", "0.500000"),
        ("1", "1.000000"),
        ("127.5", "127.500000"),
        ("255", "255.000000"),
        ("0.125", "0.125000"),
        ("0.1234565", "0.123457"),
        ("0.1234575", "0.123458"),
        ("0.1234564", "0.123456"),
        ("0.1234566", "0.123457"),
        ("0.0000005", "0.000001"),
        ("0.0000004", "0.000000"),
        ("0.0000015", "0.000002"),
        ("0.0000025", "0.000003"),
        ("0.9999995", "1.000000"),
        ("0.9999994", "0.999999"),
        ("9.9999995", "10.000000"),
        ("63.9999995", "64.000000"),
        ("254.9999995", "255.000000"),
        ("2.0000005", "2.000001"),
        ("2.5000005", "2.500001"),
        ("0.3333335", "0.333334"),
        ("10.1234565", "10.123457"),
        ("1e-7", "0.000000"),
        ("5e-7", "0.000001"),
        ("1.5e-6", "0.000002"),
        ("0.30000000000000004", "0.300000"),
        ("0.1", "0.100000"),
        ("0.7", "0.700000"),
        ("100.0000005", "100.000001"),
        ("0.000002500000000001", "0.000003"),
        ("1.0000005", "1.000001"),
        ("-0", "0.000000"),
        ("-0.0", "0.000000"),
        ("0.00000049999", "0.000000"),
        ("0.00000050001", "0.000001"),
    ];

    #[test]
    fn numbers_are_written_like_the_helper_writes_them() {
        for (typed, written) in ORACLE {
            let value: f64 = typed.parse().unwrap();
            assert_eq!(decimal6(value), *written, "запись {typed}");
        }
    }

    #[test]
    fn the_seventh_digit_five_rounds_up_where_the_binary_value_rounds_down() {
        // Двоичное `0.1234565` чуть меньше записи, и `{:.6}` даёт шесть пятьдесят шесть: помощник — пятьдесят семь.
        assert_eq!(format!("{:.6}", 0.123_456_5_f64), "0.123456");
        assert_eq!(decimal6(0.123_456_5), "0.123457");
    }

    #[test]
    fn carry_runs_through_every_digit() {
        assert_eq!(decimal6(9.999_999_5), "10.000000");
        assert_eq!(decimal6(99.999_999_5), "100.000000");
        assert_eq!(decimal6(0.999_999_5), "1.000000");
    }

    #[test]
    fn whole_and_tiny_values_keep_six_places() {
        assert_eq!(decimal6(255.0), "255.000000");
        assert_eq!(decimal6(0.0), "0.000000");
        assert_eq!(decimal6(-0.0), "0.000000");
        assert_eq!(decimal6(1e-12), "0.000000");
        assert_eq!(decimal6(1e21), "1000000000000000000000.000000");
    }
}
