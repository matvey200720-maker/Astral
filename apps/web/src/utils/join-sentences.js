/*
 * «Причина. Что дальше» одной строкой. Причины приходят и с точкой на конце (текст главного процесса: «…размер не поменять.»), и без неё, и склейка `${причина}. ${дальше}` давала две точки
 * подряд (уведомление владельца 26.11.2026). Знак конца предложения у первой части остаётся как есть, точка добавляется, только когда его нет.
 */

/* Конец предложения: точка, «!», «?», многоточие — сами или перед закрывающей кавычкой или скобкой. */
const ENDS_SENTENCE = /[.!?…]["'»”“)\]]*$/u;

export function joinSentences(first, second) {
  const head = String(first ?? "").trim();
  const tail = String(second ?? "").trim();
  if (!head || !tail) return head || tail;
  return `${head}${ENDS_SENTENCE.test(head) ? " " : ". "}${tail}`;
}
