// Любой язык вне шести словарь знает как английский.
function dictionaryLanguage(language) {
  return LANGUAGES.includes(language) ? language : FALLBACK_LANGUAGE;
}

// ---- Отмена ------------------------------------------------------------

export function isCancellation(error) {
  if (error?.name === "AbortError") return true;

  const raw = error?.message;
  const message = (raw ? String(raw) : "").trim().replace(IPC_PREFIX, "");
  if (/^AbortError\b/.test(message)) return true;

  // Из "Error: Error: Операция отменена." остаётся "Операция отменена".
  const bare = message.replace(ERROR_LEAD, "").replace(/[.\s]+$/, "");
  return CANCEL_PHRASE.test(bare);
}

// ---- Можно ли показывать текст человеку --------------------------------

export function isReadableFailure(detail, language = "ru") {
  const text = detail ? String(detail) : "";
  if (text === "") return false;

  const verdict = READABILITY.find(([pattern]) => pattern.test(text));
  if (verdict) return verdict[1];
  // Непонятный и не русский/украинский текст всё равно лучше, чем ничего:
  // перевести его мы не можем, а англоязычный человек его прочтёт.
  return language !== "ru" && language !== "uk";
}

// ---- Слова семейства ---------------------------------------------------

function wordsOf(kind) {
  const key = String(kind);
  const found = WORDS_BY_KIND[key];
  if (found === undefined) return WORDS_BY_KIND.unknown;
  // constructor, toString и прочие имена из прототипа — не семейства.
  if (!Object.hasOwn(WORDS_BY_KIND, key)) {
    throw new TypeError(`Имя ${key} не семейство отказа`);
  }
  return found;
}

// Уточнения: подставляют в причину (а иногда и в совет) то, что удалось
// вычитать из текста движка. Работают только для точного совпадения семейства.

function refineMissingEntry({ text, reason, advice }) {
  const found = ENTRY_NOT_FOUND.exec(text);
  const path = found ? found[1].replace(TRAILING_PUNCTUATION, "") : "";
  const name = path.split(PATH_SEPARATORS).filter(Boolean).pop() ?? "";
  return { reason: reason.replace(FILE_SLOT, name ? ` ${name}` : ""), advice };
}

function refineMissingArchive({ text, reason, advice }) {
  const found = ARCHIVE_NOT_FOUND.exec(text);
  const path = found
    ? found[1].replace(TRAILING_PUNCTUATION, "").replaceAll("/", "\\")
    : "";
  return { reason: reason.replace(FILE_SLOT, path ? ` ${path}` : ""), advice };
}

function refineRunningGame({ text, reason, advice }) {
  const found = RUNNING_PROCESS.exec(text);
  if (!found) return { reason, advice };
  const [, program, pid] = found;
  const tail = pid ? ` (PID ${pid})` : "";
  return { reason: `${reason}: ${program}${tail}`, advice };
}

// В совете — те заглушки, что нашёл Astral (имя из списка процессов); списка нет — штатная `GTA5_BE.exe`.
function refineBattlEyeStub({ text, reason, advice }) {
  const names = text.slice(Math.max(0, text.search(/Найден процесс:/i))).match(STUB_NAME) ?? [];
  const named = names.length ? [...new Set(names)].join(", ") : DEFAULT_STUB_NAME;
  return { reason, advice: advice.replace("{process}", named) };
}

function refineUnreadableArchive({ text, reason, advice }) {
  const nested = NESTED_ARCHIVE.exec(text);
  let name = nested ? nested[1].split(ARCHIVE_SEGMENTS).pop() : "";
  if (!name) {
    const identified = ARCHIVE_IDENTIFIER.exec(text);
    name = identified ? identified[1] : "";
  }
  // update.rpf уже назван в самой причине, повторять его незачем.
  const showName = name !== "" && name.toLowerCase() !== "update.rpf";
  return { reason: showName ? `${reason} (${name})` : reason, advice };
}

function refineBrokenTimecycle({ text, reason, advice, code }) {
  const found = TIMECYCLE_FILE.exec(text);
  const file = found ? found[1] : DEFAULT_TIMECYCLE_FILE;
  let filled = reason.replace("{file}", file);
  if (found && found[2] !== undefined) {
    filled += ` (${LINE_WORDS[LANGUAGES.indexOf(code)]} ${found[2]})`;
  }
  return { reason: filled, advice };
}

// Образец папки для совета: для диска это его буква и папка Astral,
// иначе папка Astral рядом с названной, с теми же слэшами.
function sampleFolder(folder) {
  const drive = DRIVE_LETTER.exec(folder);
  if (drive) return `${drive[1].toUpperCase()}:\\Astral`;
  const slash = folder.includes("\\") ? "\\" : "/";
  return `${folder.replace(TRAILING_SEPARATORS, "")}${slash}Astral`;
}

function refineDeniedFolder({ text, reason, advice }) {
  const found = QUOTED_FOLDER.exec(text);
  const folder = found ? found[1] : "";
  return {
    reason: reason.replace("{path}", folder),
    advice: advice.replace("{folder}", sampleFolder(folder)),
  };
}

const REFINERS = new Map([
  ["game-file-missing", refineMissingEntry],
  ["game-entry-present", refineMissingEntry],
  ["game-entry-conflict", refineMissingEntry],
  ["game-archive-missing", refineMissingArchive],
  ["game-running", refineRunningGame],
  ["game-stub", refineBattlEyeStub],
  ["archive-unreadable", refineUnreadableArchive],
  ["timecycle-broken", refineBrokenTimecycle],
  ["folder-denied", refineDeniedFolder],
]);

export function failureWords(failure, language = currentUiLanguage()) {
  const kind = failure?.kind;
  const words = wordsOf(kind);
  const code = dictionaryLanguage(language);

  // Порядок обращений к словарю: совет, проверка целостности, журнал, причина.
  const adviceText = trIn(code, words[2]);
  const verifyText = trIn(code, KEY_VERIFY);
  const logsText = trIn(code, KEY_LOGS);
  const advice = adviceText
    .replace("{verify}", verifyText)
    .replace("{logs}", logsText)
    /* Имя кнопки настроек игры — из словаря, а не вписанное в фразу: на каждом языке в совете то слово, что на самой кнопке. */
    .replace("{restore}", trIn(code, "Вернуть как было"));

  if (kind === "unknown") {
    const detail = failure.detail;
    if (isReadableFailure(detail, language)) return { reason: detail, advice };
  }

  const reason = trIn(code, words[1]);
  const refine = REFINERS.get(kind);
  if (refine === undefined) return { reason, advice };
  return refine({ text: String(failure.detail || ""), reason, advice, code });
}

// ---- Разбор ошибки -----------------------------------------------------

export function describeInstallFailure(error, language = currentUiLanguage()) {
  if (isCancellation(error)) return null;

  const detail = String(error?.message || error || "").trim();
  const kind =
    RULES.find(([, pattern]) => pattern.test(detail))?.[0] ?? "unknown";
  const { reason, advice } = failureWords({ kind, detail }, language);
  return { kind, detail, reason, advice };
}

export function failureLine(failure) {
  if (!failure) return "";
  if (failure.reason === failure.detail) return failure.reason;
  return `${failure.reason}. ${failure.advice}`;
}

// Отмена — не отказ: вместо причины человеку показывают слово об отмене.
function describeForPerson(error, language, pick) {
  const described = describeInstallFailure(error, language);
  if (described === null) {
    return trIn(dictionaryLanguage(language), KEY_CANCELLED);
  }
  return pick(described);
}

export function humanFailure(error, language = currentUiLanguage()) {
  return describeForPerson(error, language, failureLine);
}

export function failureReason(error, language = currentUiLanguage()) {
  return describeForPerson(error, language, ({ reason }) => reason);
}

// Текст для вставки в тикет поддержки: что делали, какое семейство и что
// именно сказал движок.
export function failureTicket({ title = "", kind = "", detail = "" }) {
  const lines = [tr("Astral — отчёт об отказе")];
  if (title) lines.push(`Что делали: ${title}`);
  if (kind) lines.push(`Семейство: ${kind}`);
  lines.push(`Текст движка: ${detail || "—"}`);
  return lines.join("\n");
}
