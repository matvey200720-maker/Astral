/*
 * Older builds stored the language as its display title ("RUS") and the home
 * screen shipped a "ua" key while the picker writes "uk". Either mismatch drops
 * the whole interface into its English fallback, so every stored value is
 * resolved back to a supported id before it reaches a screen.
 */
const legacyLanguageAliases = {
  RUS: "ru",
  ENG: "en",
  UKR: "uk",
  UA: "uk",
  DEU: "de",
  GER: "de",
  POL: "pl",
  FRA: "fr",
  FRE: "fr",
};

export function normalizeLanguage(value) {
  const raw = String(value ?? "").trim();
  if (supportedLanguages.some((item) => item.id === raw)) return raw;
  return (
    legacyLanguageAliases[raw.toUpperCase()] ||
    supportedLanguages.find((item) => item.id === raw.toLowerCase())?.id ||
    "ru"
  );
}
