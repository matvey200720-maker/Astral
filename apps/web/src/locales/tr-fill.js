import { tr } from "./ui.js";

/**
 * Фраза со вставками на языке окна: ключ словаря — русский шаблон с `{0}`,
 * `{1}`…, вставки подставляются после перевода. Собранную русскую строку
 * слою перевода разметки оставлять нельзя: вставка с районом или числом ломала
 * шаблон, и русский хвост оставался на de/en/pl (аудит ТЗ 17.10).
 */
export const trFill = (template, ...values) => tr(template).replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ""));

/**
 * Вставки по именам: `{name}` → `values.name`. Для слов, которые код собирает сам по языку (`failureWords`, «Загрузки»): именованная вставка не
 * шаблон слоя перевода разметки (тому нужны `{0}`), поэтому такой ключ словаря не ловит чужие русские строки.
 */
export const fillNamed = (text, values) => text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
