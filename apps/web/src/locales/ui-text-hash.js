/*
 * Ключ словаря в упакованном виде (ТЗ 18.10.2026, бюджет бандла): русская строка → число.
 *
 * Зачем. Словарь интерфейса — ~15 тыс. русских строк с переводами на четыре языка. Одним куском
 * он весил 1,25 МБ gzip и перешагивал потолок гейта в 220 КБ в шесть раз. Теперь он собирается
 * по языкам (`ui-text-plugin.js`): окно грузит перевод только своего языка, а русский ключ в
 * пакете заменён хешем — ключи (240 КБ gzip) не приходится возить по пять раз.
 *
 * Хеш — cyrb53 (53 бита, влезает в безопасное целое числа JS). Ложное совпадение с чужой строкой
 * (текст, которого в словаре нет, а хеш такой же, и экран получил бы чужой перевод) — порядка
 * 15 тыс. / 2^53 ≈ 2·10⁻¹² на обращение; сборка при этом проверяет, что два ключа словаря сами
 * хешем не совпали, и падает, если совпали.
 *
 * Модуль без зависимостей: его читает и сборка (Node), и окно (`ui.js`) — хеш обязан быть один.
 */

/** Сколько кусков на язык: каждый — отдельный файл бандла, ниже потолка гейта с запасом. */
export const UI_TEXT_SHARDS = 4;

/** Хеш строки: целое от 0 до 2^53 − 1. */
export function uiTextHash(text) {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i += 1) {
    const code = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ code, 2654435761);
    h2 = Math.imul(h2 ^ code, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

/** В каком куске языка лежит перевод этой строки. */
export const uiTextShard = (hash) => hash % UI_TEXT_SHARDS;

/** Ключ строки внутри куска: короче десятичной записи. */
export const uiTextId = (hash) => hash.toString(36);
