/*
 * Порядок сборки карточек — ряд за рядом, сверху вниз.
 *
 * ЧТО БЫЛО НЕ ТАК. Задержку карточке назначал `--reveal-index: index % 8`,
 * выставленный из JSX. На сетке из четырёх колонок это даёт 0,1,2,3 / 4,5,6,7 /
 * 0,1,2,3 — девятая карточка стартует одновременно с первой, и до второго ряда
 * очередь доходит последней. Порядок читается как случайный именно поэтому:
 * счётчик считает не ряды, а восьмёрки.
 *
 * ПОЧЕМУ НЕ СЧИТАТЬ РЯДЫ В JSX. Компонент не знает, сколько колонок сейчас на
 * экране: колонок четыре, три или две в зависимости от ширины окна, и решает
 * это лист стилей, а не React. Единственный, кто знает правду, — уже
 * разложенная страница. Отсюда и мерка: ряд карточки — это её настоящий верхний
 * край.
 *
 * ПОЧЕМУ НЕ nth-child В CSS. Тот же довод с другой стороны: правило
 * `:nth-child(4n + 1)` придётся переписывать на каждую точку перелома, а
 * сетка `auto-fill` не описывается им вовсе.
 *
 * Здесь только арифметика — DOM трогает hooks/useAssemblyOrder.js.
 */

/*
 * Ряды считаются по верхнему краю, а не по номеру в разметке: соседи по ряду
 * стоят на одной высоте, а вот сколько их — знает только раскладка. Допуск
 * нужен потому, что дробные пиксели у колонок `minmax(0, 1fr)` расходятся на
 * доли единицы (312.49 против 312.5), и без него два соседа оказались бы в
 * разных рядах.
 */
const ROW_TOLERANCE = 12;

/*
 * Дальше четвёртого ряда очередь не растягивается. Ряд стоит от 120 до 180 мс
 * в зависимости от числа колонок, и без потолка низ длинного списка — скажем,
 * раскрытого каталога оружия — ждал бы больше секунды. Экран вмещает примерно
 * четыре ряда, поэтому потолок стоит там: ряды до него идут поочерёдно, а всё,
 * что ниже (и заведомо за краем окна), приходит вместе с четвёртым.
 */
const MAX_ROW = 3;

/**
 * Ряд и место в ряду для набора прямоугольников.
 *
 * @param {{ top: number, left: number }[]} boxes координаты в системе сетки
 * @returns {{ row: number, column: number }[]} по индексу входа
 */
export function assemblyOrder(boxes, options = {}) {
  const tolerance = options.rowTolerance ?? ROW_TOLERANCE;
  const maxRow = options.maxRow ?? MAX_ROW;

  /* Порядок разметки и порядок на экране — разные вещи: `order`, `dense` и
     обычный перенос строки переставляют карточки, поэтому сортируем по
     координатам, а не по индексу. */
  const sorted = boxes
    .map((box, index) => ({ index, top: box.top, left: box.left }))
    .sort((a, b) => a.top - b.top || a.left - b.left);

  const placed = new Array(boxes.length);
  let row = -1;
  let rowTop = Number.NEGATIVE_INFINITY;
  let column = 0;

  for (const item of sorted) {
    if (item.top - rowTop > tolerance) {
      row += 1;
      rowTop = item.top;
      column = 0;
    }
    placed[item.index] = { row: Math.min(row, maxRow), column };
    column += 1;
  }

  return placed;
}

export const ASSEMBLY_ROW_TOLERANCE = ROW_TOLERANCE;
export const ASSEMBLY_MAX_ROW = MAX_ROW;
