/*
 * «Животные» (05.11.2026) — отдельной карточкой в самом низу списка инструментов графики (слово владельца): ниже даже тех
 * плиток, которых нет в списке выше и которые по умолчанию встают в его хвост.
 */
export const WORKSHOP_EDITOR_BOTTOM_SLOTS = Object.freeze(["animals"]);

/*
 * Плитки, которым место в конце каталога.
 *
 * Интерьеры — самые тяжёлые вещи в списке и самые редкие: их ставят
 * готовым модом раз в жизнь, а ищут в каталоге чаще всё остальное. Полка
 * каталога идёт порядком таксономии, и они опускаются в её хвост. Арена
 * ушла отсюда к редакторам: у неё теперь свой.
 */
export const WORKSHOP_CATALOG_TAIL_SLOTS = Object.freeze([
  "interior",
  /* Мегамолл туда же: один торговый центр на всю карту ищут реже, чем
     дороги или значки, а редактора у него пока нет. */
  "mega-mall",
]);

/** Плитки редакторов в закреплённом порядке; незнакомые — в хвост, как были. */
export function orderWorkshopEditorSlots(slots) {
  const rank = new Map(
    WORKSHOP_EDITOR_SLOT_ORDER.map((id, index) => [id, index]),
  );
  const tail = WORKSHOP_EDITOR_SLOT_ORDER.length;
  return slots
    .map((slot, index) => ({
      slot,
      index,
      rank: WORKSHOP_EDITOR_BOTTOM_SLOTS.includes(slot.id) ? Number.MAX_SAFE_INTEGER : rank.has(slot.id) ? rank.get(slot.id) : tail + index,
    }))
    .sort((a, b) => a.rank - b.rank || a.index - b.index)
    .map(({ slot }) => slot);
}

/**
 * Делит плитки раздела на полку редакторов и полку каталога.
 *
 * `isEditor(slot)` — тот же вопрос, которым плитка открывается: если за ней
 * есть редактор, она на первой полке, иначе на второй. Порядок каталога —
 * порядок таксономии, порядок редакторов — закреплённый выше.
 */
export function splitWorkshopLibrarySlots(slots, isEditor) {
  const editors = [];
  const catalog = [];
  const tail = [];
  for (const slot of slots) {
    if (isEditor(slot)) editors.push(slot);
    else if (WORKSHOP_CATALOG_TAIL_SLOTS.includes(slot.id)) tail.push(slot);
    else catalog.push(slot);
  }
  return {
    editors: orderWorkshopEditorSlots(editors),
    catalog: [...catalog, ...tail],
  };
}
