/**
 * Слова раздела «Сборки» на языке окна.
 *
 * @param {string} language
 */
export function buildsCopyFor(language) {
  const lang = COPY[language] ? language : "en";
  const copy = COPY[lang];
  return {
    ...copy,
    ...buildContentsCopyFor(lang, copy),
    mods: (count) => modCount(lang, count),
    leavingText: (mods) =>
      copy.leaving(modList(lang, mods, copy.andMore, copy.quotes)),
    replacesBadgeText: (mods) =>
      copy.replacesBadge(modList(lang, mods, copy.andMore, copy.quotes)),
    replaceWarningText: (mods) =>
      copy.replaceWarning(modList(lang, mods, copy.andMore, copy.quotes)),
  };
}
