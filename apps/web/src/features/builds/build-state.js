/*
 * Стоит ли сборка в игре.
 *
 * Сборка стоит, когда в игре стоит каждый её мод. Ответ выводится из профиля
 * установки — того, что Astral прочитал с диска, — и нигде не запоминается.
 *
 * Раньше оболочка держала «активную сборку» отдельным полем, и оно врало на
 * каждом повороте: при входе в аккаунт «установленной» объявлялась первая
 * сборка в списке, в песочнице — захардкоженная `majestic`; метка загоралась,
 * как только установка вставала в очередь, а не когда кончалась; после
 * снятия модов из библиотеки или перезапуска окна она не гасла и не
 * возвращалась. Из профиля установки все три ответа получаются сами.
 *
 * Пустая сборка не стоит: «всё из ничего» — не повод для метки. Если одна
 * сборка целиком входит в другую, в игре стоят обе, и метки будут у обеих —
 * это правда о том, что лежит в GTA V.
 */
export function buildIsInstalled(build, installed) {
  /* Установки мастерской новая сборка держит отдельно от модов каталога
     (`engineIds`, задача 3 ТЗ 08.10, вечер): в `modIds` их больше нет, а
     сборка из одних работ тоже бывает «в игре». */
  const ids = [...(build?.modIds || []), ...(build?.engineIds || [])];
  if (!ids.length) return false;
  const present = installed instanceof Set ? installed : new Set(installed);
  return ids.every((modId) => present.has(modId));
}
