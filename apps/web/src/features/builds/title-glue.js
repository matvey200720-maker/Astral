/*
 * Название сборки в крупном заголовке («Одиночная · Кино»): точка-разделитель не должна оставаться в конце строки или начинаться новую. Пробелы вокруг «·»
 * заменяются неразрывными — «A · B» переносится целиком. Неразрывный пробел берётся кодом, а не набирается в исходнике: инструмент записи файла превращает
 * набранный escape в настоящий символ.
 */
const NO_BREAK_SPACE = String.fromCharCode(160);

export function gluedTitle(name) {
  return String(name ?? "").replace(
    /\s+·\s+/g,
    `${NO_BREAK_SPACE}·${NO_BREAK_SPACE}`,
  );
}
