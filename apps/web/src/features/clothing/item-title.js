import { itemName, shownItemName } from "@modovik/clothing/assortment";
import { currentUiLanguage, tr } from "../../locales/ui.js";

/*
 * Название вещи для окна на языке интерфейса (17.11.2026, решение владельца). Вещь игры называется так, как её называет сама GTA V на этом языке (`names` из таблиц языков игры,
 * `@modovik/clothing/game-names`); у вещи сервера, автора и каталога своё имя на любом языке. Нет строки игры — запасное название по типу вещи (`tr`).
 * `name` вещи остаётся русским: по нему окно группирует одинаковые вещи, поэтому язык в группировку не попадает.
 *
 * Язык — язык окна на момент вызова, как у `tr` (оболочка ставит его во время отрисовки), так что вызов можно держать прямо в отрисовке компонента, подписанного на язык (`useTr`).
 */

/** Название вещи: строка игры на языке окна, а нет её — слово вида, магазин, коллекция или номер (`itemName`). */
export const shownName = (item) => itemName(item, tr, currentUiLanguage());

/** Только строка игры (или своё имя вещи не игры) на языке окна; пусто — названия нет. */
export const shownGameName = (item) => shownItemName(item, currentUiLanguage());

/**
 * Вещь, на которую встанет заменёнка («Заменяет «…»» в окне «Установить комплект»): цель установки (`assortmentInstallTarget`) несёт названия игры и коллекцию, и называется тем же `itemName`, что и вещь списка, —
 * на языке окна. Цель без названий игры (сервер, автор) — своё имя на любом языке.
 */
export const shownTargetName = (target) => itemName(target, tr, currentUiLanguage());

const UPDATE_SHELF =/^Обновление (.+)$/;

/**
 * Полка вещи на языке окна. У вещи игры полка — дополнение (`DLC_TITLES` в `@modovik/pack-intake`: «Байкеры», «Ограбление казино», «Обновление 02.2023» — слова игроков, не строки игры); у вещи
 * сервера — магазин сервера, у него перевода нет и остаётся как есть. «Обновление 02.2023» — слово и дата.
 */
export function shownShop(shop) {
  const text = String(shop ?? "");
  const update = UPDATE_SHELF.exec(text);
  return update ? `${tr("Обновление")} ${update[1]}` : tr(text);
}
