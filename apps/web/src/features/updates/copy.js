function buildTree(language) {
  const tree = {
    heading: OFF_COPY[language].heading,
    off: OFF_COPY[language].off,
  };
  for (const [at, path] of PATHS.entries()) {
    const keys = path.split(".");
    let node = tree;
    for (let depth = 0; depth < keys.length - 1; depth += 1) {
      const key = keys[depth];
      if (!has(node, key)) node[key] = /^\d+$/.test(keys[depth + 1]) ? [] : {};
      node = node[key];
    }
    node[keys[keys.length - 1]] = TEXTS[language][at];
  }
  return tree;
}

const TREES = Object.fromEntries(
  LANGUAGES.map((language) => [language, buildTree(language)]),
);

export function updatesCopyFor(language) {
  return typeof language === "string" && has(TREES, language)
    ? TREES[language]
    : TREES.en;
}

export function errorCopy(copy, code) {
  const table = copy.errors;
  const pair = code != null && has(table, code) ? table[code] : undefined;
  return pair ?? table.DEFAULT;
}

export function reasonCopy(copy, reason) {
  const table = copy.failed.reasons;
  const text = reason != null && has(table, reason) ? table[reason] : undefined;
  return text ?? "";
}
