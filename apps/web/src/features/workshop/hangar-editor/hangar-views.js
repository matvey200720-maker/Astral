/*
 * Камера мастерской ангара по разделам (задача лида 1, 23.11.2026; проверка в настоящем окне показала: цвет труб и цвет комнаты в кадре работают, но камера на них не смотрит).
 * Пункт над панелью («Снаружи», «Внутри», «Конструкции») и разделы «Цвет труб» и «Комната» ведут камеру изнутри к тому, что правят: `hangarFocusFor(shot)` — поза перелёта `insideFocus` кадра
 * (`{ eye, yaw, pitch, fov, at }`: оси сцены, Z вверх, взгляд `(sin yaw·cos pitch, cos yaw·cos pitch, sin pitch)`, как у `flyInside`). Перелёт — один на вход в раздел (`at` — метка входа): правка цвета
 * камеру не трогает, а улетевшего в полёте человека к виду насильно не возвращают, пока он не сменил раздел (`HangarStudio.jsx`, `onFocusView`).
 *
 * Позы — по осям сцены ангара (центр (0, 0)), снятым с `scene.bin` окном и проверенным в настоящем Electron:
 *   трубы — синие трубы на стенах, скопления у (−33,3 13,9 6,3), (−30,2 20,0 0,9), (1,4 −38,7 8,5), (44,9 −0,8 6,9), (27,2 −22,5 4,3): глаз в зале у западной стороны, взгляд на северо-западную стену, где два скопления рядом;
 *   комната — повёрнутая на 45° комната у ВОСТОЧНОГО торца зала: коробка x 23,6…43,5, y −22,5…−0,2, потолок 2,8 м, ковёр x 27,8…36,5, y −18,2…−9,0: глаз (30,5; −14,5; 1,5) ВНУТРИ комнаты на высоте человека, взгляд
 *   на северо-восток (yaw π/4) и чуть вверх (0,21) — в кадре потолок, главная стена, ковёр и плитка пола. Поза подобрана в настоящем окне (проверяющий, снимок 52): прежняя (27; −11,3) оказалась СНАРУЖИ комнаты —
 *   она попадала в габариты коробки, а комната повёрнута, и габариты глаз не ловят; клетка `hangar-views-geometry.test.js` проверяет глаз по контуру пола сцены.
 */
import { HANGAR_VIEW } from "@modovik/climb-contract/recolor/hangar";

/* «Конструкции» щелчком над панелью: глаз тот же, что у вида «Внутри», взгляд поднят на фермы и кран (радианы). */
export const HANGAR_STRUCTURE_PITCH = 0.62;

/** Вид «Трубы»: стена с синими трубами. */
export const HANGAR_PIPES_VIEW = Object.freeze({ eye: Object.freeze([-17, 9, 2.8]), yaw: -1.212, pitch: 0.1, fov: 72 });
/** Вид «Комната»: изнутри комнаты, потолок, главная стена, ковёр и плитка пола в кадре. */
export const HANGAR_ROOM_VIEW = Object.freeze({ eye: Object.freeze([30.5, -14.5, 1.5]), yaw: Math.PI / 4, pitch: 0.21, fov: 72 });

/** Куда лететь камере изнутри по пункту `shot = { tool, at }`; `null` — камера стоит. */
export function hangarFocusFor(shot) {
  if (!shot) return null;
  const at = shot.at;
  switch (shot.tool) {
    case "inside":
      return { eye: HANGAR_VIEW.eye, yaw: HANGAR_VIEW.yaw, pitch: HANGAR_VIEW.pitch, fov: 72, at };
    case "structure":
      return { eye: HANGAR_VIEW.eye, yaw: HANGAR_VIEW.yaw, pitch: HANGAR_STRUCTURE_PITCH, fov: 72, at };
    case "pipes":
      return { ...HANGAR_PIPES_VIEW, at };
    case "room":
      return { ...HANGAR_ROOM_VIEW, at };
    default:
      return null;
  }
}
