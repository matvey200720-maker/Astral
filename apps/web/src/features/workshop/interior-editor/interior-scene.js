/**
 * Сцена интерьера по контракту окна превью.
 *
 * `onRoom` сообщает наружу, что стоит в кадре: `loading` — читаем зал из игры,
 * `game` — настоящий, `schematic` — игры рядом нет. Редактор по этому пишет
 * плашку, а не гадает по картинке.
 *
 * Остальные обработчики — про макет, и все до одного необязательны: сцену
 * поднимают и без редактора (стенд окна, витрина мода), и тогда она просто
 * показывает зал.
 *
 * @param {object} [options]
 * @param {Function} [options.onSelect] `(entityId|null)` — выбрали объект в зале.
 * @param {Function} [options.onPlace] `({propId, x, y})` — щёлкнули по полу,
 *   держа объект из каталога.
 * @param {Function} [options.onMove] `(entityId, {x, y, yaw})` — протяжка
 *   закончилась; зовётся ОДИН раз на жест, а не на каждое движение мыши.
 * @param {Function} [options.probe] `({entityId, propId, x, y}) =>
 *   {level, message}` — что скажет проверка макета, если объект встанет сюда.
 *   Ответ красит объект прямо под рукой, поэтому спрашивается на каждом шаге.
 * @param {Function} [options.onProbe] `({level, message}|null)` — то же самое
 *   словами, для плашки над кадром. Зовётся только когда ответ ИЗМЕНИЛСЯ:
 *   перерисовывать React на каждое движение мыши незачем.
 */
export function createInteriorScene(options = {}) {
  const hasGame =
    typeof options.hasGame === "function" ? options.hasGame : () => false;
  const onRoom = typeof options.onRoom === "function" ? options.onRoom : null;
  /*
   * Про предметы кадр отчитывается тем же способом, что и про помещение.
   *
   * Половина каталога, нарисованная коробками с именем на боку, — штатное
   * состояние без подключённой игры, и молчать о нём нельзя: человек видит
   * ровно одно — предметы не такие, как обещано, — и не знает, ждать ли модель
   * или у него что-то сломано.
   */
  const onProps =
    typeof options.onProps === "function" ? options.onProps : null;
  const loadGltfModule = options.loadGltfModule || loadGltfRuntime;
  const call =
    (name) =>
    (...args) =>
      options[name]?.(...args);
  const onSelect = call("onSelect");
  /*
   * Отделка: что в зале можно покрасить и что человек в нём выбрал щелчком.
   *
   * Список поверхностей приходит НАВЕРХ, а не задаётся сверху, и по-другому
   * быть не может: состав помещения лежит в файлах Rockstar, а не в реестре, и
   * до того, как модель приедет из игры, ни редактор, ни контракт не знают,
   * сколько у магазина стен и есть ли у него потолок.
   */
  const onSurfaces = call("onSurfaces");
  const onPickSurface = call("onPickSurface");
  const onPlace = call("onPlace");
  const onMove = call("onMove");
  const onProbe = call("onProbe");
  const probe = (request) =>
    typeof options.probe === "function" ? options.probe(request) : null;

  let ctx = null;
  let THREE = null;
  let root = null;
  /* Зал отдельной группой внутри корня: приехавшая из игры отделка заменяет
     схему целиком, а лампы и камера при этом остаются на месте. */
  let hall = null;
  let schematic = null;
  let lamps = [];
  let house = null;
  let mounted = false;
  /* Была ли игра в прошлом кадре: по смене этого признака повторяется заказ
     моделей предметов. */
  let hadGame = false;
  /* Где стоит приманка: по ней движение мыши в ту же клетку не пересчитывает
     ни проверку, ни кадр. Снимается вместе с самой приманкой. */
  let ghostAt = null;
  /* Поколение сцены: модель едет из игры асинхронно, а окно вправе закрыться
     раньше. Приехавшая в мёртвую сцену геометрия не видна никому и никем не
     освобождается. */
  let generation = 0;

  /*
   * Что сцена завела сама и обязана освободить: пол, стены и потолок ТЕКУЩЕЙ
   * схемы помещения.
   *
   * Список пересобирается вместе с комнатой, а не копится за сеанс. Комнату
   * меняют выбором локации, и лежи её геометрия в общем списке до закрытия
   * окна — десяток переключений оставил бы в куче десяток мёртвых коробок.
   *
   * Клоны моделей из игры сюда не попадают: `clone(true)` делит геометрию и
   * материалы с разобранным оригиналом, который живёт в кэше `interior-models`
   * и переживает закрытие окна. Освободить их отсюда значило бы отдать
   * следующему открытию редактора пустые буферы вершин.
   */
  let owned = [];
  /* Что сейчас стоит в зале: идентификатор модели -> добавленный клон. */
  const parts = new Map();

  /* ---------- отделка ---------- */

  /* Разобранный зал: поверхности, их материалы и клоны, которые надо освободить.
     Пересобирается на каждую смену состава — приехавшую деталь, поднятую схему,
     выбранный стиль. */
  let surfaceIndex = null;
  /* Состав зала изменился, и индекс устарел. Флагом, а не сразу: детали
     приезжают по одной, а разбирать зал ради каждой — считать нормали
     оболочки по нескольку раз на одно открытие редактора. */
  let surfacesStale = false;
  /* Что покрашено: записи макета из контракта, числа и строки. */
  let finish = [];
  /* Какую поверхность человек выбрал: она светится в кадре. */
  let highlighted = "";
  /* По чему покрашено в прошлый раз: макет приезжает новым массивом на каждую
     правку проекта, а перекрашивать зал из-за сдвинутого предмета незачем. */
  let finishKey = "";
  /* Картинки, принесённые человеком: ссылка -> текстура (или null, пока едет).
     Заводит их сцена, значит она же и освобождает. */
  const brought = new Map();
  const loadTexture =
    typeof options.loadTexture === "function" ? options.loadTexture : null;

  let selection = stockInteriorSelection();
  /*
   * Помещение, которое сейчас в кадре, — и то же самое, которое правят.
   *
   * До первой раскладки проекта нет, и это зал витрины: стенд окна и витрина
   * мода поднимают сцену без шаблона вовсе.
   */
  let room = FALLBACK_HALL;
  /* Размер помещения, по которому настроены камера, туман и лампы. */
  let extent = roomExtent(room);
  /* Состав, который уже заказан у игры. Раскладка и отделка приезжают из React
     порознь, и один и тот же набор незачем просить дважды. */
  let asked = "";
  /* Кадр строится один раз, по залу: переключение отделки не должно сбрасывать
     вид, который человек выбрал. Замысел автора зала, и он сохранён. */
  let framed = false;
  /* По чему был покрашен свет в прошлый раз: час приходит каждым кадром, а
     минута игрового времени в кадре ничего не меняет. */
  let paintKey = "";

  /* ---------- макет ---------- */

  let layout = normalizeLayout(EMPTY_LAYOUT);
  let plan = null;
  let layoutView = null;
  /* Объект из каталога, который сейчас ставят: под ним ходит приманка, а
     щелчок по полу превращает её в объект. Пусто — обычная работа с залом. */
  let armed = null;
  let viewMode = "inside";

  /* ---------- указатель ---------- */

  let canvas = null;
  let raycaster = null;
  let floorPlane = null;
  const pointer = { ndc: null, hit: null };
  /* Где нажали: по нему считается порог в пять пикселей. */
  let pointerStart = null;
  /* Идёт протяжка объекта: окно про этот жест не знает, орбита на нём стоит. */
  let drag = null;
  /* Что в прошлый раз сказала проверка — чтобы не дёргать React на каждый шаг.
     Начальное состояние — «всё в порядке»: плашка о молчании не сообщает. */
  let probed = QUIET;

  /* ---------- схематичный зал ---------- */

  function surface(kind, repeat) {
    const assets = ctx?.assets;
    if (typeof assets?.texture !== "function") return null;
    /* Текстура принадлежит набору окна: он один на все редакторы, он кэширует
       и он же освобождает. Отсюда её только берут. */
    return assets.texture(kind, {
      kind,
      repeat,
      onLoad: () => ctx?.requestRender?.(),
    });
  }

  /**
   * Схема помещения по числам его шаблона.
   *
   * Строится всегда, а не «когда игры рядом нет»: для комнат реестра игра
   * модели не отдаёт вовсе, и это единственное, что человек увидит. Сама
   * геометрия — в `interior-room.js`, чтобы её можно было померить числами, а не
   * картинкой; сюда возвращается готовая группа и список того, что она завела.
   */
  function buildShell() {
    const built = buildRoomShell(THREE, room, { surface });
    owned = built.owned;
    return built.group;
  }

  /** Поставить схему в зал заново — под новое помещение. */
  function raiseShell() {
    dropShell();
    schematic = buildShell();
    hall.add(schematic);
    releaseSurfaces();
  }

  /**
   * Снять схему и освободить её.
   *
   * Прежде снятая схема оставалась в общем `owned` до закрытия окна: она была
   * одна на весь сеанс, и держать её было дёшево. Теперь у каждого помещения
   * своя, и та же щедрость означала бы кучу мёртвых коробок к десятому
   * переключению локации. Собрать её обратно стоит одну коробку и один
   * прямоугольник — дешевле, чем помнить.
   */
  function dropShell() {
    if (schematic) releaseSurfaces();
    if (schematic) hall.remove(schematic);
    for (const item of owned) item?.dispose?.();
    owned = [];
    schematic = null;
  }

  /* ---------- свет ---------- */

  function buildLights() {
    /*
     * Четыре лампы по углам под потолком — так их поставил автор зала, и
     * причина та же: одна точка в центре оставляет углы чёрными, и зал кажется
     * меньше, чем есть. Места считаются по размеру зала, когда он загрузится.
     */
    lamps = [0, 1, 2, 3].map(() => {
      const lamp = new THREE.PointLight(0xffe6c2, 0, 90, 2);
      lamp.name = "interior-lamp";
      root.add(lamp);
      return lamp;
    });
    house = new THREE.PointLight(0xfff1de, 0, 90, 2);
    house.name = "interior-house-light";
    root.add(house);
    placeLights();
  }

  function placeLights() {
    const reach = extent.radius * 0.55;
    const lampY = Math.max(1.6, extent.height * 0.82);
    const spots = [
      [reach, lampY, reach],
      [-reach, lampY, reach],
      [reach, lampY, -reach],
      [-reach, lampY, -reach],
    ];
    lamps.forEach((lamp, index) => {
      lamp.position.set(...spots[index]);
      lamp.distance = extent.radius * 2.6;
    });
    if (house) {
      house.position.set(0, lampY - 0.4, 0);
      house.distance = extent.radius * 3.2;
    }
  }

  /**
   * Свет зала по часу кадра и по усилению окна.
   *
   * Усиление приходит готовым: искусственный свет обязан гореть в кадре
   * одинаково при любой экспозиции, какую бы окно ни выбрало по небу, а
   * диапазон экспозиции знает только окно. Своего потолка здесь нет и быть не
   * должно — прежний срабатывал ровно в полдень, лампы недосвечивали, и закат
   * выходил ярче полудня.
   */
  function refresh(gain, daylight) {
    if (!lamps.length) return;
    const guard = Number(gain) > 0 ? Number(gain) : 1;
    const day = clamp(Number(daylight) || 0, 0, 1);
    /* Помещение входит в ключ: у магазина потолок ниже вдвое, и та же лампа
       светит там иначе. Без него смена локации оставляла бы прежнюю яркость. */
    const scale = lampScale(room);
    const key = `${Math.round(guard * 1000)}|${Math.round(day * 100)}|${Math.round(scale * 1000)}`;
    if (key === paintKey) return;
    paintKey = key;

    for (const lamp of lamps) lamp.intensity = LAMP_CANDELA * scale * guard;
    if (house) {
      /*
       * Заливка — единственное, что зависит от часа.
       *
       * Днём освещённый снаружи зал переотражает свет во все стороны: этого не
       * даёт ни одна направленная лампа, а считать честное глобальное
       * освещение в реальном времени никто не станет. Отсюда и берётся часть
       * разницы между полуднем и полночью внутри зала — лампы горят одинаково,
       * а отражённого дневного света ночью просто нет.
       */
      house.intensity = HOUSE_CANDELA * (0.3 + day * 1.9) * scale * guard;
    }
  }

  /* ---------- камера ---------- */

  /**
   * Взгляд изнутри зала.
   *
   * Камерой распоряжается окно, сцена лишь сообщает ему, куда смотреть и с
   * какого расстояния. Своей орбиты здесь нет: вторые органы управления в том
   * же холсте означали бы, что колесо мыши крутит две камеры сразу.
   */
  /* Высота глаз в зале: чуть выше человеческого роста для просторного цеха и
     не ниже полутора метров для тесного. */
  const eyeHeight = () => clamp(extent.height * 0.28, 1.6, 2.4);

  /**
   * Взгляд и пределы отдаются окну одним вызовом.
   *
   * Камера наружу не выходит — это замысел автора зала. Раньше он держался
   * заплаткой: каждый кадр сцена проверяла расстояние и тянула камеру обратно.
   * Работало, но означало драку с собственным вводом человека на каждом кадре;
   * теперь предел знает орбита окна и держит его сама, ещё внутри колеса.
   */
  function frameCamera() {
    if (!ctx?.setOrbit) return;
    if (viewMode === "top") {
      ctx.setOrbit(topOrbit());
      return;
    }
    ctx.setOrbit({
      target: [0, eyeHeight(), 0],
      radius: Math.max(3, extent.radius * 0.48),
      yaw: 0.78,
      pitch: 0.18,
      /* Ближе — камера утыкается в пол, дальше — вылетает наружу сквозь
         стену, и вернуться, промотав колесо на пустоте, человек уже не
         догадается. */
      minRadius: 1.5,
      maxRadius: Math.max(3.4, extent.radius * 0.92),
      /* Пределы наклона возвращаются к заводским явно: взгляд сверху зажимает
         их почти в точку, и без этой строки возврат внутрь оставлял бы камеру
         смотреть в пол. */
      minPitch: 0.02,
      maxPitch: 1.42,
    });
  }

  /**
   * Взгляд сверху: почти отвесная орбита над серединой комнаты.
   *
   * Два числа спорят между собой, и спор решается в пользу первого.
   *
   * Первое — потолок. Камера, поднятая выше крыши, видит крышу: интерьер в игре
   * односторонний и рассчитан на взгляд изнутри. Поэтому предел расстояния
   * считается по высоте зала, а не по размеру комнаты.
   *
   * Второе — сама комната: чтобы она попала в кадр целиком, камере нужно
   * подняться на `половина глубины / tan(половина угла обзора)`. Замерено на
   * схематичном зале: восьмиметровый потолок даёт по полу 7.3 метра при
   * глубине комнаты 7.5 — верхний и нижний ряды объектов срезаются краями
   * кадра.
   *
   * Поэтому по умолчанию камера встаёт под крышей, а ПОТОЛОК КОЛЕСА поднят до
   * той высоты, с которой комната видна целиком. Так безопасный ракурс достаётся
   * даром, а недостающие полметра человек добирает сам — и если крыша его зала
   * смотрится насквозь (интерьеры GTA строят изнутри), он их получит.
   */
  function topOrbit() {
    /* Пол макета, а не помещение целиком: сверху в кадр обязана влезть та
       площадь, по которой расставляют. Имя своё, чтобы не путалось с `room` —
       помещением, у которого есть ещё и высота. */
    const floor = plan || { width: extent.radius, depth: extent.radius };
    const aspect = Math.max(0.5, Number(ctx?.camera?.aspect) || 1.6);
    /* Запас в 12%: комната, вписанная впритык, упирается в края кадра, и
       объект у стены оказывается наполовину за ним. */
    const fits =
      ((Math.max(floor.depth, floor.width / aspect) / 2) * 1.12) / HALF_FOV;
    const underRoof = extent.height * 0.94;
    const radius = Math.max(3, Math.min(fits, underRoof) / Math.sin(TOP_PITCH));
    return {
      target: [0, 0, 0],
      radius,
      yaw: 0,
      pitch: TOP_PITCH,
      minRadius: 3,
      maxRadius: Math.max(3.2, Math.max(fits, underRoof) / Math.sin(TOP_PITCH)),
      /* Наклон зажат, но не заперт: чуть отвести камеру от отвеса полезно —
         так видно высоту объектов, а не только их пятна на полу. */
      minPitch: TOP_PITCH_FLOOR,
      maxPitch: TOP_PITCH,
    };
  }

  /* ---------- помещение из игры ---------- */

  /**
   * Что грузить для помещения, которое сейчас правят.
   *
   * Два разных ответа за одним вопросом, и разница не в оформлении. У зала Auto
   * Shop состав СОБИРАЕТСЯ выбором человека: оболочка плюс по одному варианту
   * из каждой группы отделки. У комнаты реестра он ФИКСИРОВАН: Rockstar
   * сложила магазин 24/7 из восьми drawable раз и навсегда, переключать в нём
   * нечего, и выбор отделки к нему не относится вовсе.
   *
   * Пусто — законный ответ: помещение может быть незнакомым (стенд поднимает
   * сцену без шаблона), и тогда его рисует схема.
   */
  function wantedParts() {
    const available = gameRoomParts(room.id);
    if (!available) return [];
    if (available.parts) return available.parts.map((part) => part.id);
    return [available.shell, ...Object.values(selection).filter(Boolean)];
  }

  /**
   * Где стоит каждая часть помещения — в координатах кадра.
   *
   * Пусто у зала Auto Shop: его части лежат в мировых координатах карты, и в
   * кадр их приводит `measureHall`, сводя весь зал по его собственной коробке.
   *
   * У комнаты реестра сводить нечего и НЕЛЬЗЯ. Её части приезжают с местами из
   * `v_int_*.ytyp` — в той же системе координат, в которой человек расставляет
   * предметы, и в той же, которую компилятор кладёт в YMAP. Значит и в кадр их
   * переводит то же `worldPoint`, что и предметы. Сведи мы комнату по её
   * коробке — оболочка захватывает и заднюю комнату, и торговый зал уехал бы
   * на пару метров от разметки, которую человек правит.
   */
  function partPlacement() {
    const available = gameRoomParts(room.id);
    if (!available?.parts) return null;
    return new Map(
      available.parts.map((part) => {
        const [x, z] = worldPoint(plan, part.x, part.y);
        /* Высота идёт как есть: пол помещения и в игре, и в кадре лежит на
           нуле. */
        return [part.id, { x, y: part.z, z }];
      }),
    );
  }

  function requestParts() {
    const wanted = wantedParts();
    /* Помещение входит в ключ: у разных комнат разный состав, и состав пустой
       тоже надо уметь заказать ровно один раз. */
    const signature = `${room.id}|${wanted.join("|")}`;
    if (signature === asked) return;
    asked = signature;

    if (!wanted.length) {
      stripParts();
      onRoom?.({
        status: "schematic",
        reason: tr("Игра не отдаёт это помещение отдельной моделью."),
      });
      return;
    }
    if (!hasGame()) {
      stripParts();
      onRoom?.({
        status: "schematic",
        reason: tr("Помещение читается из игры только в Astral Desktop."),
      });
      return;
    }
    const mine = generation;
    /*
     * Помещение сверяется вместе с поколением: раскладка проекта приезжает
     * ПОСЛЕ `mount`, и заказанный на витринном зале Auto Shop успевает уехать в
     * игру раньше, чем выяснится, что правят магазин. Приехав, он встал бы в
     * комнату на одиннадцать метров сорокаметровой моделью.
     */
    const ordered = room;
    const alive = () => mounted && generation === mine && room === ordered;
    onRoom?.({ status: "loading", reason: "" });

    void loadGltfModule()
      .then(async (gltf) =>
        Promise.all(
          wanted.map(async (id) => [
            id,
            (await loadInteriorPart(THREE, gltf.GLTFLoader, id))?.model || null,
          ]),
        ),
      )
      .then((loaded) => {
        if (!alive()) return;
        attach(wanted, loaded);
      })
      .catch((error) => {
        if (!alive()) return;
        /* Заказ снимается: неудачное чтение обязано повторяться по нажатию,
           иначе тот же вариант больше не попросить вовсе. */
        asked = "";
        onRoom?.({
          status: "schematic",
          reason: String(error?.message || error),
        });
      });
  }

  /** Переставить отделку: лишнее снять, недостающее добавить. */
  function attach(wanted, loaded) {
    const keepIds = new Set(wanted);
    for (const [id, object] of [...parts]) {
      if (keepIds.has(id)) continue;
      hall.remove(object);
      parts.delete(id);
    }

    const placement = partPlacement();
    let added = 0;
    for (const [id, model] of loaded) {
      if (!model || parts.has(id)) continue;
      /* Клон, а не сама модель: разобранная модель живёт в кэше и достаётся
         следующему открытию редактора — переключение отделки не должно заново
         тянуть и парсить десяток мегабайт. */
      const clone = model.clone(true);
      const spot = placement?.get(id);
      if (spot) clone.position.set(spot.x, spot.y, spot.z);
      hall.add(clone);
      parts.set(id, clone);
      added += 1;
    }

    if (!parts.size) {
      asked = "";
      onRoom?.({
        status: "schematic",
        reason: tr("Модель помещения из игры недоступна."),
      });
      return;
    }

    dropShell();
    if (added) releaseSurfaces();
    if (added && !framed) {
      if (placement) placeHall();
      else measureHall();
    }
    onRoom?.({ status: "game", reason: "" });
    ctx?.requestRender?.();
  }

  /**
   * Снять модель из игры и вернуть схему.
   *
   * Нужно ровно там, где помещение сменилось на то, которого игра не отдаёт:
   * человек выбрал магазин, а в зале стоит приехавший Auto Shop. Снять его
   * мало — `measureHall` успел сдвинуть зал по своим мировым координатам, и
   * схема, поставленная в тот же зал, уехала бы вместе с ним.
   */
  function stripParts() {
    for (const [, object] of parts) hall.remove(object);
    /* Клоны не освобождаются: геометрию и материалы они делят с разобранным
       оригиналом в кэше `interior-models`, а он переживает закрытие окна. */
    if (parts.size) releaseSurfaces();
    parts.clear();
    hall.position.set(0, 0, 0);
    framed = false;
    if (!schematic) raiseShell();
  }

  /* ---------- отделка ---------- */

  /**
   * Состав зала изменился: старый разбор больше не про него.
   *
   * Клоны материалов освобождаются СРАЗУ, а не вместе с новым разбором в
   * ближайшем кадре. Разница в том, кто держит буферы снятой отделки: отпущенный
   * в кадре клон живёт до следующего кадра, а кадра может и не быть — окно
   * рисует по требованию, и человек, закрывший редактор в тот же миг, оставил бы
   * их за собой.
   */
  function releaseSurfaces() {
    disposeInteriorSurfaces(surfaceIndex);
    surfaceIndex = null;
    surfacesStale = true;
  }

  /**
   * Разобрать зал на поверхности заново и покрасить их по макету.
   *
   * Зовётся один раз на смену состава: приехала деталь, поднялась схема,
   * переключили стиль. Разбор стоит прохода по мешам и по нормалям, а состав
   * меняется редко — в отличие от самой покраски, которая идёт на каждое
   * движение пипетки.
   */
  function reindexSurfaces() {
    releaseSurfaces();
    /*
     * Флаг снимается ПОСЛЕ освобождения, а не до: освобождение его само и
     * поднимает — оно ведь означает «разбора больше нет». Сними его раньше, и
     * зал разбирался бы заново каждый кадр: проход по мешам, нормалям и
     * габаритам оболочки шестьдесят раз в секунду ради ответа, который не
     * менялся.
     */
    surfacesStale = false;
    if (!mounted || !THREE) return;

    const sources = [];
    /* Схема идёт первой и под собственным именем `room`: без установленной игры
       красить в редакторе больше нечего, и панель отделки обязана работать
       ровно так же. */
    if (schematic)
      sources.push({ id: "room", label: tr("Помещение"), object: schematic });
    for (const [id, object] of parts)
      sources.push({ id, label: partLabel(room.id, id), object });

    surfaceIndex = indexInteriorSurfaces(THREE, sources);
    paint();
    onSurfaces(describeInteriorSurfaces(surfaceIndex));
  }

  /** Положить на поверхности выбранные цвета и текстуры. */
  function paint() {
    if (!surfaceIndex) return;
    paintInteriorSurfaces(surfaceIndex, finish, {
      textureFor,
      highlight: highlighted,
    });
    ctx?.requestRender?.();
  }

  /**
   * Картинка, принесённая человеком, — текстурой кадра.
   *
   * Читает её окно (файл лежит в хранилище мастерской, а не в игре), поэтому
   * ответ приходит не сразу: первый спрос отдаёт пустоту и заказывает картинку,
   * а приехавшая перекрашивает зал сама. Пустая запись в карте — это «уже
   * спросили»: без неё каждый кадр заказывал бы одно и то же заново.
   */
  function textureFor(reference) {
    if (brought.has(reference)) return brought.get(reference);
    brought.set(reference, null);
    if (!loadTexture) return null;
    const mine = generation;
    void Promise.resolve(loadTexture(reference))
      .then((image) => {
        if (!image || !mounted || generation !== mine) return;
        const texture = new THREE.Texture(image);
        texture.colorSpace = THREE.SRGBColorSpace;
        texture.wrapS = THREE.RepeatWrapping;
        texture.wrapT = THREE.RepeatWrapping;
        /* Своя картинка ложится на ту же развёртку, что и текстура Rockstar:
           повторение по ней уже посчитано самой моделью. */
        texture.needsUpdate = true;
        brought.set(reference, texture);
        paint();
      })
      .catch(() => {
        /* Не прочиталась — поверхность останется такой, как в игре. Кричать
           отсюда некому: окно про эту картинку узнало от самого человека и
           покажет отказ там, где он её выбирал. */
      });
    return null;
  }

  /** Поверхность под указателем: щелчок по стене выбирает стену. */
  function surfaceUnder(event) {
    if (!surfaceIndex || !hall) return "";
    for (const hit of aim(event).intersectObject(hall, true)) {
      const found = surfaceIndex.byMesh.get(hit.object);
      if (found) return found.id;
    }
    return "";
  }

  /**
   * Разобрать зал по размеру: поставить его на пол, свести в центр и настроить
   * по нему камеру, лампы, туман и коробку теней.
   *
   * Один раз за сеанс, по первой приехавшей отделке: у карт GTA координаты
   * мировые, и без переноса зал оказался бы в километрах от камеры, — но
   * повторный разбор на каждой смене стиля сбрасывал бы вид, который человек
   * выбрал.
   */
  /**
   * Разобрать помещение, части которого уже стоят по своим местам.
   *
   * Отличается от `measureHall` ровно тем, что НИЧЕГО не двигает. Размер берётся
   * из шаблона комнаты, а не из коробки приехавшей геометрии: оболочка магазина
   * 24/7 — это весь MLO, вместе с подсобкой за стеной, и по её коробке камера
   * встала бы на помещение в полтора раза больше правимого.
   */
  function placeHall() {
    hall.position.set(0, 0, 0);
    extent = roomExtent(room);
    framed = true;
    placeLights();
    applyScale();
    frameCamera();
  }

  function measureHall() {
    const bounds = new THREE.Box3().setFromObject(hall);
    if (bounds.isEmpty()) return;
    const size = bounds.getSize(new THREE.Vector3());
    const centre = bounds.getCenter(new THREE.Vector3());
    hall.position.sub(new THREE.Vector3(centre.x, bounds.min.y, centre.z));
    extent = {
      radius: Math.max(size.x, size.z) / 2,
      height: size.y,
      halfWidth: size.x / 2,
      halfDepth: size.z / 2,
    };
    framed = true;
    placeLights();
    applyScale();
    frameCamera();
  }

  /**
   * Масштаб мира — окну.
   *
   * Туман окна рассчитан на город: сотни метров. Зал сорок метров поперёк, и
   * городская дальность кладёт на дальнюю стену молочную пелену там, где
   * должен быть бетон с износом. Воздух в зале есть, но его на два порядка
   * меньше, чем на улице, — отсюда щедрая дальность, а не свой цвет тумана:
   * цвет остаётся окну, иначе на дальнем краю появится шов.
   */
  function applyScale() {
    ctx?.setFogRange?.(
      Math.max(6, extent.radius * 0.4),
      Math.max(180, extent.radius * 12),
    );
    /* Коробка теней по умолчанию рассчитана на квартал, семьдесят метров. Зал
       занимает из них двадцать, и три четверти карты уходит на пустоту —
       сузить её значит получить более резкую тень колонны бесплатно. */
    ctx?.setShadowExtent?.(clamp(extent.radius * 1.4, 12, 120));
    /*
     * Коробка полёта — та же комната, чуть у́же её стен.
     *
     * Свободная камера, вышедшая наружу, показывает изнанку: интерьеры игры
     * односторонние и рассчитаны на взгляд изнутри. Держать её внутри дешевле,
     * чем объяснять, почему за стеной пусто.
     */
    const halfWidth = extent.halfWidth ?? extent.radius;
    const halfDepth = extent.halfDepth ?? extent.radius;
    ctx?.setFlyBounds?.({
      min: [-halfWidth * 0.92, 0.35, -halfDepth * 0.92],
      max: [
        halfWidth * 0.92,
        Math.max(1.2, extent.height * 0.88),
        halfDepth * 0.92,
      ],
    });
  }

  /* ---------- макет ---------- */

  /*
   * Что известно про модели предметов: сколько типов приехало из игры, сколько
   * осталось коробками и почему. Считается здесь, а не в React: заказ модели
   * живёт в сцене, и второй счётчик рядом разошёлся бы с первым.
   */
  const modelState = new Map();
  let modelReason = "";

  function noteModel({ archetype, status, reason }) {
    modelState.set(archetype, status === "ready");
    if (status !== "ready" && reason) modelReason = reason;
    const ready = [...modelState.values()].filter(Boolean).length;
    const total = modelState.size;
    onProps?.({
      ready,
      total,
      /* Пока не приехал ни один тип — «читаем»; причина появляется только
         тогда, когда её действительно есть кому объяснить. */
      status: ready === total ? "game" : ready ? "partial" : "placeholder",
      reason: ready === total ? "" : modelReason,
    });
  }

  /**
   * Настоящая модель объекта из игры — если нативный хост её знает.
   *
   * Возвращает тот же `{ model, status, reason }`, что и загрузчик: причина
   * нужна кадру, чтобы сказать, почему предмет остался коробкой.
   */
  function requestPropModel(archetype) {
    if (!hasGame())
      return Promise.resolve({
        model: null,
        status: "missing",
        reason: tr("Папка GTA V не выбрана, читать модели неоткуда."),
      });
    const mine = generation;
    return loadGltfModule()
      .then((gltf) => loadInteriorPart(THREE, gltf.GLTFLoader, archetype))
      .then((answer) =>
        mounted && generation === mine
          ? answer
          : { model: null, status: "missing", reason: "" },
      )
      .catch((error) => ({
        model: null,
        status: "missing",
        reason: String(error?.message || error),
      }));
  }

  /**
   * Помещение в кадре — по шаблону раскладки.
   *
   * Зовётся на каждую правку макета, а срабатывает только на смену локации:
   * пересобирать стены, свет и кадр, пока человек двигает урну, значит вырывать
   * у него из-под руки то, что он держит.
   *
   * @returns {boolean} Помещение сменилось — кадр уже пересобран.
   */
  function applyRoom() {
    const next = frameRoom(plan, layout.zones, layout.roomId);
    if (
      next.id === room.id &&
      next.width === room.width &&
      next.depth === room.depth &&
      next.height === room.height
    )
      return false;

    room = next;
    extent = roomExtent(room);
    /*
     * Разбор кадра начинается заново, и перенос зала сбрасывается вместе с ним.
     *
     * Зал витрины `measureHall` сводит по его собственной коробке — то есть
     * двигает всю группу. Помещение проекта переносить не нужно вовсе: его
     * части приезжают с местами. Останься перенос от прежнего зала, новое
     * помещение встало бы на его смещение — а это метры.
     */
    hall.position.set(0, 0, 0);
    framed = false;
    /* Свет считается по новому потолку: без сброса ключа прежняя яркость
       осталась бы до первой смены часа. */
    paintKey = "";
    if (!parts.size) raiseShell();
    placeLights();
    applyScale();
    frameCamera();
    return true;
  }

  function applyLayout() {
    const before = plan;
    plan = createFloorPlan(layout.room);
    const rebuilt = applyRoom();
    layoutView?.setLayout(layout);
    /* Состав моделей у нового помещения другой — вплоть до пустого. */
    if (rebuilt) requestParts();
    /*
     * Взгляд сверху построен по размерам комнаты, и сменившаяся комната обязана
     * его пересобрать. Но только сменившаяся: раскладка приезжает на каждую
     * правку макета, и безусловный вызов сбрасывал бы поворот и приближение
     * ровно тогда, когда человек двигает объект.
     */
    if (!rebuilt && viewMode === "top" && roomChanged(before, plan))
      frameCamera();
    /* Раскладка приезжает из React и во время протяжки тоже — например, когда
       выбор объекта уже доехал до списка. Позицию под рукой она при этом
       перебивать не должна: человек её сейчас и держит. */
    if (drag) {
      layoutView?.moveEntity(drag.id, {
        x: drag.x,
        y: drag.y,
        yaw: drag.yaw,
        level: drag.level,
      });
    }
    ctx?.requestRender?.();
  }

  const entityById = (id) =>
    layout.entities.find((entity) => entity.id === id) || null;

  /*
   * Размер типа предмета: по нему точка под указателем удерживается в комнате.
   * Неизвестный тип отдаёт ноль — это «удерживать не по чему», а не «предмет
   * размером с точку»: в раскладке объекта без типа не бывает
   * (`normalizeLayout` их отбрасывает), но сцену поднимают и стендом.
   */
  const propSizeOf = (propId) => {
    const prop = layout.props.find((item) => item.id === propId) || null;
    return prop ? { width: prop.width, depth: prop.depth } : null;
  };

  const roomChanged = (before, after) => {
    if (!before || !after) return before !== after;
    return before.width !== after.width || before.depth !== after.depth;
  };

  /* ---------- указатель ---------- */

  /*
   * «Этот жест наш».
   *
   * `ctx.claimPointer` — способ окна: заявленный указатель окно пропускает
   * целиком, от нажатия до отпускания и вместе с колесом, даже если орбита на
   * нём уже успела начаться. Заявляется только попадание в объект — щелчок по
   * пустому полу так и остаётся орбитой.
   *
   * `stopImmediatePropagation` — про соседей по холсту, а не про окно: на общем
   * узле обычная остановка не останавливает никого, а жест, у которого есть
   * хозяин, не должен доехать ни до чьего чужого слушателя.
   */
  function claim(event) {
    event.stopImmediatePropagation();
    ctx?.claimPointer?.(event);
  }

  function aim(event) {
    const box = canvas.getBoundingClientRect();
    pointer.ndc.set(
      ((event.clientX - box.left) / (box.width || 1)) * 2 - 1,
      -((event.clientY - box.top) / (box.height || 1)) * 2 + 1,
    );
    raycaster.setFromCamera(pointer.ndc, ctx.camera);
    return raycaster;
  }

  /**
   * Точка пола под указателем — уже в координатах макета, по сетке и в комнате.
   *
   * `placement` описывает ставимый предмет: размер, поворот и захват. С ним
   * возвращается середина предмета, удержанная стенами комнаты; без него —
   * голая точка пола. Второе нужно ровно один раз, в начале протяжки, чтобы
   * измерить, за какое место предмет взяли.
   */
  function floorUnder(event, placement = null) {
    const ray = aim(event).ray;
    const hit =
      ray.intersectPlane(floorPlane, pointer.hit) || aboveHorizon(ray);
    if (!hit) return null;
    return pickPoint(plan, hit.x, hit.z, layout.snap, placement);
  }

  /*
   * Точка «пола» для луча, ушедшего выше горизонта.
   *
   * Вид изнутри стоит почти горизонтально, и верхняя треть кадра — это небо:
   * пола под указателем там нет, `intersectPlane` отвечает пустотой, и
   * протяжка замирала. Предмет вставал, мышь ехала дальше, и почему он не
   * двигается — неоткуда узнать.
   *
   * Взамен берётся направление взгляда по горизонтали, отложенное далеко
   * вперёд: предмет уезжает в ту сторону, куда ведут, а стены комнаты сами
   * прижимают его к дальней стене. Рука при этом ведёт себя одинаково по всему
   * кадру.
   */
  const FAR_FLOOR = 500;
  function aboveHorizon(ray) {
    const flat = pointer.far.set(ray.direction.x, 0, ray.direction.z);
    if (flat.lengthSq() < 1e-8) return null;
    return flat.normalize().multiplyScalar(FAR_FLOOR).add(ray.origin);
  }

  /**
   * Куда встанет предмет, которого сейчас держат.
   *
   * Отдельной функцией, потому что зовут её и на движении мыши, и на повороте
   * колесом: повёрнутый предмет занимает больше места, и у самой стены поворот
   * обязан отодвинуть его от неё, а не утопить в ней.
   */
  const heldPlacement = (gesture) => ({
    ...(propSizeOf(gesture.propId) || {}),
    yaw: gesture.yaw,
    grabX: gesture.grabX,
    grabY: gesture.grabY,
  });

  /** Что скажет проверка, если объект встанет сюда. Красит объект и плашку. */
  function ask(request) {
    const answer = probe(request) || null;
    const level =
      answer?.level === "error" || answer?.level === "warn"
        ? answer.level
        : "ok";
    const message = answer?.message || "";
    const key = `${level}|${message}`;
    if (key !== probed) {
      probed = key;
      onProbe(level === "ok" ? null : { level, message });
    }
    return level;
  }

  function clearProbe() {
    if (probed === QUIET) return;
    probed = QUIET;
    onProbe(null);
    layoutView?.markZone("ok");
  }

  function onPointerDown(event) {
    if (!canvas || event.target !== canvas || event.button !== 0) return;
    pointerStart = [event.clientX, event.clientY];
    /* Пока в руке объект из каталога, протяжка остаётся орбитой: ставят
       щелчком, а разглядывать зал перед постановкой надо тем же движением, что
       и всегда. */
    if (armed) return;

    const id = layoutView?.hitTest(aim(event)) || null;
    if (!id) return;
    onSelect(id);
    const entity = entityById(id);
    if (!entity || entity.locked) return;

    const point = floorUnder(event);
    if (!point) return;
    /* Дальше объект едет за рукой — жест наш до самого отпускания. */
    claim(event);
    drag = {
      id,
      propId: entity.propId,
      /* Захват за точку, а не за середину: объект, прыгающий центром под
         курсор, уезжает из-под руки на полметра в первый же миг. */
      grabX: point.x - entity.x,
      grabY: point.y - entity.y,
      x: entity.x,
      y: entity.y,
      yaw: entity.yaw,
      level: entity.level,
      moved: false,
      turned: false,
      pointerId: event.pointerId,
    };
    try {
      canvas.setPointerCapture(event.pointerId);
    } catch {
      /* Указатель уже отпущен — протяжка доработает через события документа. */
    }
  }

  function onPointerMove(event) {
    if (drag) {
      const point = floorUnder(event, heldPlacement(drag));
      if (!point) return;
      /* Указатель уже заявлен на нажатии — здесь остаётся только не пустить
         жест к соседям по холсту (см. `claim`). */
      event.stopImmediatePropagation();
      /*
       * Та же клетка — та же картинка.
       *
       * Привязка в четверть метра на комнате в одиннадцать метров — это около
       * двадцати пикселей кадра: девятнадцать движений мыши из двадцати
       * попадают туда же, где предмет уже стоит. Каждое из них стоило полной
       * проверки макета (попарные сравнения всех предметов), записи матриц и
       * заказанного кадра — ради ответа, который не изменился.
       */
      if (point.x === drag.x && point.y === drag.y) return;
      /* Захват вычтен и стены применены внутри `pickPoint`: вычитать его после
         обрезки значило бы снова выпустить предмет наружу — ровно на то
         расстояние, за какое место его взяли. */
      drag.x = point.x;
      drag.y = point.y;
      drag.moved = true;
      drag.level = ask({ entityId: drag.id, propId: drag.propId, ...drag });
      layoutView?.moveEntity(drag.id, {
        x: drag.x,
        y: drag.y,
        level: drag.level,
      });
      layoutView?.markZone(drag.level);
      ctx?.requestRender?.();
      return;
    }
    if (!armed || !canvas || event.target !== canvas) return;
    /* Приманка удерживается так же, как сам предмет: иначе она показывала бы
       точку, в которую предмет потом не встанет. */
    const point = floorUnder(event, { ...(propSizeOf(armed) || {}), yaw: 0 });
    if (!point) return;
    /* И та же клетка, что и в протяжке: приманка стоит на сетке, а мышь ходит
       по пикселям. */
    if (ghostAt && ghostAt.x === point.x && ghostAt.y === point.y) return;
    ghostAt = point;
    const level = ask({ propId: armed, ...point });
    layoutView?.setGhost({ propId: armed, ...point, level });
    layoutView?.markZone(level);
    ctx?.requestRender?.();
  }

  function onPointerUp(event) {
    const start = pointerStart;
    const gesture = drag;
    pointerStart = null;
    drag = null;

    if (gesture) {
      /* Заявку окно снимает само — на отпускании, где бы оно ни случилось.
         Здесь, как и в протяжке, остаются одни соседи по холсту. */
      event.stopImmediatePropagation();
      try {
        canvas?.releasePointerCapture?.(gesture.pointerId);
      } catch {
        /* см. выше */
      }
      clearProbe();
      if (gesture.moved || gesture.turned) {
        onMove(gesture.id, { x: gesture.x, y: gesture.y, yaw: gesture.yaw });
      }
      return;
    }
    if (!start || !canvas || event.target !== canvas) return;
    /*
     * Щелчок — это щелчок, а не конец вращения. Орбитой сцену водит окно тем же
     * указателем, и без порога любое разглядывание зала заканчивалось бы
     * выбором случайного объекта.
     */
    const slop = Math.hypot(event.clientX - start[0], event.clientY - start[1]);
    if (slop > POINTER_SLOP) return;

    if (armed) {
      const point = floorUnder(event, { ...(propSizeOf(armed) || {}), yaw: 0 });
      if (point) onPlace({ propId: armed, ...point });
      return;
    }
    const hit = layoutView?.hitTest(aim(event)) || null;
    onSelect(hit);
    /* Мимо предмета — значит по самому помещению: щелчок по стене выбирает
       стену. Это единственный способ ткнуть в поверхность, у которой нет
       говорящего имени: список слева называет её «поверхность 4», а глазами
       человек видит ровно ту стену, в которую ткнул. */
    if (!hit) onPickSurface(surfaceUnder(event));
  }

  /**
   * Колесо поворачивает объект — но только пока его держат.
   *
   * Без этого условия колесо перестало бы быть увеличением ровно там, где
   * указатель случайно оказался над объектом. Тот же поворот лежит ручкой в
   * инспекторе и клавишей: жест здесь — короткий путь, а не единственный.
   */
  function onWheel(event) {
    if (!drag || !canvas || event.target !== canvas) return;
    /* Пока жест заявлен, окно колесом не приближается само — остаются соседи
       по холсту и прокрутка страницы. */
    event.stopImmediatePropagation();
    event.preventDefault();
    const step = layout.rotationSnap || 45;
    drag.yaw = drag.yaw + (event.deltaY > 0 ? step : -step);
    drag.turned = true;
    /* Повёрнутый предмет занимает больше места: у самой стены поворот обязан
       отодвинуть его от неё, а не утопить в ней углом. */
    const held = holdInRoom(plan, {
      x: drag.x,
      y: drag.y,
      yaw: drag.yaw,
      ...(propSizeOf(drag.propId) || {}),
    });
    drag.moved = drag.moved || held.x !== drag.x || held.y !== drag.y;
    drag.x = held.x;
    drag.y = held.y;
    drag.level = ask({ entityId: drag.id, propId: drag.propId, ...drag });
    layoutView?.moveEntity(drag.id, {
      x: drag.x,
      y: drag.y,
      yaw: drag.yaw,
      level: drag.level,
    });
    layoutView?.markZone(drag.level);
    ctx?.requestRender?.();
  }

  function listen(on) {
    if (!canvas) return;
    const method = on ? "addEventListener" : "removeEventListener";
    /*
     * Холст, а не документ: за пределами кадра сцене ловить нечего, а протяжку,
     * ушедшую за край, приводит обратно захват указателя (`setPointerCapture`)
     * — события с этим указателем браузер шлёт холсту, где бы ни была мышь.
     */
    canvas[method]("pointerdown", onPointerDown);
    canvas[method]("pointermove", onPointerMove);
    canvas[method]("pointerup", onPointerUp);
    canvas[method]("pointercancel", onPointerUp);
    canvas[method]("wheel", onWheel, { passive: false });
    /* Колесо над кадром зала — приближение камеры (а при заявленном жесте — поворот предмета): метка для правила `scroll`. */
    if (method === "addEventListener") markWheel(canvas);
  }

  /* ---------- контракт окна ---------- */

  function mount(context) {
    ctx = context;
    THREE = context.THREE;
    generation += 1;
    paintKey = "";
    framed = false;
    asked = "";
    /* Раскладка проекта приезжает после `mount` — до неё в кадре зал витрины. */
    room = FALLBACK_HALL;
    extent = roomExtent(room);

    root = new THREE.Group();
    root.name = "astral-interior";
    /*
     * Переходник — на самом корне сцены.
     *
     * Стенд окна (`dev/preview-lab`) поднимает сцену сам и наружу отдаёт только
     * контекст: адаптера у него на руках нет. Без этой строки макет на стенде
     * не посмотреть вовсе — а зал с макетом, который нельзя увидеть глазами,
     * чинится вслепую. Ссылка на объект, который и так живёт ровно столько же,
     * сколько корень, ничего не стоит.
     */
    root.userData.scene = api;
    hall = new THREE.Group();
    hall.name = "interior-hall";
    root.add(hall);

    /* Схему поднимает `applyLayout` ниже — по той комнате, которую правят.
       Строить её здесь значило собрать зал витрины сорок на тридцать два, чтобы
       в том же такте выбросить его и собрать магазин: две геометрии, два
       набора материалов и два прогона шума текстуры (по четыре миллисекунды на
       каждую) синхронно до первого кадра. Схема всё равно встанет сразу —
       пустой кадр в ожидании неотличим от сломанного редактора. */

    buildLights();
    context.scene.add(root);

    /* Макет живёт прямым ребёнком корня, а не внутри зала: зал приезжает из
       игры и переставляется целиком, а расставленное человеком при этом должно
       остаться на месте. */
    layoutView = createLayoutView({
      THREE,
      root,
      requestModel: requestPropModel,
      onModel: noteModel,
      onChanged: () => ctx?.requestRender?.(),
    });

    canvas = context.renderer?.domElement || null;
    raycaster = new THREE.Raycaster();
    pointer.ndc = new THREE.Vector2();
    pointer.hit = new THREE.Vector3();
    /* Запасная точка для луча выше горизонта: своя, чтобы не затирать ту, в
       которую пишет `intersectPlane`. */
    pointer.far = new THREE.Vector3();
    /* Пол зала лежит на нуле: `measureHall` ставит на него нижнюю грань
       приехавшей модели, а схема строится от нуля сама. */
    floorPlane = new THREE.Plane(new THREE.Vector3(0, 1, 0), 0);
    listen(true);

    applyScale();
    frameCamera();

    mounted = true;
    applyLayout();
    /* Раскладки может не быть вовсе (стенд окна, витрина мода) или её комната
       может совпасть с залом по размеру — тогда `applyRoom` выходит рано и
       схему не поднимает. Кадр без зала выглядит поломкой, поэтому здесь
       последняя проверка. */
    if (!schematic && !parts.size) raiseShell();
    requestParts();
  }

  function update(context, frame = {}) {
    if (!mounted) return;
    ctx = context || ctx;

    const base = frame.lighting;

    /*
     * Солнце и заливка окна приглушаются под крышей.
     *
     * Базовые значения берутся из кадра, а не из самих источников: свет в них
     * правит и окно, и мы, и читать оттуда своё же прошлое значение — верный
     * способ загнать яркость в лавину за десяток кадров.
     */
    if (base?.key && ctx?.sun) {
      ctx.sun.intensity = base.key.intensity * SUN_THROUGH_ROOF;
    }
    if (base?.ambient && ctx?.ambient) {
      ctx.ambient.intensity = base.ambient.intensity * AMBIENT_UNDER_ROOF;
    }

    refresh(frame.interiorGain, base?.daylight);

    /* Состав зала мог смениться между кадрами: деталь приехала из игры,
       поднялась схема, переключили стиль. Разбор идёт здесь, одним разом на
       все накопившиеся правки, а не по разу на каждую приехавшую деталь. */
    if (surfacesStale) reindexSurfaces();

    /*
     * Игру подключают уже при открытом редакторе — и тогда предметы, которые
     * успели стать коробками, спрашиваются заново. Сравнение стоит один шаг на
     * кадр, а без него человек, выбравший папку GTA V, видел бы заглушки до
     * перезапуска приложения и не понимал бы, почему.
     */
    const nowHasGame = hasGame();
    if (nowHasGame !== hadGame) {
      hadGame = nowHasGame;
      if (nowHasGame) layoutView?.retryModels();
    }

    /* Подписи разворачиваются к камере здесь, а не в обработчике орбиты: про
       то, что камера поехала, сцене никто не сообщает, зато кадр без движения
       камеры отсюда уходит одним сравнением кватернионов. */
    layoutView?.billboard(ctx?.camera);
  }

  function dispose() {
    mounted = false;
    generation += 1;
    listen(false);
    drag = null;
    pointerStart = null;
    probed = "";
    layoutView?.dispose();
    layoutView = null;
    canvas = null;
    raycaster = null;
    floorPlane = null;
    /*
     * Корень снимается со сцены до того, как окно пройдёт по ней с уборкой:
     * внутри лежат клоны моделей из игры, а они делят геометрию и материалы с
     * разобранными оригиналами в кэше.
     */
    if (root && ctx?.scene) ctx.scene.remove(root);
    for (const item of owned) item?.dispose?.();
    owned = [];
    /* Клоны материалов и принесённые картинки завела сцена — значит, ей их и
       освобождать: с моделью в кэше они ничего не делят. */
    releaseSurfaces();
    surfacesStale = false;
    for (const texture of brought.values()) texture?.dispose?.();
    brought.clear();
    parts.clear();
    lamps = [];
    house = null;
    schematic = null;
    hall = null;
    root = null;
    paintKey = "";
    asked = "";
    ctx = null;
  }

  const api = {
    /* ---- контракт окна превью ---- */
    mount,
    update,
    dispose,
    /*
     * Зал под крышей, и это не мелочь настройки. Окно ключует экспозицию по
     * небу, а неба в этом кадре не видно вовсе: яркое полуденное небо роняло
     * бы экспозицию так, что зал становился бы чернее, чем ночью, — реакция на
     * время суток переворачивалась. Ровно этот флаг и заводился для сцен под
     * крышей (см. `preview-lighting.js`, `enclosedExposureStops`).
     */
    enclosed: true,
    /* Ракурс объявляет сцена: помещение осматривают изнутри, крутясь на месте,
       значит орбита. */
    camera: "orbit",

    /* ---- то, что знает про зал ---- */

    /** Выбранная отделка: стиль зала, антресоль, баннеры, схема освещения. */
    apply(next) {
      const wanted = { ...selection, ...(next || {}) };
      const same = Object.keys(wanted).every(
        (group) => wanted[group] === selection[group],
      );
      if (same && parts.size) return;
      selection = wanted;
      if (!mounted) return;
      requestParts();
      /* Кадр просим здесь же: окно рисует по требованию, и без этой строки
         правка на неподвижной камере доехала бы до картинки только тогда,
         когда человек тронет мышью сцену. */
      ctx?.requestRender?.();
    },

    /* ---- то, что знает про макет ---- */

    /**
     * Что расставлено: комната шаблона, защищённые зоны, типы объектов, сами
     * объекты и выбранный.
     *
     * Раскладку собирает редактор из проекта. Сюда она приходит числами, без
     * `@modovik/interior-contract`: сцене нечего знать про формат проекта, а
     * зал обязан подниматься и на стенде, где проекта нет вовсе.
     */
    setLayout(next) {
      layout = normalizeLayout(next);
      if (!mounted) return;
      applyLayout();
    },

    /**
     * Объект из каталога, который сейчас ставят.
     *
     * Пока он в руке, под указателем ходит приманка, а щелчок по полу
     * превращает её в объект. Раньше каталог ставил объект сам — в первую
     * свободную точку из семи заранее записанных, — и место выбирал не человек.
     */
    setArmed(propId) {
      armed = propId || null;
      /* Новый предмет в руке — приманка начинается заново: её прежнее место
         принадлежит другому типу и другому размеру. */
      ghostAt = null;
      if (!armed) {
        layoutView?.setGhost(null);
        clearProbe();
        ctx?.requestRender?.();
      }
    },

    /* ---- то, что знает про отделку ---- */

    /**
     * Чем покрашено помещение: записи макета из контракта.
     *
     * Сравнение по строке, а не по ссылке: записи приезжают из React новым
     * массивом на каждую правку проекта — в том числе на сдвинутый предмет, к
     * отделке отношения не имеющий, — а перекраска трогает материалы и просит
     * кадр.
     */
    setFinish(next) {
      const wanted = Array.isArray(next) ? next : [];
      const signature = wanted
        .map((item) => `${item.surfaceId}|${item.color}|${item.texture}`)
        .join(";");
      if (signature === finishKey) return;
      finishKey = signature;
      finish = wanted;
      paint();
    },

    /** Какая поверхность выбрана: в кадре она светится. */
    setHighlightedSurface(surfaceId) {
      const wanted = String(surfaceId || "");
      if (wanted === highlighted) return;
      highlighted = wanted;
      paint();
    },

    /** Что в зале можно покрасить — для тестов и для стенда окна. */
    get surfaces() {
      return surfaceIndex ? describeInteriorSurfaces(surfaceIndex) : [];
    },

    /** Ракурс: изнутри зала или почти отвесно сверху. */
    setView(next) {
      const wanted = next === "top" ? "top" : "inside";
      if (wanted === viewMode) return;
      viewMode = wanted;
      frameCamera();
      ctx?.requestRender?.();
    },

    /** Что сейчас в кадре — для тестов и для отладки со стенда. */
    get selection() {
      return { ...selection };
    },
    get partCount() {
      return parts.size;
    },
    get lampCount() {
      return lamps.length;
    },
    get roomExtent() {
      return { ...extent };
    },
    /** Какое помещение сейчас в кадре — и то же ли, которое правят. */
    get room() {
      return room;
    },
    get showsSchematic() {
      return Boolean(schematic);
    },
    get view() {
      return viewMode;
    },
    get armed() {
      return armed;
    },
    /** Сколько вызовов отрисовки стоит макет. Пусто — макета в кадре нет. */
    get layoutDrawCount() {
      return layoutView ? layoutView.drawCount : 0;
    },
    get layoutInstanceCount() {
      return layoutView ? layoutView.instanceCount : 0;
    },
  };

  return api;
}
