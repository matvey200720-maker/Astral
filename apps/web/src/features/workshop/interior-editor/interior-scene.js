/*
 * Зал интерьера для общего окна предпросмотра.
 *
 * Что показывает этот файл, придумано не здесь: Auto Shop из mptuner, восемь
 * авторских стилей зала, антресоли, баннеры и схемы освещения — всё это
 * Rockstar положила отдельными drawable, и редактор берёт их из установленной
 * игры тем же конвейером, что и здания. Замысел сохранён целиком, включая
 * взгляд ИЗНУТРИ зала: снаружи любое помещение читается нагромождением стен —
 * видно крышу и внешние грани, а не интерьер.
 *
 * Переехало другое — кадр. Раньше рядом с залом жил собственный
 * `WebGLRenderer`, собственный цикл кадров, собственные четыре лампы и
 * выключатель «День/Ночь» на два положения. Это означало третьи сутки в
 * мастерской: у дороги свой полдень, у арены свой, у интерьера третий. Теперь
 * рендерер, камера, небо, солнце, рассеянный свет, туман и сам кадр приходят из
 * окна (`components/desktop/workshop/preview/PreviewWindow.jsx`), а оно берёт
 * их из таймцикла игры. Выключатель заменила шкала часов окна: у зала теперь
 * настоящий рассвет и настоящие сумерки, а не два подобранных цвета фона.
 *
 * Контракт окна:
 *
 *   mount(ctx)          — поставить зал в чужую сцену;
 *   update(ctx, frame)  — кадр: час, небо, свет, прошедшие секунды;
 *   dispose()           — забрать всё своё обратно.
 *
 * Ни одного `import * as THREE`: движок приходит в `ctx.THREE`. Своя копия
 * означала бы вторую сцену рядом с первой и `instanceof`, разошедшийся где-то
 * глубоко внутри рендерера.
 *
 * Файл называется `*-scene.js` и лежит рядом со своим редактором не по
 * привычке: стенд окна (`dev/preview-lab`) обходит мастерскую глобом и берёт в
 * список каждый такой файл, опознавая переходник по форме. Сцена, спрятанная
 * внутри компонента, на стенд не попадает — а зал, который нельзя посмотреть
 * глазами, чинится вслепую.
 *
 *
 * ЗЕМЛЯ И ТУМАН
 *
 * Три правила из шапки окна писаны по улице, но зал под крышей от них не
 * освобождён — у него есть пол и стены, и они участвуют в тумане ровно так же.
 *
 *  1. В `scene.fog.color` отсюда не пишет никто: в униформе тумана лежит
 *     экранный цвет, сведённый плёночной кривой, и подмешанный туда линейный
 *     цвет неба даёт белую полосу по горизонту. Сцена задаёт только масштаб —
 *     `ctx.setFogRange`.
 *  2. Дальность тумана гуляет по часу и погоде, поэтому «докуда тянуть
 *     поверхность» читается каждый кадр из `ctx.fog.far`, а не считается один
 *     раз в `mount`. У зала это проверка, а не растяжение: пол и стены стоят
 *     там, где их поставила Rockstar, и вылезти за туман они не могут. Зато
 *     могут утонуть в нём — городская дальность на зал в сорок метров кладёт
 *     молочную пелену там, где должен быть бетон. Отсюда собственный масштаб.
 *  3. Тянуть дальше дальности тумана незачем: всё, что за ней, залито ровным
 *     цветом и не видно, а карту теней и глубину ест исправно. Схематичный зал
 *     поэтому ровно того размера, что настоящий, и ни метром больше.
 *
 *
 * МАКЕТ В ЗАЛЕ
 *
 * Зал приезжал из игры и стоял пустой: объекты макета в кадр не попадали вовсе,
 * и человек расставлял их вслепую, а смотрел на пустое помещение. Теперь сцена
 * принимает раскладку (`setLayout`) и показывает её — заглушками честного
 * размера с подписями там, где модели объекта из игры не достать, и настоящей
 * моделью там, где достать. Всё, что про это надо знать, — в
 * `interior-layout-view.js`; сюда приходят уже числа.
 *
 * Комната макета и помещение в кадре — ОДНО И ТО ЖЕ, и это стоило отдельной
 * работы. Раньше они были разными: в кадре стоял зал Auto Shop из mptuner (42 ×
 * 32 м), а правился шаблон локации — магазин 24/7 (11.51 × 7.51) или лавка при
 * заправке (14.47 × 8.39). Комнату клали серединой в середину зала и обводили по
 * полу, чтобы было видно, где кончается правимое. Обводка не врала, но и
 * помещением, которое правят, не была: между ним и залом пятнадцать раз по
 * площади, и по такому кадру нельзя решить, влезет ли холодильник у стены.
 *
 * Дольше всего здесь стояло утверждение, что подтянуть из игры ТУ комнату,
 * которую правят, нельзя: обычный интерьер GTA — это MLO, оболочка плюс сотни
 * расставленных сущностей, чьи архетипы резолвятся лишь частично. Довод верен,
 * вывод из него — нет. Архетипы самого помещения резолвятся все: магазин 24/7
 * лежит двадцатью drawable в `v_int_66.rpf`, лавка при заправке — двадцатью
 * четырьмя в `v_int_68.rpf`, с одним словарём текстур на комнату. Частично
 * резолвятся чужие пропы вокруг — витрины, ящики, мусор, — но помещение это не
 * они.
 *
 * Поэтому в кадре стоит настоящее помещение, а части его встают по местам из
 * `v_int_*.ytyp` — в тех же координатах, в которых человек расставляет
 * предметы, и в тех же, которые компилятор кладёт в YMAP. Схема по числам
 * шаблона осталась запасным путём: без игры, без приложения или у незнакомой
 * комнаты (стенд окна поднимает сцену вовсе без проекта) человек по-прежнему
 * видит помещение верного размера, а не пустоту. Числа и геометрия схемы — в
 * `interior-room.js`, состав и места настоящей — в `interior-models.js`,
 * перевод координат — в `interior-layout.js`.
 *
 *
 * ОТДЕЛКА
 *
 * Помещение в кадре можно не только смотреть, но и красить: цвет и текстура
 * его поверхностей правятся здесь же. Список поверхностей при этом уезжает
 * НАВЕРХ, а не приходит сверху, и по-другому быть не может — состав магазина
 * лежит в файлах Rockstar, и до того, как модель приедет из установленной
 * игры, ни редактор, ни контракт не знают, сколько у него стен и есть ли у
 * него потолок. Разбирает приехавшее `interior-finish.js`, сцена же отвечает
 * за три вещи: когда разбирать (состав зала сменился), чем красить (макет
 * проекта) и на чём (клоны материалов, а не материалы кэша).
 *
 * Схема помещения красится тем же кодом и под тем же именем `room`: без игры
 * человек видит те же органы, а не пустую панель с обещанием.
 *
 *
 * УКАЗАТЕЛЬ
 *
 * Холст один, и мышью на нём работают двое: окно крутит орбиту, редактор
 * двигает объекты. Рассудить их может только тот, кто знает, попал ли указатель
 * в объект, — то есть сцена. Отсюда два приёма.
 *
 * Первый — порог в пять пикселей на щелчке, ровно как у торгового центра
 * (`mega-mall-scene.js`): без него любое разглядывание зала заканчивалось бы
 * выбором случайного объекта.
 *
 * Щелчок мимо предмета попадает в само помещение: сцена ищет поверхность под
 * указателем и называет её наверх. Это единственный способ ткнуть в стену, у
 * которой нет говорящего имени, — в списке она «поверхность 4», а глазами
 * человек видит ровно ту стену, в которую ткнул.
 *
 * Второй — заявка окну. Разобрав попадание, сцена зовёт `ctx.claimPointer`, и
 * окно пропускает заявленный указатель целиком: нажатие, протяжку, отпускание
 * и колесо. Щелчок по пустому полу не заявляется — там орбита и должна
 * работать. Порядок подписки при этом ничего не решает: слушатели окна заведены
 * на холсте раньше наших, но начатую орбиту заявка разбирает задним числом,
 * поэтому слушатели сцены висят на том же холсте и в обычной фазе.
 *
 *
 * ВЗГЛЯД СВЕРХУ
 *
 * План сверху у редактора был — отдельной схемой из прямоугольников, — и ушёл
 * вместе с появлением настоящего зала. Расставлять сверху удобнее, поэтому он
 * вернулся камерой над тем же залом, а не второй картинкой: `setView("top")`
 * просит у окна почти отвесную орбиту с зажатым наклоном.
 *
 * Камера при этом остаётся ПОД потолком. Сверху над крышей видно крышу, а не
 * пол: меши интерьера односторонние, и полагаться на то, что игра построила их
 * нормалями внутрь, нельзя. Поэтому предельное расстояние в этом ракурсе
 * считается по высоте помещения, а не по размеру его пола.
 */

