/*
 * Подписи кадра с кварталом из игры (задача 4Б ТЗ 18.10.2026): что на нём из
 * игры, а что нарисовано Astral, и что говорит кадр, пока квартал едет.
 *
 * Правило поставки (`CLAUDE.md`): нарисованное называется нарисованным. Квартал
 * читается из игры игрока на его машине — в поставке текстур и моделей Rockstar
 * нет, — а свет, туман и экспозицию считает Astral по числам таймцикла.
 * Строки — через `tr()` в момент показа: язык меняется без перезагрузки.
 */

import { tr } from "../../../locales/ui.js";

/* Ступени разрешения кадра (`block-scene.js`) в процентах. */
const RESOLUTION_PERCENT = ["100", "80", "64"];

/** Строки состояния, когда кадр упрощён под видеокарту: без сглаживания краёв и/или сниженное разрешение. */
export function blockLowered({ step = 0, antialias = true } = {}) {
  const lowered = [];
  if (!antialias) lowered.push(tr("Кадр упрощён под вашу видеокарту: без сглаживания краёв."));
  if (step > 0)
    lowered.push(tr("Кадр упрощён под вашу видеокарту: разрешение {percent} %.").replace("{percent}", RESOLUTION_PERCENT[step] ?? "—"));
  return lowered;
}

/** Что кадр говорит, пока квартал не готов: едет из игры или собираются программы. */
export function blockNote(note) {
  if (note?.phase === "shaders") return tr("Собираются шейдеры квартала…");
  return tr("Квартал читается из вашей игры…");
}
