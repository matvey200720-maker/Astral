import { StageNote } from "../../../components/ui/StageOverlay.jsx";
import { tr } from "../../../locales/ui.js";
import { textureAvailable } from "./scene-textures.js";

/*
 * Откуда листы в кадре (строка состояния в панели редактора, не на картинке): без Astral Desktop листы игры не прочитать — такие
 * поверхности идут средним цветом, и об этом — предупреждением. Когда листы из вашей GTA V, строки нет (ТЗ 29.10.2026, вечер: в
 * колонке нет абзацев о том, что и так работает).
 */
export function StageSheetsNote() {
  /* Откуда листы, кадру говорить незачем (ТЗ 29.10.2026, вечер: обход кадров): строка — только когда листов игры нет. */
  if (textureAvailable({ set: "hangar" })) return null;
  return <StageNote tone="warning">{tr("Без Astral Desktop листы игры не прочитать — цвета средние")}</StageNote>;
}
