/*
 * Материал, который показали позже, встаёт, когда его листы ответили, и вместе с остальными (ревью этапа 1, 14.11.2026; решение владельца 13.11: сцену без текстур
 * не показываем).
 *
 * Облик просит листы у каждого материала, в том числе у спрятанного (`visible: false`) — и листы спрятанного уже прочитаны к тому часу, когда его покажут
 * («арена: наклейки, кола, автоматы — показать»), и материал встаёт сразу с текстурами. Но облик может не просить листы у спрятанного: тогда показанный позже материал
 * встал бы в среднем цвете, а листы доехали бы на виду, без заставки. Здесь — очередь показа: материал, которого не было видно, становится видимым, только когда все
 * его листы ответили (пришли или не придут), а если облик показал сразу несколько, они встают вместе — когда волна доехала и итог листов подведён (`sheets-flow.js`),
 * а до тех пор кадр показывает лёгкую загрузку (полоску), не карточку.
 *
 * Потолок ожидания (находка 7 ревью тестового ПК, 15.11.2026): листы не отвечают (читатель завис) — материал не должен оставаться невидимым навсегда. `silenceMs` — столько без единого ответа листа
 * очередь терпит; потом зовёт `onSilence` (кадр показывает придержанное, как `main`: в среднем цвете, листы доедут на виду). Ответ любого листа (`heard`) отсчёт начинает заново: честно идущая
 * загрузка материал держит, сколько идёт; молчание — нет. Без `silenceMs` потолка нет.
 *
 * Чистый модуль без three и DOM: «лист» — любой объект с `userData.settled`; его читает `orbit-stage.js`, а тест гоняет на подставных листах.
 */
export function createRevealQueue({ silenceMs = 0, onSilence = null, setTimer = (run, ms) => setTimeout(run, ms), clearTimer = (handle) => clearTimeout(handle) } = {}) {
  const held = new Set();
  let timer = 0;
  const disarm = () => {
    if (!timer) return;
    clearTimer(timer);
    timer = 0;
  };
  const arm = () => {
    disarm();
    if (!silenceMs || !held.size) return;
    timer = setTimer(() => {
      timer = 0;
      if (held.size) onSilence?.();
    }, silenceMs);
  };
  return {
    /**
     * Спрятанный материал, чей облик теперь «виден» и просит `sheets`: `true` — показать сейчас (листы на месте, и других ждущих нет), `false` — придержан до итога
     * волны (какой-то лист ещё едет или уже ждут другие: встают вместе).
     */
    want(material, sheets) {
      const waiting = sheets.some((sheet) => !sheet.userData.settled);
      if (!waiting && held.size === 0) return true;
      held.add(material);
      if (!timer) arm();
      return false;
    },
    /** Облик снова спрятал материал (или он ушёл): ждать его показа не нужно. */
    drop(material) {
      held.delete(material);
      if (!held.size) disarm();
    },
    /** Волна доехала и итог подведён: придержанные материалы — показать вместе. */
    release() {
      const out = [...held];
      held.clear();
      disarm();
      return out;
    },
    clear() {
      held.clear();
      disarm();
    },
    /** Какой-то лист кадра ответил: читатель жив, тишина кончилась — отсчёт потолка заново (если есть кого ждать). */
    heard() {
      if (held.size) arm();
    },
    has: (material) => held.has(material),
    get size() {
      return held.size;
    },
  };
}
