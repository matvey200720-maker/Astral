/*
 * Рассеянный свет студии одним источником (18.10.2026, задача 10Б: «в зале арены очень лагает»).
 *
 * Студийное окружение (`RoomEnvironment` → PMREM) даёт стандартному материалу мягкий рассеянный свет и блики, но
 * каждый пиксель каждого материала платит за него выборками из кубической карты — на залах с сотнями тысяч
 * треугольников это четверть времени кадра. Для тяжёлой сцены (материалы «Ламберт», блики на шероховатом
 * 0,84 не видны) тот же рассеянный свет считается девятью числами: сферическими гармониками второго порядка от
 * той же комнаты. Коэффициенты сняты один раз с `RoomEnvironment` (куб 64×64×6, проекция излучения на базис SH9,
 * оси сцены three.js) и дальше вычислений не требуют.
 *
 * Сила — та же, что у окружения кадра (`scene.environmentIntensity`): освещённость от окружения у three.js — π·L,
 * у источника-зонда — та же свёртка с косинусом, так что при одинаковой силе яркость стен сходится.
 */

import * as THREE from "three";

/* Проекция излучения RoomEnvironment на SH9: девять троек RGB (комната серая — каналы равны). */
export const ROOM_SH = Object.freeze([
  [3.45729, 3.45729, 3.45729],
  [1.41403, 1.41403, 1.41403],
  [1.17536, 1.17536, 1.17536],
  [0.16898, 0.16898, 0.16898],
  [0.18813, 0.18813, 0.18813],
  [1.22964, 1.22964, 1.22964],
  [0.36519, 0.36519, 0.36519],
  [-0.15421, -0.15421, -0.15421],
  [-1.13125, -1.13125, -1.13125],
]);

/*
 * Прибавка силы: «Ламберт» без бликов окружения и без блика ламп отдаёт кадру на 13 % меньше света, чем PBR с окружением (среднее
 * по двенадцати видам зала Majestic: 0,874); с прибавкой 1,6 яркость сходится (0,98–1,0) — проверено теми же видами.
 */
export const ROOM_PROBE_GAIN = 1.6;

/** Источник-зонд с рассеянным светом студии; сила — 0 (выключен), пока сцена не просит. */
export function createRoomLightProbe() {
  const probe = new THREE.LightProbe();
  ROOM_SH.forEach((value, index) => probe.sh.coefficients[index].set(value[0], value[1], value[2]));
  probe.intensity = 0;
  return probe;
}
