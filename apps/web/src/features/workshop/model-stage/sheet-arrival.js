/*
 * Что делать с ответом листа, когда он пришёл (находка 3 ревью тестового ПК, 15.11.2026).
 *
 * Лист, что едет, мог перестать быть нужным кадру: сцену сменили, пока он был в пути, и `evictStaleTextures` убрал его из таблицы листов (и освободил на видеокарте). Раньше пришедшая
 * картинка всё равно ложилась на забытый лист: `standIns.remember` держал её как замену до закрытия кадра (до 16 МБ у листа 2048), а `sheetEpoch` и пачка листов (`sheetBatch.arrive`) поднимали
 * лишний итог — полный проход облика, сборку программ и тени — на чужой сцене, и её заставка держалась дольше. Теперь ответ забытому листу ничего не меняет.
 *
 * То же у листа сцены из кэша сцен (находка 4 приёмки тестового ПК, 16.11.2026): сцена A ушла в кэш, пока её листы ещё ехали, на кадре сцена B, и лист A приходит. Он остаётся в таблице (вернутся к A —
 * он нужен), но материалы B на него не смотрят: пачка листов отдаёт облику пустой набор материалов, а итог (полный проход облика, сборка программ, тень) считается на B ни за чем. Теперь такой лист
 * ложится на свою текстуру и больше ничего не зовёт; вернулись к A — `setLook` берёт готовый лист из таблицы.
 *
 * Картинку закрывать не нужно и нельзя: она общая с кэшем окна (`scene-textures.js: images`, его берут обложки и плитки), кадр её только держал, а теперь не держит.
 *
 * Чистый модуль без three и DOM: его читает `orbit-stage.js`, а тест гоняет на подставных ответах.
 */

/**
 * `ready` — лист на месте в кадре и в охвате текущей сцены, картинка пришла: ставить, звать пачку;
 * `missing` — лист на месте и в охвате, но картинки нет (нет в игре, отказ): пачки он не рождает, а итог мог ждать именно его ответа;
 * `kept` — картинка пришла, но лист не текущей сцены (`current: false`, из кэша сцен): положить на текстуру, пачку и итог не звать;
 * `stale` — кадр закрыт, лист вытеснен (заменён другим), либо лист не текущей сцены и не пришёл: ничего не трогать.
 */
export function sheetArrival({ disposed = false, image = null, listed = true, current = true } = {}) {
  if (disposed || !listed) return "stale";
  if (!current) return image ? "kept" : "stale";
  return image ? "ready" : "missing";
}
