/*
 * Под заставкой сцену не рисуют (14.11.2026, профиль «до»: `WebGLRenderer.render` — 26–31 % занятости главного потока окна за вход; кадр рисовался на каждую пачку
 * листов, хотя холст закрыт заставкой и никто его не видит).
 *
 * Пока идёт первая загрузка сцены, холст закрыт (`is-covered`, `ModelStage.jsx`), и кадр знает об этом (`stage.setCovered`). Закрытый кадр рисует только
 *  • первую отрисовку новой сцены — её ждёт комната редактора (`onPresented`, правило 26 `docs/3D.md`);
 *  • отрисовку итога листов (`sheet-finish.js: unpainted`) — в ней заливаются текстуры и считается карта теней, чтобы к открытию холста на нём уже был итоговый кадр
 *    и открытие не приносило долгого кадра;
 *  • комнату без сцены (`empty`): сцены ещё нет, рисовать нечего, а кадр холста (фон, окружение, программы пола) готовится заранее — как рисовал до заставки. Прежде ворота закрывали и его, и
 *    первая отрисовка комнаты уходила на всё чтение сцены (стенд «вход в редактор»: 0,35 с → 0,9–1,8 с);
 *  • явный снимок (`stage.render`) — он идёт мимо этого ворота.
 * Остальные просьбы нарисовать (облик по пачке листов, сборка программ, камера) пропускаются, а облик и программы собираются по ходу, как собирались. Открыли холст —
 * если что-то пропустили, кадр рисуется сразу, поэтому закрытый кадр, которому итог не пришёл (листы «не идут», потолок), ничего не держит. Открытый кадр (волна листов
 * после первого «готово», полоска) рисуется как прежде.
 *
 * Чистый модуль без three и DOM: его читает `orbit-stage.js`, а тест гоняет на подставных кадрах.
 */
export function createCoverGate() {
  let covered = false;
  /* Просили нарисовать, пока было закрыто, и не нарисовали: холст открыть без кадра нельзя. */
  let skipped = false;
  return {
    /** Закрыть или открыть. `true` — открыли, а рисовать пропускали: нужен кадр. */
    set(value) {
      const next = Boolean(value);
      if (next === covered) return false;
      covered = next;
      if (covered) return false;
      const owed = skipped;
      skipped = false;
      return owed;
    },
    /** Можно ли рисовать сейчас: открыт, либо первая отрисовка сцены, либо отрисовка итога, либо сцены ещё нет (`empty`). */
    allows({ firstOfScene = false, finalPending = false, empty = false } = {}) {
      if (!covered || firstOfScene || finalPending || empty) return true;
      skipped = true;
      return false;
    },
    /** Кадр нарисован: холст свежий, долга нет. */
    drawn() {
      skipped = false;
    },
    get covered() {
      return covered;
    },
    get owes() {
      return skipped;
    },
  };
}
