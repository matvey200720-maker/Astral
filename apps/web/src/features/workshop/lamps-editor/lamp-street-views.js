/** Глаз вида в осях сцены и рамка орбиты вокруг него. */
export function streetPose(viewId) {
  const spec = STREET_VIEWS[viewId] || STREET_VIEWS.road;
  const [x, y] = spec.at;
  const z = spec.ground + (spec.eyeHeight ?? EYE_HEIGHT);
  const eye = [x, z, -y];
  return {
    pose: { eye, yaw: spec.yaw, pitch: spec.pitch, fov: spec.fov },
    /*
     * Орбита и перелёт домой: цель — перед глазом, дальность — как у вида «по умолчанию» квартала. Пол
     * полёта — земля под камерой (`ground`, `timecycle-block/block-ground.js`); `floor` — запасной, на
     * случай, когда луч земли не нашёл: ниже земли вида на три метра, а не плоские 0,8 м от якоря, из-за
     * которых полёт над дорогой на −9,6 м подскакивал на девять метров.
     */
    frame: { target: [x + Math.sin(spec.yaw) * 30, z, -(y + Math.cos(spec.yaw) * 30)], radius: 30, floor: spec.ground - 3, ground: true, fly: spec.fly !== false },
  };
}

