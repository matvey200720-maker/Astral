/*
 * Столб кадра — настоящий `prop_streetlight_01` этой улицы Davis (из манифеста секции: от якоря (62, −55,3),
 * земля −9,6 м): на нём «У лампы» показывает лампу, а «Столб» и «Украшения» — правку. `at` — метры от якоря
 * в осях игры; сам экземпляр кадр находит по ближайшей точке (`nearestInstance`), а не по номеру: номера
 * зависят от порядка файлов игры.
 */
export const LIVE_POLE = Object.freeze({ piece: "prop_streetlight_01", at: Object.freeze([62, -55.3]) });

/**
 * Ближайший к `LIVE_POLE.at` экземпляр детали: `matrices` — матрицы экземпляров в осях сцены
 * (`pieceMatrices`); возвращает номер или −1, если их нет или все дальше `within` метров.
 */
export function nearestInstance(matrices, at = LIVE_POLE.at, within = 6) {
  let best = -1;
  let distance = within;
  (matrices || []).forEach((matrix, index) => {
    const e = matrix?.elements;
    if (!e) return;
    /* Сцена (x, y, z) — игра (x, −z). */
    const d = Math.hypot(e[12] - at[0], -e[14] - at[1]);
    if (d < distance) {
      distance = d;
      best = index;
    }
  });
  return best;
}

