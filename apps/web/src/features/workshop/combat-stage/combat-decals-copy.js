/*
 * Строки про раны и кровь в кадре боя (ТЗ 18.10.2026, задача 4А, декали): откуда они в кадре и что, если данных нет.
 * Показываются строкой состояния в панели редактора (`StageNote`). Строки — через `tr()` в момент показа: язык меняется без перезагрузки.
 */

import { tr } from "../../../locales/ui.js";

/** Про раны и брызги у попаданий; `state` — состояние данных (`useCombatStage`). */
export function decalsNote(state) {
  if (state === "ready")
    return tr(
      "Раны, подтёки и брызги на теле — по системе повреждений вашей игры (peddamage.xml), на земле за жертвой — брызги из decals.dat и bloodfx.dat; времени жизни у брызг на земле в файлах нет.",
    );
  if (state === "failed" || state === "missing")
    return tr("Ран и пятен нет: данные повреждений вашей игры не прочитались, кровь рисуют только частицы.");
  return tr("Читаем раны и кровь из вашей игры…");
}

/** То же для килла: враг падает вместе со своими ранами. */
export function killDecalsNote(state) {
  if (state === "ready")
    return tr("Рана на враге и брызги на земле — по данным вашей игры (peddamage.xml, bloodfx.dat), враг падает вместе с ними.");
  if (state === "failed" || state === "missing") return tr("Ран и крови на враге нет: данные повреждений вашей игры не прочитались.");
  return tr("Читаем раны и кровь из вашей игры…");
}
