/*
 * Фильтр «Персонаж» (Все / Мужское / Женское) раздела «Одежда» каталога (слово владельца 14.11.2026: «в фильтрах добавь мужское, женское, чтобы девочки тоже могли выбрать
 * на себя одежду»; поправка в тот же день: никакой общей настройки «мой персонаж» нет, каталог и мастерская друг другом не управляют).
 *
 * Обычный фильтр: тот же орган, что у «Размера» редуксов, — группа под чертой в меню порядка «Новые ▾» (`filterGroup`, `design-qa.md`, «Фильтры раздела»). Стартовое значение —
 * «Все»; выбор «Мужское» или «Женское» только отбирает карточки и ничего другого не ставит. Положение фильтра помнится в памяти раздела, как остальные фильтры каталога
 * (`catalog:gender`, до закрытия окна).
 *
 * Отбор — по полю карточки `domain.clothing.gender`, не по имени: вещи без пола и на оба пола видны при любом значении (`useCatalogResults.js`, `fitsFilters`).
 */

/** Раздел каталога, где есть фильтр пола. */
export const GENDER_FILTERED = "clothing";

/** Выбранное значение фильтра: `"male"`, `"female"` или `""` («Все»); всё остальное — «Все». */
export const genderChoiceOf = (shown) =>
  shown === "male" || shown === "female" ? shown : "";

/** Фильтр пола раздела `category` для выдачи: `"male"` / `"female"`; пусто — не отбирать (у раздела нет такого фильтра или выбрано «Все»). */
export const genderFilterOf = (category, shown) =>
  category === GENDER_FILTERED ? genderChoiceOf(shown) : "";

/** Группа «Персонаж» для меню порядка: заголовок, поле, выбранный пункт и пункты `[ключ, подпись]`. `words` — слова каталога на языке окна. */
export function genderGroupOf(words, shown) {
  return {
    heading: words.genderLabel,
    field: "gender",
    value: genderChoiceOf(shown),
    items: [
      ["", words.genderAll],
      ["male", words.label("Мужское")],
      ["female", words.label("Женское")],
    ],
  };
}
