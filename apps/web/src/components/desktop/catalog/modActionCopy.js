export function modActionCopy(language) {
  return translations[language] || english;
}

export function modActionEditions(mod) {
  if (Array.isArray(mod.editions) && mod.editions.length) return mod.editions;
  if (Array.isArray(mod.manifest?.editions) && mod.manifest.editions.length) {
    return mod.manifest.editions;
  }
  return ["Legacy", "Enhanced"];
}

/* Указал ли автор версию игры. Нет — строка плана так и говорит, а не
   подписывает «Legacy + Enhanced» словами «указана автором мода». */
export function modEditionsStated(mod) {
  return (
    (Array.isArray(mod.editions) && mod.editions.length > 0) ||
    (Array.isArray(mod.manifest?.editions) && mod.manifest.editions.length > 0)
  );
}

const PLURAL_LOCALES = {
  ru: "ru-RU",
  uk: "uk-UA",
  en: "en-US",
  de: "de-DE",
  pl: "pl-PL",
  fr: "fr-FR",
};

/** «3 файла», «5 файлов», «21 файл» — по правилам языка окна. */
export function modFilesLabel(count, language) {
  const copy = modActionCopy(language);
  const rule = new Intl.PluralRules(PLURAL_LOCALES[language] || "en-US").select(
    count,
  );
  return `${count} ${copy.fileForms[rule] || copy.fileForms.other}`;
}

/** «4 части», «5 частей» — состав сборки (Т-81c) на языке окна. */
export function modPartsLabel(count, language) {
  const copy = modActionCopy(language);
  const rule = new Intl.PluralRules(PLURAL_LOCALES[language] || "en-US").select(
    count,
  );
  return `${count} ${copy.partForms[rule] || copy.partForms.other}`;
}

/** «19 компонентов» — сколько компонентов у сборки редукса (владелец 13.11.2026), на языке окна. */
export function modComponentsLabel(count, language) {
  const copy = modActionCopy(language);
  const rule = new Intl.PluralRules(PLURAL_LOCALES[language] || "en-US").select(count);
  return `${count} ${copy.componentForms[rule] || copy.componentForms.other}`;
}

