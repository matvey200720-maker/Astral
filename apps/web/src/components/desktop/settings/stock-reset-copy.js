const NB = String.fromCharCode(160);
const rulesByLanguage = {};
function plural(language, count, forms) {
  const rules = (rulesByLanguage[language] ||= new Intl.PluralRules(language));
  return forms[rules.select(Number(count) || 0)] ?? forms.other ?? forms.many;
}
const number = (language, count) => new Intl.NumberFormat(language).format(Number(count) || 0);
const counted = (language, count, forms) => `${number(language, count)} ${plural(language, count, forms)}`;
const size = (language, bytes) => formatBytes(bytes, language);

