export function stockResetCopyFor(language) {
  return COPY[language] ?? EN;
}

/* Отказ главного процесса — словами языка окна (сам он пишет по-русски). */
export function stockResetFailure(error, copy) {
  const text = String(error?.message || error || "");
  if (/Закройте GTA V/.test(text)) return copy.errors.gameRunning;
  if (/Вернуть GTA V без модов/.test(text)) return copy.errors.astralFirst;
  if (/игра без модов/.test(text)) return copy.errors.vanilla;
  if (/Не хватает места/.test(text) || /ENOSPC/.test(text)) return copy.errors.noSpace;
  return null;
}
