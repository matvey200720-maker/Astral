/*
 * Поле травы для общего окна превью.
 *
 * Это не сцена, а постоялец сцены: окно (`preview/PreviewWindow.jsx`) держит
 * рендерер, камеру, солнце, небо и туман, а отсюда в него приезжает то, ради
 * чего его открыли, — земля, трава, подстилка, кусты и деревья. Поэтому здесь
 * нет ни одного `import * as THREE`: всё строится тем `THREE`, который окно
 * передало в `ctx`.
 *
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ ВЫГЛЯДИТ КАК СБОРКА, А НЕ КАК СЦЕНА
 *
 * Трава — это тысячи объектов, и наивная реализация кладёт окно, а не «немного
 * замедляет». Три решения ниже приняты именно поэтому, и каждое стоит того,
 * чтобы его не отменили в следующей правке.
 *
 * 1. Один вызов отрисовки на тип растения. Всё поле — один `InstancedMesh`,
 *    подстилка — второй, кусты — третий, кроны — четвёртый, стволы — пятый.
 *    Шестьдесят тысяч отдельных `Mesh` — это шестьдесят тысяч вызовов, то есть
 *    секунды на кадр ещё до того, как видеокарта нарисует первый пиксель.
 *
 * 2. Ползунок не пересобирает буфер. Матрицы экземпляров считаются ОДИН раз
 *    при монтаже и не переписываются никогда. Плотность меняет только
 *    `mesh.count` — сколько экземпляров рисовать; высота, разброс, цвет,
 *    дальность, ветер и свет — это униформы. Отсюда правило: любая новая
 *    настройка травы обязана быть униформой либо `count`, и ничем третьим.
 *    Пересборка шестидесяти тысяч матриц на движение ползунка — это кадр в
 *    четверть секунды, то есть ползунок, за которым картинка не поспевает.
 *
 *    Из этого же правила следует, ПОЧЕМУ РЕЛЬЕФ ЗЕМЛИ НЕ ПОЛЗУНОК. Высота
 *    куста и дерева вписана в матрицу экземпляра (по ней строится их тень), а
 *    значит амплитуда рельефа живым ползунком быть не может — только частью
 *    покрова либо константой. Она константа: см. `terrainHeight` в
 *    `vegetation-shader.js`, там же причина, почему в начале координат она
 *    ровно ноль.
 *
 * 3. Ветер и свет живут в вершинном шейдере. Пересчёт матриц на процессоре
 *    ради покачивания — это те же шестьдесят тысяч умножений матриц каждый
 *    кадр плюс перезаливка буфера в видеопамять; в шейдере это десяток команд
 *    на вершину и ноль обращений к шине. Сами программы лежат в
 *    `vegetation-shader.js` — вместе с причинами, по которым нормаль у листвы
 *    наклонная, а материал глубины считает тот же изгиб, что и материал света.
 *
 *
 * АЛЬФА И МИП-УРОВНИ
 *
 * У листвы альфа несёт форму листа, поэтому материалы здесь непрозрачные с
 * альфа-тестом, а не полупрозрачные: полупрозрачность потребовала бы сортировки
 * тысяч карточек по глубине каждый кадр и всё равно давала бы швы на
 * пересечениях. Порог теста занижен (см. `ALPHA_TEST`) — на дальних мип-уровнях
 * альфа усредняется и трава редеет раньше, чем должна. Край силуэта сглаживает
 * alpha-to-coverage, и включается он строго по качеству окна: без многократной
 * выборки он даёт не мягкий край, а полупрозрачную кашу (см. `tune`).
 *
 * Анизотропия обязательна и не является украшением. Поле смотрят с высоты
 * человека, то есть под скользящим углом; без анизотропии трава в двадцати
 * метрах смазывается в ровную полосу. Ровно этим уже болела обочина дороги.
 *
 *
 * ЗЕМЛЯ И ТУМАН
 *
 * Земля обязана доставать до `ctx.fog.far` и читает его каждый кадр — см.
 * раздел про землю в шапке `PreviewWindow.jsx`. Здесь это одно умножение
 * масштаба, а не пересборка плиты.
 *
 * Ближняя граница тумана привязана к дальности травы, а не прибита числом.
 * Прибитая, она стояла на двадцати пяти метрах при штатной дальности поля в
 * двадцать четыре: ВСЁ поле стояло ДО начала тумана, ближний и дальний край
 * были одинаково контрастны, и глубины в кадре не было вовсе.
 */

