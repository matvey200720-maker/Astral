const BUSH_LOBES = 3;

/* ---------- низкодискрепансная расстановка ---------- */

/*
 * Последовательность R₂ (Roberts, 2018): две координаты, каждая с шагом в
 * обратную степень пластического числа. Свойство, ради которого она здесь, —
 * равномерность ЛЮБОГО префикса: первые сто точек покрывают квадрат так же
 * ровно, как первые двадцать тысяч. Отсюда и берётся ползунок плотности,
 * который не трогает буфер: убавили `count` — поле поредело всюду сразу, а не
 * обрезалось сектором.
 */
const PLASTIC = 1.324717957244746;
const R2_X = 1 / PLASTIC;
const R2_Y = 1 / (PLASTIC * PLASTIC);
const fract = (value) => value - Math.floor(value);

/**
 * Точка последовательности, разложенная по кругу заданного радиуса.
 *
 * `turn` — поворот всего кольца в оборотах. Он нужен, чтобы кусты не выросли
 * там же, где деревья: брать для них РАЗНЫЕ индексы одной последовательности
 * нельзя — подпоследовательность с шагом семь уже не низкодискрепансная, и
 * пять кустов из неё сбились все в одну четверть горизонта. Поворот сохраняет
 * равномерность и при этом разводит ярусы.
 */
function discPoint(index, radius, inner = 0, turn = 0) {
  const u = fract(0.5 + R2_X * (index + 1));
  const v = fract(0.5 + R2_Y * (index + 1));
  /* Корень — не украшение: без него точки сгущаются к центру, потому что
     площадь кольца растёт с радиусом, а доля индексов — нет. */
  const r = Math.sqrt(inner * inner + u * (radius * radius - inner * inner));
  const angle = (v + turn) * Math.PI * 2;
  return [Math.cos(angle) * r, Math.sin(angle) * r];
}

/* Свой генератор случайных вместо Math.random: сцена обязана открываться одной
   и той же поляной, иначе «до» и «после» правки не сравнить глазами, а тест не
   сможет утверждать про неё вообще ничего. */
function seeded(seed) {
  let state = (seed * 2654435761) >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

/* ---------- сборка геометрии руками ---------- */

/*
 * Ком листвы и дерево с сучьями собираются в обычные массивы, а не из готовых
 * `PlaneGeometry`/`CylinderGeometry` с последующей склейкой.
 *
 * Склейка потребовала бы `BufferGeometryUtils`, то есть отдельного куска
 * three, который окно не тянет, а главное — она создаёт десяток временных
 * геометрий, каждую из которых надо потом освободить. Промахнуться в этом
 * списке легко и незаметно: тест на освобождение подписывается только на те
 * геометрии, которые дошли до `built.geometries`. Массивы такой возможности не
 * дают вовсе — геометрия ровно одна, и освобождается она одна.
 */
const emptyMesh = () => ({
  position: [],
  normal: [],
  uv: [],
  colour: [],
  index: [],
});

function finishMesh(THREE, parts) {
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute(
    "position",
    new THREE.Float32BufferAttribute(parts.position, 3),
  );
  geometry.setAttribute(
    "normal",
    new THREE.Float32BufferAttribute(parts.normal, 3),
  );
  geometry.setAttribute("uv", new THREE.Float32BufferAttribute(parts.uv, 2));
  /* Вершинный цвет здесь — это запечённое затенение, а не краска: им ком
     листвы темнеет внутрь, а плоскости креста расходятся по яркости. Три байта
     на вершину против второй текстуры и второй выборки на фрагмент. */
  geometry.setAttribute(
    "color",
    new THREE.Float32BufferAttribute(parts.colour, 3),
  );
  geometry.setIndex(parts.index);
  return geometry;
}

const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

const cross = (a, b) => [
  a[1] * b[2] - a[2] * b[1],
  a[2] * b[0] - a[0] * b[2],
  a[0] * b[1] - a[1] * b[0],
];

function unit(v) {
  const length = Math.hypot(v[0], v[1], v[2]) || 1;
  return [v[0] / length, v[1] / length, v[2] / length];
}

/**
 * Уложить готовые вершины в единичную коробку креста.
 *
 * Не косметика: по половине ширины карточки считается коробка теней (см.
 * `SHADOW_EXTENT`), а по единичному кресту — весь остальной счёт сцены, от
 * матрицы экземпляра до размера куста в метрах. Ком, собранный «примерно в
 * радиусе единицы», разошёлся бы с обоими, и разошёлся бы молча: в кадре это
 * деревья без тени по краю леса, в тесте — ничего.
 *
 * Масштаб один на все три оси: разный растянул бы квадратные карточки в
 * прямоугольники, и листва поехала бы вслед за формой кома.
 */
function fitToUnitBox(position) {
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  let minZ = Infinity;
  let maxZ = -Infinity;
  for (let index = 0; index < position.length; index += 3) {
    minX = Math.min(minX, position[index]);
    maxX = Math.max(maxX, position[index]);
    minY = Math.min(minY, position[index + 1]);
    maxY = Math.max(maxY, position[index + 1]);
    minZ = Math.min(minZ, position[index + 2]);
    maxZ = Math.max(maxZ, position[index + 2]);
  }
  const midX = (minX + maxX) / 2;
  const midZ = (minZ + maxZ) / 2;
  const half = Math.max((maxX - minX) / 2, (maxZ - minZ) / 2, 1e-6);
  const tall = Math.max(maxY - minY, 1e-6);
  const scale = Math.min(0.5 / half, 1 / tall);
  for (let index = 0; index < position.length; index += 3) {
    position[index] = (position[index] - midX) * scale;
    position[index + 1] = (position[index + 1] - minY) * scale;
    position[index + 2] = (position[index + 2] - midZ) * scale;
  }
}

/**
 * Сук или ствол: труба переменного радиуса вдоль изогнутой оси.
 *
 * Ось — квадратичная кривая Безье, потому что прямой отросток под углом
 * читается подпоркой, а не веткой, а вторая точка кривой стоит ровно одного
 * сложения.
 *
 * Нормаль считается по производной радиуса, а не усреднением граней: у трубы
 * вершины на стыке развёртки продублированы (шов), и усреднение оставило бы по
 * стволу светлую полосу во всю высоту. Производная берётся численно и по той же
 * функции радиуса, которой построены пояса, — записать её второй раз руками
 * значит однажды разойтись с профилем комля.
 */
function limbInto(parts, { from, to, bow, radius, rings, sides, tile }) {
  const control = [
    (from[0] + to[0]) / 2 + bow[0],
    (from[1] + to[1]) / 2 + bow[1],
    (from[2] + to[2]) / 2 + bow[2],
  ];
  const at = (t) =>
    [0, 1, 2].map(
      (axis) =>
        (1 - t) * (1 - t) * from[axis] +
        2 * (1 - t) * t * control[axis] +
        t * t * to[axis],
    );
  const speed = (t) =>
    [0, 1, 2].map(
      (axis) =>
        2 * (1 - t) * (control[axis] - from[axis]) +
        2 * t * (to[axis] - control[axis]),
    );

  const start = parts.position.length / 3;
  for (const t of rings) {
    const centre = at(t);
    const tangent = unit(speed(t));
    /* Опора для базиса: вертикаль, а у почти вертикального ствола —
       горизонталь. Совпади опора с осью — и базис вырождается в ноль. */
    const anchor = Math.abs(tangent[1]) > 0.9 ? [1, 0, 0] : [0, 1, 0];
    const first = unit(cross(anchor, tangent));
    const second = cross(tangent, first);
    const here = radius(t);
    /* Наклон стенки: во сколько раз радиус меняется быстрее, чем растёт длина
       оси. Он и заваливает нормаль от чистой радиальной. */
    const step = 1e-3;
    const grow =
      (radius(Math.min(1, t + step)) - radius(Math.max(0, t - step))) /
      (Math.min(1, t + step) - Math.max(0, t - step));
    const slope = grow / (Math.hypot(...speed(t)) || 1);
    for (let side = 0; side <= sides; side += 1) {
      const angle = (side / sides) * Math.PI * 2;
      const outward = [
        first[0] * Math.cos(angle) + second[0] * Math.sin(angle),
        first[1] * Math.cos(angle) + second[1] * Math.sin(angle),
        first[2] * Math.cos(angle) + second[2] * Math.sin(angle),
      ];
      parts.position.push(
        centre[0] + outward[0] * here,
        centre[1] + outward[1] * here,
        centre[2] + outward[2] * here,
      );
      parts.normal.push(
        ...unit([
          outward[0] - tangent[0] * slope,
          outward[1] - tangent[1] * slope,
          outward[2] - tangent[2] * slope,
        ]),
      );
      /* Кора идёт по стволу несколько раз: развёртка обходит его один раз, и
         ствол в шесть метров с одним повтором коры выглядит фанерным. Повтор
         вписан в развёртку, а НЕ в `texture.repeat`: набор текстур окна общий
         на все редакторы и кэширует по ключу, куда repeat входит, — правка там
         однажды поехала бы вслед за корой в чужом редакторе. */
      parts.uv.push(side / sides, t * tile);
      parts.colour.push(1, 1, 1);
    }
  }

  /* Обход именно такой, а не «как получилось»: сторона у коры лицевая, и
     вывернутая труба пропадает из кадра целиком, оставив дерево одной листвой
     в воздухе. */
  const stride = sides + 1;
  for (let ring = 0; ring + 1 < rings.length; ring += 1) {
    for (let side = 0; side < sides; side += 1) {
      const a = start + ring * stride + side;
      const b = a + 1;
      const c = a + stride;
      const d = c + 1;
      parts.index.push(a, b, c, b, d, c);
    }
  }
}

/**
 * Переходник сцены для окна превью.
 *
 * `onAssets` вызывается один раз при монтировании: им редактор узнаёт, нашлась
 * ли растительность в установленной игре, и пишет под кадром правду вместо
 * догадки. `onStats` — замеры кадра (вызовы отрисовки, треугольники, сколько
 * травинок нарисовано), не чаще двух раз в секунду.
 */
export function createVegetationScene(options = {}) {
  const onAssets =
    typeof options.onAssets === "function" ? options.onAssets : null;
  const onStats =
    typeof options.onStats === "function" ? options.onStats : null;
  const onEdit = typeof options.onEdit === "function" ? options.onEdit : null;
  let project = createVegetationProject(options.project);
  let built = null;
  let context = null;
  let assets = [];
  let coverKey = "";
  let statsAt = 0;
  /* Ручки прямо в поле: стрела ветра, бусина дальности и столбик высоты. Жест
     разбирает сцена — только она знает, попал ли указатель в ручку, — а правку
     несёт наружу `onEdit`, тем же путём, что и ползунок инспектора. */
  let gizmos = null;
  let canvas = null;
  let drag = null;
  let hovered = "";

  /* ---------- текстуры ---------- */

  function dataTexture(THREE, pixels, { colour = true } = {}) {
    const texture = new THREE.DataTexture(
      pixels.data,
      pixels.width,
      pixels.height,
      THREE.RGBAFormat,
    );
    texture.wrapS = THREE.RepeatWrapping;
    texture.wrapT = THREE.RepeatWrapping;
    if (colour) texture.colorSpace = THREE.SRGBColorSpace;
    texture.magFilter = THREE.LinearFilter;
    /* Мип-уровни у `DataTexture` выключены по умолчанию, а без них трава в
       двадцати метрах закипает муаром — на альфа-тесте это видно резче, чем на
       асфальте: кипит не зерно, а сам силуэт. Сторона — степень двойки. */
    texture.minFilter = THREE.LinearMipmapLinearFilter;
    texture.generateMipmaps = true;
    texture.needsUpdate = true;
    return texture;
  }

  /** Столько выборок, сколько даёт видеокарта, но не больше разумного. */
  function sharpen(ctx, texture) {
    if (!texture || texture.anisotropy === undefined) return texture;
    const most = ctx.renderer?.capabilities?.getMaxAnisotropy?.() ?? 1;
    texture.anisotropy = Math.max(texture.anisotropy || 1, Math.min(8, most));
    texture.needsUpdate = true;
    return texture;
  }

  const hasAsset = (id) => assets.some((entry) => entry.id === id);

  /**
   * Текстура из игры, если она там есть.
   *
   * Загрузку файла делает набор окна: он один на все редакторы, он же кэширует
   * и он же освобождает. Поэтому чужая текстура помечается «не наша» —
   * освобождать её отсюда значило бы выдернуть её из-под соседнего редактора.
   */
  function gameTexture(ctx, id) {
    if (!hasAsset(id) || typeof ctx.assets?.texture !== "function") return null;
    try {
      return (
        ctx.assets.texture(id, {
          /* Картинка доезжает не в этом кадре, а окно рисует по требованию:
             без сигнала листва осталась бы своей отрисовкой до первого
             движения мыши. */
          onLoad: () => ctx.requestRender?.(),
        }) || null
      );
    } catch {
      return null;
    }
  }

  function gameNormal(ctx, id) {
    if (!hasAsset(id) || typeof ctx.assets?.normalTexture !== "function")
      return null;
    try {
      return (
        ctx.assets.normalTexture(id, {
          onLoad: () => ctx.requestRender?.(),
        }) || null
      );
    } catch {
      return null;
    }
  }

  /* ---------- геометрия ---------- */

  /**
   * Крест из плоскостей: растение, у которого нет «лица».
   *
   * Треугольники продублированы с обратным обходом, а сторона материала
   * оставлена лицевой. Так дешевле, чем `DoubleSide`: у двусторонней карточки
   * three переворачивает нормаль на изнанке, и трава чернеет ровно наполовину —
   * с той стороны, откуда на неё как раз и смотрят. Обратный треугольник рядом
   * решает это без единой строки в шейдере, а фрагментов не прибавляет: из двух
   * совпавших видно всегда один.
   *
   * `bulge` — чью форму изображает нормаль. Ноль: веер, расходящийся от оси
   * пучка, — так стоит трава. Единица: шар, у которого низ смотрит вниз, а верх
   * вверх, — так стоят куст и крона. Смысл в том, что нормаль здесь описывает
   * РАСТЕНИЕ, а не карточку: честная нормаль плоскости даёт жесть (половина
   * куста чёрная, половина белая), а прежняя нормаль строго вверх давала
   * постоянный N·L, то есть зелёный фетр без светлого и тёмного бока. Подробно
   * — в шапке `vegetation-shader.js`.
   */
  function crossGeometry(THREE, planes, { bulge = 0 } = {}) {
    const parts = emptyMesh();
    /* Насколько нормаль расходится вбок. Меньше — растение читается плоским,
       больше — крайние вершины карточки уходят светом в стороны, и куст
       начинает бликовать краями. */
    const lateral = 0.75;
    for (let plane = 0; plane < planes; plane += 1) {
      const angle = (Math.PI * plane) / planes;
      const dx = Math.cos(angle) * 0.5;
      const dz = Math.sin(angle) * 0.5;
      const base = plane * 4;
      parts.position.push(-dx, 0, -dz, dx, 0, dz, dx, 1, dz, -dx, 1, -dz);
      parts.uv.push(0, 0, 1, 0, 1, 1, 0, 1);
      /* Плоскости креста притушены по очереди. Крест из одинаково ярких
         плоскостей читается буквой «икс» ровно в тот момент, когда одна из них
         поворачивается к зрителю ребром, — а поворачивается она постоянно. */
      const shade = 1 - (plane / Math.max(1, planes - 1)) * 0.14;
      for (const [side, height] of [
        [-1, 0],
        [1, 0],
        [1, 1],
        [-1, 1],
      ]) {
        parts.normal.push(
          side * dx * 2 * lateral,
          1 - bulge + (height - 0.5) * 2 * bulge,
          side * dz * 2 * lateral,
        );
        parts.colour.push(shade, shade, shade);
      }
      parts.index.push(base, base + 1, base + 2, base, base + 2, base + 3);
      parts.index.push(base + 2, base + 1, base, base + 3, base + 2, base);
    }
    const geometry = finishMesh(THREE, parts);
    geometry.normalizeNormals();
    return geometry;
  }

  /**
   * Ком листвы: карточки, разложенные по поверхности воображаемого кома.
   *
   * Крест из трёх плоскостей — это три прямоугольника, стоящие в одной точке, и
   * с любого ракурса один из них смотрит на зрителя плашмя. Отсюда и берётся
   * «картонность»: силуэт куста и кроны узнаётся с одного взгляда и повторяется
   * на всех экземплярах в кадре. Настоящая крона в игре собрана иначе — из
   * десятков мелких карточек с листвой, лежащих ПО ОБОЛОЧКЕ кроны; ни одного
   * ребра во весь объект в ней нет, а объём даёт то, что карточки смотрят в
   * разные стороны.
   *
   * Здесь ровно это: карточки садятся на ком по спирали золотого угла (она
   * покрывает сферу без полос и без сгущений у полюсов), нормаль у каждой —
   * наружу от центра кома, а плоскость карточки этой нормали перпендикулярна,
   * то есть повёрнута к зрителю лицом со своей стороны кома. Поворот вокруг
   * нормали свой у каждой карточки: без него все они встают «вверх ногами
   * одинаково» и ком снова читается сеткой.
   *
   * Ком укладывается ровно в ту же единичную коробку, что и крест
   * (xz ∈ [-0.5, 0.5], y ∈ [0, 1]), и подгонка в конце не косметическая: по
   * половине ширины карточки считается коробка теней (см. `SHADOW_EXTENT`), и
   * ком, вылезший за коробку, потерял бы тень целиком.
   */
  function clusterGeometry(
    THREE,
    {
      cards = 6,
      seed = 7,
      lowest = -0.9,
      squash = 1,
      size = 0.9,
      /* Долей у кома. Единица — шар (крона: её объём собирают восемнадцать
         таких комьев снаружи). Больше — сросшиеся доли, силуэт несимметричен и
         поворот экземпляра его в самом деле меняет (куст). */
      lobes = 1,
    } = {},
  ) {
    const parts = emptyMesh();
    const random = seeded(seed);
    /* Золотой угол: соседние карточки расходятся по кругу на несоизмеримую
       долю оборота, и никакое их число не складывается в лучи. */
    const golden = Math.PI * (3 - Math.sqrt(5));

    /* Центры долей считаются заранее и одним проходом: карточка обязана знать
       свою долю до того, как встанет на место. Доли разведены по горизонту
       золотым углом и подняты на разную высоту — иначе они складываются в
       трилистник, лежащий одним блином. */
    const centres = [];
    for (let lobe = 0; lobe < lobes; lobe += 1) {
      if (lobes === 1) {
        centres.push([0, 0, 0, 1]);
        continue;
      }
      const turn = lobe * golden + 0.4;
      /* Вбок доли расходятся меньше, чем вверх, и это не вкус: ком целиком
         вписывается в единичную коробку по САМОЙ широкой оси (см.
         `fitToUnitBox`), и доли, разъехавшиеся по горизонту, придавливают
         куст к земле блином вместо того, чтобы его нарастить. */
      const away = 0.14 + random() * 0.16;
      centres.push([
        Math.cos(turn) * away,
        (random() - 0.3) * 0.6,
        Math.sin(turn) * away,
        /* Своя величина у каждой доли: три одинаковых шара — это снеговик. */
        0.66 + random() * 0.34,
      ]);
    }

    for (let card = 0; card < cards; card += 1) {
      const lobe = centres[card % lobes];
      /* Широты берутся равномерно по ВЫСОТЕ кома, а не по углу: равномерный
         угол сгущает карточки у полюсов, и у кроны получается шапка. Индекс
         внутри доли, а не общий: иначе карточки одной доли садятся все на одну
         широту, и доля выходит блином. */
      const inLobe = Math.floor(card / lobes);
      const perLobe = Math.ceil(cards / lobes);
      const up = 1 - ((inLobe + 0.5) / perLobe) * (1 - lowest);
      const ring = Math.sqrt(Math.max(0, 1 - up * up));
      const turn = card * golden + random() * 0.7;
      const out = [Math.cos(turn) * ring, up, Math.sin(turn) * ring];

      /* Базис в плоскости карточки. Опорой служит мировая вертикаль, а у самого
         верха кома, где она сливается с нормалью, — горизонталь: иначе базис
         вырождается и карточка схлопывается в отрезок. */
      const anchor = Math.abs(out[1]) > 0.86 ? [1, 0, 0] : [0, 1, 0];
      const along = dot(anchor, out);
      const first = unit([
        anchor[0] - out[0] * along,
        anchor[1] - out[1] * along,
        anchor[2] - out[2] * along,
      ]);
      const second = cross(out, first);
      const roll = (random() - 0.5) * 1.5;
      const rise = [
        first[0] * Math.cos(roll) + second[0] * Math.sin(roll),
        first[1] * Math.cos(roll) + second[1] * Math.sin(roll),
        first[2] * Math.cos(roll) + second[2] * Math.sin(roll),
      ];
      const side = cross(rise, out);

      /* Часть карточек уходит внутрь кома. Разложенные строго по оболочке, они
         дают полый шар: сквозь просветы видно небо там, где у настоящей кроны
         густая тень. */
      const pull = (0.58 + random() * 0.42) * lobe[3];
      const wide = size * lobe[3] * (0.82 + random() * 0.4);
      const centre = [
        lobe[0] + out[0] * pull,
        lobe[1] + out[1] * pull * squash,
        lobe[2] + out[2] * pull,
      ];
      /* Карточка стоит комлем к центру кома: у листвы стебель нарисован снизу
         картинки, и повёрнутая наоборот она растёт из воздуха наружу внутрь. */
      const origin = [
        centre[0] - side[0] * wide * 0.5 - rise[0] * wide * 0.42,
        centre[1] - side[1] * wide * 0.5 - rise[1] * wide * 0.42,
        centre[2] - side[2] * wide * 0.5 - rise[2] * wide * 0.42,
      ];

      /*
       * Затенение вглубь кома — вершинным цветом, а не второй текстурой.
       *
       * Внутри кроны темно, и без этого ком светится насквозь одинаково ярко:
       * получается облако, а не крона. Карточки, утянутые внутрь и смотрящие
       * вниз, темнее; наружные и верхние — светлее.
       */
      const shade = (0.5 + 0.5 * pull) * (0.74 + 0.26 * (out[1] * 0.5 + 0.5));
      /* Зеркалим половину карточек прямо в развёртке: поэкземплярное отражение
         в шейдере разворачивает ВЕСЬ ком разом, а нам нужно, чтобы соседние
         карточки одного кома не были одной и той же картинкой. */
      const flip = random() < 0.5;
      const base = parts.position.length / 3;
      for (const [u, v] of [
        [0, 0],
        [1, 0],
        [1, 1],
        [0, 1],
      ]) {
        parts.position.push(
          origin[0] + side[0] * u * wide + rise[0] * v * wide,
          origin[1] + side[1] * u * wide + rise[1] * v * wide,
          origin[2] + side[2] * u * wide + rise[2] * v * wide,
        );
        parts.uv.push(flip ? 1 - u : u, v);
        parts.normal.push(out[0], out[1], out[2]);
        parts.colour.push(shade, shade, shade);
      }
      parts.index.push(base, base + 1, base + 2, base, base + 2, base + 3);
      parts.index.push(base + 2, base + 1, base, base + 3, base + 2, base);
    }

    fitToUnitBox(parts.position);
    return finishMesh(THREE, parts);
  }

  /**
   * Дерево: ствол с комлем и сучья.
   *
   * Гранёный столб был виден с двух метров и оставался столбом даже с
   * четырнадцатью гранями: дереву не хватало не граней, а СУЧЬЕВ. Ствол,
   * уходящий в крону одной палкой, читается вкопанным бревном, потому что у
   * него нет места, откуда крона растёт; четыре сука разводят силуэт и связывают
   * ствол с комьями листвы над ним.
   *
   * Толщина ствола вписана в геометрию, а не в матрицу экземпляра, и это
   * условие сучьев, а не вкусовщина. Прежде матрица сжимала дерево по X и Z в
   * `TRUNK_GIRTH` раз — сук, отведённый вбок, вышел бы из этого сжатия плоской
   * лентой, а отвести его настолько же дальше значило бы держать в буфере
   * координаты, которых в кадре нет. Теперь масштаб экземпляра равномерный, и
   * метр вбок — это метр вбок.
   */
  function treeShape(THREE) {
    const parts = emptyMesh();

    /*
     * Сучья расставлены по золотому углу вокруг ствола, а не по четвертям:
     * четыре сука через девяносто градусов складываются в крест, и дерево
     * читается телеграфным столбом с траверсами.
     */
    const golden = Math.PI * (3 - Math.sqrt(5));
    const random = seeded(31337);
    limbInto(parts, {
      from: [0, 0, 0],
      to: [0.028, 1, -0.02],
      /* Ствол не отвес: чуть выгнутый ствол читается выросшим, прямой —
         поставленным. */
      bow: [-0.026, 0, 0.016],
      radius: (t) => trunkRadius(t) * trunkFlare(t),
      /* Пояса сгущены к земле: комель — это экспонента, и на равномерных
         поясах от неё остаётся конус. */
      rings: [0, 0.015, 0.04, 0.08, 0.15, 0.26, 0.4, 0.56, 0.74, 1],
      sides: 14,
      /*
       * Повторов коры по стволу.
       *
       * Было 2.4 — то есть один повтор на два с лишним метра ствола. Плиты
       * коры в этой картинке идут пятью поясами на повтор (`BARK_ALONG`), и на
       * таком растяжении пояс выходит в полметра: с трёх шагов у ствола нет
       * никакого зерна, он читается выбеленным столбом. Шесть повторов дают
       * пояс в двадцать сантиметров — размер настоящей плиты коры, и он виден
       * в кадре как зерно, а не как полосы.
       */
      tile: 6,
    });

    for (let branch = 0; branch < TRUNK_BRANCHES; branch += 1) {
      /*
       * Сучья убраны внутрь кроны — и по высоте, и по вылету.
       *
       * Стояли от 0.4 высоты и на треть её вбок, то есть нижний сук выходил из
       * кроны снизу, а дальний протыкал её насквозь: в кадре это тонкие тёмные
       * прутья, торчащие за силуэт, и они же подчёркивают каждый просвет между
       * комьями. Крона занимает 0.38…1.22 высоты и 0.48 вбок (см.
       * `CANOPY_CENTRE` и соседей) — сук обязан кончаться внутри этих границ, а
       * не на них.
       */
      const along = 0.5 + (branch / (TRUNK_BRANCHES - 1)) * 0.34;
      const turn = branch * golden + 0.6;
      const reach = 0.14 + random() * 0.1;
      const lift = 0.12 + random() * 0.1;
      const thick = trunkRadius(along) * trunkFlare(along) * 0.6;
      const face = [Math.cos(turn), 0, Math.sin(turn)];
      limbInto(parts, {
        /* Сук начинается ВНУТРИ ствола: выйдя из его поверхности, он оставляет
           на стыке кольцевую щель, сквозь которую видно небо. */
        from: [face[0] * thick * 0.5, along, face[2] * thick * 0.5],
        to: [face[0] * reach, along + lift, face[2] * reach],
        /* Сук выгибается вверх: прямой отросток под углом читается подпоркой. */
        bow: [0, lift * 0.42, 0],
        radius: (t) => thick * (1 - t * 0.72),
        rings: [0, 0.3, 0.62, 1],
        sides: 7,
        /* Сук вчетверо короче ствола — и повторов у него во столько же
           меньше: одна и та же кора обязана идти по ним ОДНИМ размером
           зерна, иначе сук выглядит другой породы. */
        tile: 1.6,
      });
    }

    return finishMesh(THREE, parts);
  }

  /* ---------- материалы ---------- */

  /**
   * Материал листвы: один на тип растения, общий для всех его экземпляров.
   *
   * Униформы держатся своим объектом рядом с материалом, потому что писать в
   * них надо каждый кадр, а лезть за ними в `material.userData.shader` —
   * значит зависеть от того, скомпилировался ли шейдер. До первого кадра он не
   * скомпилирован, и первое же значение ветра уехало бы в никуда.
   *
   * Свет берётся своими униформами (`uSunDir`, `uSunColour`) из `ctx.sun`, а не
   * из `directionalLights[]`: иначе просвечивание зависело бы от того, сколько
   * ламп три скомпилировал в программу, а это число окно вправе менять.
   */
  function foliageMaterial(
    ctx,
    {
      sway,
      field = 1,
      yaw = 0,
      patch = 0.02,
      thin = 0,
      ground = 0,
      transmit,
      root,
      /* Тянуть ли карточку под пропорции картинки. У креста — да: там карточка
         и есть картинка. У кома — нет: там картинок семь, они смотрят в разные
         стороны, и растягивать по одной пропорции пришлось бы весь ком. */
      stretch = false,
    },
  ) {
    const { THREE } = ctx;
    const uniforms = {
      uTime: { value: 0 },
      uWind: { value: 0 },
      uWindSpeed: { value: 1 },
      uWindDir: { value: new THREE.Vector2(0, 1) },
      uHeight: { value: 1 },
      uSpread: { value: 0 },
      uAspect: { value: 1 },
      uSway: { value: sway },
      /* Метры на единицу места экземпляра. У травы и подстилки — дальность
         прорисовки (места лежат в единичном круге), у куста и кроны — единица:
         их места уже в метрах, потому что они не растягиваются вслед за
         травой. */
      uField: { value: field },
      /* Кто крутит растение вокруг оси: единица — шейдер, ноль — матрица. */
      uYaw: { value: yaw },
      uDistance: { value: GRASS_MAX_RADIUS },
      /* Размер куртин: единица, делённая на метры пятна. */
      uPatch: { value: patch },
      /* Прореживать ли по куртинам и по краю поля. У куста и дерева ноль: их
         десятки, и потерять из них случайную половину значит потерять кадр. */
      uThin: { value: thin },
      /* Садиться ли на рельеф в шейдере. У куста и дерева ноль — их высота уже
         стоит в матрице, потому что по ней строится тень. */
      uGround: { value: ground },
      uTintSpread: { value: 0 },
      uTint: { value: new THREE.Color(1, 1, 1) },
      uSunDir: { value: new THREE.Vector3(0, 1, 0) },
      uSunColour: { value: new THREE.Color(0, 0, 0) },
      /* Насколько узок ореол просвечивания вокруг солнца. Круче — просвет
         виден только когда смотришь прямо в солнце сквозь крону, положе —
         светится вся листва подряд и перестаёт быть событием. */
      uSunPower: { value: 2.6 },
      uTransmit: { value: transmit },
      uRootShade: { value: root },
    };
    const material = new THREE.MeshLambertMaterial({
      /* Ламберт, а не «стандартный»: у травы нет ни бликов, ни металла, а
         разница в цене на шестидесяти тысячах экземпляров — это разница между
         окном и слайд-шоу. Просвечивание при этом дописано своим членом: в
         ламберте его нет, а без него вся работа с часами суток бессмысленна. */
      alphaTest: ALPHA_TEST,
      transparent: false,
      side: THREE.FrontSide,
      /* Вершинный цвет несёт запечённое затенение вглубь кома листвы и разводку
         плоскостей креста по яркости (см. `finishMesh`). Он включён у ВСЕХ
         четырёх материалов листвы, хотя кресту нужен слабее: программа у них
         одна на всех по общему ключу кэша, и включённый через раз он собрал бы
         две программы вместо одной. */
      vertexColors: true,
    });
    /*
     * КАРТЫ НОРМАЛЕЙ У ЛИСТВЫ НЕТ, и это не «не дошли руки».
     *
     * Тангенциальная карта нормалей требует базиса, лежащего в плоскости той
     * САМОЙ карточки, по которой натянута развёртка. Базиса с тангентами у нас
     * нет, и three строит его сам (`getTangentFrame`) из экранных производных —
     * но строит ортогонально ТОЙ нормали, которую ему дали, а дали мы ему
     * нормаль объёма (см. `PLANT_NORMAL`), которая карточке не перпендикулярна:
     * у кроны она уходит от неё до шестидесяти градусов. Базис получается
     * перекошенным относительно текселей, и карта поворачивает нормаль не туда,
     * куда нарисовано. Прежний отказ был по этой же причине (тогда нормаль
     * стояла строго вверх), и нормаль объёма её не сняла, а только переназвала.
     *
     * Заодно это выборка текстуры, которой нет у самого дорогого материала
     * сцены. Кора и земля карты нормалей носят: у них нормаль настоящая,
     * геометрическая, и базис от неё честный.
     */
    material.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, uniforms);
      shader.vertexShader = shader.vertexShader
        .replace(
          "void main() {",
          `${PLANT_HEAD}\n${PLANT_VARYINGS}\nvoid main() {`,
        )
        .replace("#include <uv_vertex>", `#include <uv_vertex>\n${PLANT_UV}`)
        .replace(
          "#include <beginnormal_vertex>",
          `#include <beginnormal_vertex>\n${PLANT_NORMAL}`,
        )
        .replace(
          "#include <begin_vertex>",
          `#include <begin_vertex>\n${PLANT_APPLY}`,
        );
      shader.fragmentShader = shader.fragmentShader
        .replace("void main() {", `${PLANT_FRAGMENT_HEAD}\nvoid main() {`)
        .replace(
          "#include <map_fragment>",
          `#include <map_fragment>\n${PLANT_FRAGMENT_MAP}`,
        )
        .replace(
          "#include <lights_fragment_end>",
          `#include <lights_fragment_end>\n${PLANT_FRAGMENT_LIGHT}`,
        );
    };
    /* Ключ кэша программ общий: правка у всех материалов листвы одна и та же,
       и без общего ключа three собрал бы четыре одинаковые программы. */
    material.customProgramCacheKey = () => "astral-vegetation-foliage";
    material.userData.uniforms = uniforms;
    material.userData.stretch = stretch;
    return material;
  }

  /**
   * Материал глубины листвы: та же альфа и ТОТ ЖЕ изгиб.
   *
   * Без своей альфы three рисует в карту теней прямоугольник карточки, и под
   * деревом ложится тень от щита, а не от кроны. Без изгиба крона ходит по
   * ветру, а её тень стоит намертво: при ненаправленном качании в семь сотых
   * расхождение было меньше дециметра и его прощали, при направленном ветре оно
   * измеряется метром и читается как поломка. Униформы берутся ТЕМ ЖЕ
   * объектом, что у освещённого материала, — не «такие же», а те же самые:
   * копия разошлась бы на первом же кадре.
   */
  function depthMaterial(ctx, uniforms) {
    const { THREE } = ctx;
    const material = new THREE.MeshDepthMaterial({
      depthPacking: THREE.RGBADepthPacking,
      alphaTest: ALPHA_TEST,
    });
    material.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, uniforms);
      shader.vertexShader = shader.vertexShader
        .replace("void main() {", `${PLANT_HEAD}\nvoid main() {`)
        .replace("#include <uv_vertex>", `#include <uv_vertex>\n${PLANT_UV}`)
        .replace(
          "#include <begin_vertex>",
          `#include <begin_vertex>\n${PLANT_DEPTH}`,
        );
    };
    material.customProgramCacheKey = () => "astral-vegetation-depth";
    return material;
  }

  /* ---------- сборка ---------- */

  function build(ctx) {
    const { THREE, scene } = ctx;
    const root = new THREE.Group();
    root.name = "astral-vegetation";

    const grassGeometry = crossGeometry(THREE, GRASS_PLANES);
    const litterGeometry = crossGeometry(THREE, GRASS_PLANES, { bulge: 0.3 });
    /* Куст приземистее кроны и снизу карточек почти не имеет: он стоит на
       земле, и всё, что уходит ниже его основания, оказывается под грунтом. */
    const shrubGeometry = clusterGeometry(THREE, {
      cards: BUSH_CARDS,
      seed: 617,
      lowest: -0.25,
      squash: 0.9,
      /* Карточка мельче прежней (было 0.86 при семи штуках): три десятка
         карточек прежнего размера — это не куст, а зелёный шар без просветов, и
         рваного края у него нет вовсе. */
      size: 0.7,
      lobes: BUSH_LOBES,
    });
    /* Крону обходят кругом и смотрят на неё снизу — карточки идут по всему
       кому, включая исподнее. Долей одна: доли кроне дают восемнадцать таких
       комьев снаружи, а не карточки внутри одного. */
    const canopyGeometry = clusterGeometry(THREE, {
      cards: CANOPY_CARDS,
      seed: 1093,
      lowest: -0.86,
      squash: 0.94,
      size: 0.94,
    });
    const trunkGeometry = treeShape(THREE);
    /* Плита повёрнута ГЕОМЕТРИЕЙ, а не мешем: рельеф смещает вершины по местной
       оси Y, и у повёрнутого меша «вверх» оказалось бы местным -Z. */
    const groundGeometry = new THREE.PlaneGeometry(
      1,
      1,
      GROUND_SEGMENTS,
      GROUND_SEGMENTS,
    );
    groundGeometry.rotateX(-Math.PI / 2);

    /*
     * Сила просвечивания растёт от травы к кроне, и это не вкус.
     *
     * У травы против солнца просвечивает всё, что не корень, но травинка
     * толстая и стоит одна; у кроны свет идёт сквозь листву слой за слоем и на
     * выходе окрашен ею сильнее всего. Числа выведены из закатного кадра: при
     * ключе 20.9 и небе 2.3 (замер в шапке `PLANT_FRAGMENT_LIGHT`) крона выходит
     * в яркость неба ровно около единицы, и это тот кадр, ради которого
     * просвечивание вообще заведено.
     */
    const grassMaterial = foliageMaterial(ctx, {
      sway: 0.55,
      yaw: 1,
      patch: 1 / 9,
      thin: 1,
      ground: 1,
      transmit: 0.62,
      root: 0.42,
      stretch: true,
    });
    const litterMaterial = foliageMaterial(ctx, {
      sway: 0.32,
      yaw: 1,
      patch: 1 / 5,
      thin: 1,
      ground: 1,
      transmit: 0.5,
      root: 0.5,
      stretch: true,
    });
    const bushMaterial = foliageMaterial(ctx, {
      sway: 0.18,
      patch: 0.02,
      transmit: 0.72,
      root: 0.48,
    });
    const canopyMaterial = foliageMaterial(ctx, {
      sway: 0.14,
      patch: 0.02,
      transmit: 0.82,
      root: 0.52,
    });
    const barkMaterial = new THREE.MeshStandardMaterial({
      roughness: 0.95,
      metalness: 0,
    });
    const barkUniforms = {
      uTime: { value: 0 },
      uWind: { value: 0 },
      uWindSpeed: { value: 1 },
      uWindDir: { value: new THREE.Vector2(0, 1) },
      /* Ствол качается на порядок слабее кроны: дерево гнётся не стволом. */
      uSway: { value: 0.035 },
    };
    barkMaterial.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, barkUniforms);
      shader.vertexShader = shader.vertexShader
        .replace("void main() {", `${TRUNK_HEAD}\nvoid main() {`)
        .replace(
          "#include <begin_vertex>",
          `#include <begin_vertex>\n${TRUNK_APPLY}`,
        );
    };
    barkMaterial.customProgramCacheKey = () => "astral-vegetation-bark";
    barkMaterial.userData.uniforms = barkUniforms;

    const groundMaterial = new THREE.MeshStandardMaterial({
      roughness: 1,
      metalness: 0,
    });
    const groundUniforms = {
      uFieldTint: { value: new THREE.Color(1, 1, 1) },
      uFieldRadius: { value: 24 },
    };
    groundMaterial.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, groundUniforms);
      shader.vertexShader = shader.vertexShader
        .replace("void main() {", `${GROUND_HEAD}\nvoid main() {`)
        .replace(
          "#include <beginnormal_vertex>",
          `#include <beginnormal_vertex>\n${GROUND_NORMAL}`,
        )
        .replace(
          "#include <begin_vertex>",
          `#include <begin_vertex>\n${GROUND_APPLY}`,
        );
      shader.fragmentShader = shader.fragmentShader
        .replace("void main() {", `${GROUND_FRAGMENT_HEAD}\nvoid main() {`)
        .replace(
          "#include <map_fragment>",
          `#include <map_fragment>\n${GROUND_FRAGMENT_BODY}`,
        );
    };
    groundMaterial.customProgramCacheKey = () => "astral-vegetation-ground";
    groundMaterial.userData.uniforms = groundUniforms;

    const instanced = (geometry, material, capacity, name) => {
      const mesh = new THREE.InstancedMesh(geometry, material, capacity);
      mesh.name = name;
      /*
       * Отсечение по пирамиде выключено намеренно. Габарит `InstancedMesh`
       * three считает по геометрии и матрицам, а у нас в матрицах стоит
       * единичный масштаб: настоящий размер задаёт шейдер. Габарит поэтому
       * выходит с карточку величиной, и поле пропадает целиком, стоит камере
       * отвернуться от нуля. Поле и так всё время вокруг камеры — отсекать в
       * нём нечего.
       */
      mesh.frustumCulled = false;
      /*
       * Тень трава не бросает.
       *
       * Не «не успели»: тень от карточки с альфа-тестом и вершинным ветром —
       * это второй полный проход по тем же тысячам экземпляров. Цена — второй
       * такой же кадр, а видно на траве газонной высоты серую дымку. Глубину
       * слою травы даёт затенение у корня во фрагментном шейдере — на порядок
       * дешевле и почти так же убедительно. Тень бросают те, у кого есть рост:
       * кусты и деревья.
       */
      mesh.castShadow = false;
      mesh.receiveShadow = true;
      root.add(mesh);
      return mesh;
    };

    const grass = instanced(
      grassGeometry,
      grassMaterial,
      GRASS_CAPACITY,
      "vegetation-grass",
    );
    const litter = instanced(
      litterGeometry,
      litterMaterial,
      LITTER_CAPACITY,
      "vegetation-litter",
    );
    const bush = instanced(
      shrubGeometry,
      bushMaterial,
      BUSH_CAPACITY,
      "vegetation-bush",
    );
    const canopy = instanced(
      canopyGeometry,
      canopyMaterial,
      TREE_CAPACITY * CANOPY_PER_TREE,
      "vegetation-canopy",
    );
    const trunk = instanced(
      trunkGeometry,
      barkMaterial,
      TREE_CAPACITY,
      "vegetation-trunk",
    );
    trunk.castShadow = true;

    /*
     * Условие на текстуры куста и кроны: их картинки обязаны быть квадратными
     * либо иметь ту же пропорцию, что задана `uAspect`. Пропорции карточки
     * шейдер берёт из размера картинки, и материал глубины теперь берёт их
     * оттуда же — но только потому, что считает ТУ ЖЕ функцию. Поставите кроне
     * прямоугольный атлас — проверьте, что тень не разъехалась.
     */
    bush.castShadow = true;
    bush.customDepthMaterial = depthMaterial(
      ctx,
      bushMaterial.userData.uniforms,
    );
    canopy.castShadow = true;
    canopy.customDepthMaterial = depthMaterial(
      ctx,
      canopyMaterial.userData.uniforms,
    );

    const ground = new THREE.Mesh(groundGeometry, groundMaterial);
    ground.name = "vegetation-ground";
    ground.position.y = -0.01;
    ground.receiveShadow = true;
    root.add(ground);

    built = {
      root,
      scene,
      textures: [],
      geometries: [
        grassGeometry,
        litterGeometry,
        shrubGeometry,
        canopyGeometry,
        trunkGeometry,
        groundGeometry,
      ],
      materials: {
        grass: grassMaterial,
        litter: litterMaterial,
        bush: bushMaterial,
        canopy: canopyMaterial,
        bark: barkMaterial,
        ground: groundMaterial,
      },
      depth: [bush.customDepthMaterial, canopy.customDepthMaterial],
      meshes: { grass, litter, bush, canopy, trunk, ground },
      /* Белый под рукой: подмешивать его в цвет земли надо каждый кадр, а
         заводить объект цвета шестьдесят раз в секунду — это мусор на ровном
         месте. */
      white: new THREE.Color(1, 1, 1),
      sunDir: new THREE.Vector3(0, 1, 0),
      groundSpan: 0,
      groundTile: 4,
      /* Ни то, ни другое не «ещё не считали»: оба сравниваются с посчитанным и
         обязаны при первом сравнении не совпасть. */
      fogNear: 0,
      coverage: null,
    };

    seedInstances(ctx);
    scene.add(root);
  }

  /**
   * Матрицы и семена экземпляров. Считаются ОДИН раз за всю жизнь сцены.
   *
   * Трава и подстилка стоят единичным масштабом: рост, наклон, ветер и рельеф
   * им задаёт шейдер, и матрица нужна только под место. У кустов и деревьев
   * наоборот — и размер, и высота рельефа вписаны в матрицу, потому что по ней
   * же строится их тень, а тень обязана совпадать с тем, что стоит на земле.
   */
  function seedInstances(ctx) {
    const { THREE } = ctx;
    const { meshes } = built;
    const matrix = new THREE.Matrix4();
    const position = new THREE.Vector3();
    const quaternion = new THREE.Quaternion();
    const scale = new THREE.Vector3(1, 1, 1);
    const axis = new THREE.Vector3(0, 1, 0);
    /* Наклон кома: своя ось (горизонтальная) и свой поворот, домноженные на
       поворот вокруг вертикали. Заводятся здесь, а не в цикле: четыреста
       тридцать два кома — это столько же выброшенных объектов. */
    const tiltAxis = new THREE.Vector3();
    const tilt = new THREE.Quaternion();

    const seedAttribute = (mesh, capacity, random) => {
      const data = new Float32Array(capacity * 4);
      for (let index = 0; index < capacity * 4; index += 1) {
        data[index] = random();
      }
      const attribute = new THREE.InstancedBufferAttribute(data, 4);
      mesh.geometry.setAttribute("aSeed", attribute);
      return attribute;
    };

    /*
     * Трава и подстилка.
     *
     * Места лежат в ЕДИНИЧНОМ круге, а не в метрах: в метры их переводит
     * `uField` в шейдере, и от этого зависит, честна ли плотность (см. шапку
     * `astralPlant`). Матрица — чистый перенос, без поворота и масштаба:
     * повёрнутая матрица потребовала бы вносить растяжение поля через обратный
     * поворот, а поворот карточки шейдеру всё равно считать.
     */
    const grassRandom = seeded(1571);
    seedAttribute(meshes.grass, GRASS_CAPACITY, grassRandom);
    for (let index = 0; index < GRASS_CAPACITY; index += 1) {
      const [x, z] = discPoint(index, 1);
      matrix.makeTranslation(x, 0, z);
      meshes.grass.setMatrixAt(index, matrix);
    }
    meshes.grass.instanceMatrix.needsUpdate = true;

    /* Подстилка идёт по своей последовательности с поворотом кольца: возьми она
       ту же, что трава, — и каждый цветок вырос бы в основании пучка. */
    const litterRandom = seeded(6781);
    seedAttribute(meshes.litter, LITTER_CAPACITY, litterRandom);
    for (let index = 0; index < LITTER_CAPACITY; index += 1) {
      const [x, z] = discPoint(index, 1, 0, 0.19);
      matrix.makeTranslation(x, 0, z);
      meshes.litter.setMatrixAt(index, matrix);
    }
    meshes.litter.instanceMatrix.needsUpdate = true;

    /* Кусты */
    const bushRandom = seeded(90210);
    seedAttribute(meshes.bush, BUSH_CAPACITY, bushRandom);
    for (let index = 0; index < BUSH_CAPACITY; index += 1) {
      const [x, z] = discPoint(index, BUSH_RING[1], BUSH_RING[0], 0.37);
      const size =
        BUSH_HEIGHT[0] + bushRandom() * (BUSH_HEIGHT[1] - BUSH_HEIGHT[0]);
      position.set(x, terrainHeight(x, z), z);
      quaternion.setFromAxisAngle(axis, bushRandom() * Math.PI * 2);
      scale.set(size, size, size);
      matrix.compose(position, quaternion, scale);
      meshes.bush.setMatrixAt(index, matrix);
    }
    scale.set(1, 1, 1);
    meshes.bush.instanceMatrix.needsUpdate = true;

    /* Деревья: ствол и кроны считаются одним проходом, иначе крона однажды
       окажется не над своим стволом. */
    const treeRandom = seeded(4242);
    seedAttribute(meshes.canopy, TREE_CAPACITY * CANOPY_PER_TREE, treeRandom);
    seedAttribute(meshes.trunk, TREE_CAPACITY, treeRandom);
    for (let index = 0; index < TREE_CAPACITY; index += 1) {
      const [x, z] = discPoint(index, TREE_RING[1], TREE_RING[0], 0.71);
      const ground = terrainHeight(x, z);
      const height =
        TREE_HEIGHT[0] + treeRandom() * (TREE_HEIGHT[1] - TREE_HEIGHT[0]);
      position.set(x, ground, z);
      quaternion.setFromAxisAngle(axis, treeRandom() * Math.PI * 2);
      /* Масштаб равномерный: обхват ствола вписан в саму геометрию (см.
         `TRUNK_GIRTH` и `treeShape`). Сжатие по горизонтали, которое стояло
         здесь раньше, расплющило бы сучья в ленты. */
      scale.set(height, height, height);
      matrix.compose(position, quaternion, scale);
      meshes.trunk.setMatrixAt(index, matrix);

      /*
       * Комья кроны по ОБЪЁМУ эллипсоида, а не ярусами по высоте.
       *
       * Ярусы давали дыры кольцом вокруг ствола — с любой стороны видно одно и
       * то же окно в небо и голый сук в нём. Здесь направление кома берётся с
       * шара равномерно по высоте (широта — линейно по `up`, долгота — золотым
       * углом), а глубина посадки `pull` идёт своей квазислучайной
       * последовательностью: часть комьев садится на оболочку кроны и держит
       * её силуэт, часть уходит внутрь и закрывает просветы между наружными.
       *
       * Кубический корень у `pull` — не украшение. Возьми долю как есть, и
       * комья сгустятся к центру: объём шара растёт как куб радиуса, а доля
       * индексов — нет, и снаружи крона осталась бы такой же дырявой.
       */
      const golden = Math.PI * (3 - Math.sqrt(5));
      for (let clump = 0; clump < CANOPY_PER_TREE; clump += 1) {
        const up = 1 - ((clump + 0.5) / CANOPY_PER_TREE) * 2;
        const ring = Math.sqrt(Math.max(0, 1 - up * up));
        const turn = clump * golden + index * 1.7;
        const pull = Math.cbrt(
          0.12 + fract(clump * R2_X + index * R2_Y) * 0.88,
        );
        const clumpSize =
          height *
          (CANOPY_CLUMP[0] +
            treeRandom() * (CANOPY_CLUMP[1] - CANOPY_CLUMP[0]));
        position.set(
          x + Math.cos(turn) * ring * pull * height * CANOPY_SPREAD,
          /* Ком вписан в единичную коробку НИЗОМ в ноль (см. `fitToUnitBox`),
             поэтому его середина стоит на полразмера выше места экземпляра, и
             это полразмера здесь вычитается: иначе вся крона всплывает. */
          ground +
            height * CANOPY_CENTRE +
            up * pull * height * CANOPY_RISE -
            clumpSize * 0.5,
          z + Math.sin(turn) * ring * pull * height * CANOPY_SPREAD,
        );
        /* Поворот вокруг вертикали, а поверх него — завал набок вокруг своей
           горизонтальной оси. Без завала комья стоят строем: у кома есть верх
           и низ (карточки светлее сверху), и восемнадцать одинаково
           ориентированных комьев читаются одной большой картинкой. */
        quaternion.setFromAxisAngle(axis, treeRandom() * Math.PI * 2);
        const lean = treeRandom() * Math.PI * 2;
        tiltAxis.set(Math.cos(lean), 0, Math.sin(lean));
        tilt.setFromAxisAngle(tiltAxis, (treeRandom() - 0.5) * 2 * CANOPY_TILT);
        quaternion.premultiply(tilt);
        scale.set(clumpSize, clumpSize, clumpSize);
        matrix.compose(position, quaternion, scale);
        meshes.canopy.setMatrixAt(index * CANOPY_PER_TREE + clump, matrix);
      }
    }
    scale.set(1, 1, 1);
    meshes.trunk.instanceMatrix.needsUpdate = true;
    meshes.canopy.instanceMatrix.needsUpdate = true;
  }

  /* ---------- пересборка по частям ---------- */

  /** Ключ покрова: всё, от чего зависят текстуры, и ничего сверх того. */
  const coverKeyOf = (value) => `${value.cover.kind}|${value.cover.groundId}`;

  /**
   * Смена покрова.
   *
   * Единственное место, где вообще что-то пересобирается, — и то это карты
   * материалов, а не геометрия и не буферы экземпляров. Ползунки сюда не
   * заходят: ни один из них покрова не меняет.
   */
  function ensureCover(ctx) {
    const key = coverKeyOf(project);
    if (key === coverKey) return;
    coverKey = key;

    const cover = coverById(project.cover.kind);
    const { materials } = built;

    const own = (pixels, options) => {
      const texture = dataTexture(ctx.THREE, pixels, options);
      built.textures.push(texture);
      return texture;
    };

    /* Своё освобождается, чужое только отпускается: текстуры игры принадлежат
       набору окна и живут дольше этой сцены. */
    const release = (texture) => {
      const owned = built.textures.indexOf(texture);
      if (owned >= 0) {
        texture.dispose?.();
        built.textures.splice(owned, 1);
      }
    };

    const swap = (material, slot, texture) => {
      release(material[slot]);
      material[slot] = texture;
      material.needsUpdate = true;
      return texture;
    };

    swap(
      materials.grass,
      "map",
      gameTexture(ctx, cover.blade) ||
        own(bladePixels({ seed: cover.id.length + 3 })),
    );
    swap(
      materials.litter,
      "map",
      gameTexture(ctx, cover.litter) ||
        own(litterPixels({ seed: cover.id.length + 37 })),
    );
    swap(
      materials.bush,
      "map",
      gameTexture(ctx, cover.bush) ||
        /* У куста своя карточка, а не крона поменьше: короткая ветка и листва
           от самого низа. С кроновой он читался деревцем на палочке. */
        own(leafPixels({ seed: 11, leaves: 96, stem: 0.3, lowest: 0.03 })),
    );
    swap(
      materials.canopy,
      "map",
      gameTexture(ctx, cover.leaf) || own(leafPixels({ seed: 29, leaves: 74 })),
    );
    const gameBark = gameTexture(ctx, cover.bark);
    swap(materials.bark, "map", gameBark || own(barkPixels({})));
    /*
     * Карты нормалей берут только кора и земля — те две поверхности, у которых
     * нормаль настоящая: у коры она посчитана по производной радиуса ствола, у
     * земли по производной рельефа, и обе совпадают с тем, что в самом деле
     * нарисовано. У листвы нормаль изображает объём, а не карточку, и класть на
     * неё тангенциальную карту нечем — почему, разобрано в `foliageMaterial`.
     *
     * СВОЯ карта нормалей у коры есть, и это не отступление от правила «не
     * выдумывать рельеф». Правило запрещает придумывать неровности для чужой
     * картинки — что мы и делаем, когда игра отдала диффуз без нормали
     * (`gameBark` есть, `gameNormal` нет): там своя нормаль описывала бы не ту
     * кору. Но когда кора нарисована нами, борозды у неё не выдуманы, а
     * посчитаны — `barkPixels` и `barkNormalPixels` идут по ОДНОМУ полю высот, и
     * карта нормалей описывает ровно тот рельеф, который виден в диффузе. Без
     * неё ствол на скользящем свету остаётся гладкой трубой, а зерно коры —
     * это первое, за что глаз цепляется на крупном плане.
     */
    swap(
      materials.bark,
      "normalMap",
      gameNormal(ctx, cover.bark) ||
        (gameBark ? null : own(barkNormalPixels({}), { colour: false })),
    );

    const groundId = project.cover.groundId || cover.ground;
    const groundTexture = gameTexture(ctx, groundId);
    swap(
      materials.ground,
      "map",
      groundTexture || own(groundPixels({ kind: groundKind(groundId) })),
    );
    swap(materials.ground, "normalMap", gameNormal(ctx, groundId));
    /* Метры на тайл берутся у манифеста игры, а без игры — своё число: земля
       единственная здесь, что действительно повторяется, и ошибка в этом числе
       читается как «трава растёт на кафеле». */
    built.groundTile =
      assets.find((entry) => entry.id === groundId)?.tileMeters || 3;

    /* Материал глубины повторяет альфу материала: тень обязана иметь ту же
       форму, что и лист. */
    built.meshes.bush.customDepthMaterial.map = materials.bush.map;
    built.meshes.bush.customDepthMaterial.needsUpdate = true;
    built.meshes.canopy.customDepthMaterial.map = materials.canopy.map;
    built.meshes.canopy.customDepthMaterial.needsUpdate = true;

    for (const material of Object.values(materials)) {
      sharpen(ctx, material.map);
      sharpen(ctx, material.normalMap);
    }
  }

  const groundKind = (id) =>
    id === "ground-steppe"
      ? "steppe"
      : id === "ground-meadow"
        ? "meadow"
        : id === "ground-dirt"
          ? "dirt"
          : "lawn";

  /* ---------- то, что считается каждый кадр ---------- */

  /**
   * Пропорции карточки.
   *
   * Атлас травы бывает и квадратным, и вдвое шире высоты, и натянуть его на
   * квадратную карточку значит либо растянуть травинки вдвое, либо сплющить.
   * Спрашиваем у самой картинки, а не у таблицы: таблица разъедется с рецептом
   * извлечения на первой же замене текстуры.
   */
  const cardAspect = (texture) => {
    const width = texture?.image?.width;
    const height = texture?.image?.height;
    return width && height ? width / height : 1;
  };

  /**
   * Цвет человека, приведённый к виду, в котором его можно умножать.
   *
   * Выбранный цвет — это тон, а не яркость: трава светлеет от солнца, а не от
   * пипетки. Поэтому цвет нормируется по собственной яркости (иначе тёмно-
   * зелёный выбор погасил бы поле в чёрное), но не полностью: часть яркости
   * оставлена, чтобы тёмный выбор всё-таки читался темнее светлого.
   */
  function tintFor(THREE, target, hex) {
    target.setStyle(hex, THREE.SRGBColorSpace);
    const luma =
      target.r * 0.2126 + target.g * 0.7152 + target.b * 0.0722 || 0.001;
    target.multiplyScalar((0.62 + luma * 0.75) / luma);
    return target;
  }

  /**
   * Сколько подстилки в кадре.
   *
   * Своя плотность, а не доля травяной: подстилка это ярус под ногами, и её
   * количество зависит от того, докуда её вообще видно, а не от того, насколько
   * густо человек попросил траву.
   */
  function litterCount(distance) {
    const radius = Math.min(LITTER_RADIUS, distance);
    return Math.min(
      LITTER_CAPACITY,
      Math.round(LITTER_PER_METRE * Math.PI * radius * radius),
    );
  }

  /* ---------- ручки в поле ---------- */

  /*
   * Все три ручки — обычные меши, а не спрайты: они стоят В поле, и заслонение
   * травой или кустом подсказывает глубину лучше любой подписи. Цвета мимо
   * тонмаппинга (`toneMapped = false`): это органы управления, а не предметы
   * сцены, и гаснуть на закате вместе с поляной им незачем. Ползунков они не
   * подменяют и правила файла не трогают: ни одна матрица экземпляров от них
   * не шевелится — двигаются лишь сами меши ручек.
   */
  function buildGizmos(ctx) {
    if (!built || gizmos) return;
    const { THREE } = ctx;

    /* Материалы ложатся в общий словарь материалов сцены, геометрии — в общий
       список: dispose обходит их целиком, и ручки уходят из видеопамяти вместе
       с поляной, а не остаются висеть после десятка открытий редактора. */
    const material = (key, colour) => {
      const made = new THREE.MeshBasicMaterial({ color: colour });
      made.toneMapped = false;
      built.materials[key] = made;
      return made;
    };
    const geometry = (made) => {
      built.geometries.push(made);
      return made;
    };

    const group = new THREE.Group();
    group.name = "vegetation-gizmos";

    /* Стрела ветра: древко и наконечник собраны вдоль +Z, поворот кладёт их по
       бегу волны травы. Оранжевая с белым наконечником: гизмо в цвет травы на
       зелёном поле — невидимка. */
    const wind = new THREE.Group();
    wind.name = "gizmo-wind";
    const windMaterial = material("gizmoWind", "#ffb02e");
    const windAnchor = new THREE.Mesh(
      geometry(new THREE.SphereGeometry(0.2, 14, 10)),
      windMaterial,
    );
    const windShaft = new THREE.Mesh(
      geometry(new THREE.CylinderGeometry(0.07, 0.07, 1, 10)),
      windMaterial,
    );
    windShaft.rotation.x = Math.PI / 2;
    const windHead = new THREE.Mesh(
      geometry(new THREE.ConeGeometry(0.26, 0.9, 14)),
      material("gizmoWindHead", "#fff3d9"),
    );
    windHead.rotation.x = Math.PI / 2;
    wind.add(windAnchor, windShaft, windHead);
    wind.position.set(WIND_ANCHOR.x, 0, WIND_ANCHOR.z);

    /* Кольцо дальности: тонкий плоский обруч на земле. Само кольцо жеста не
       ловит — оно пересекает весь кадр, и клик по нему крал бы орбиту; ручка —
       бусина на кольце. Обруч единичный, в метры его переводит масштаб. */
    const ring = new THREE.Mesh(
      geometry(new THREE.TorusGeometry(1, 0.014, 8, 128)),
      material("gizmoRing", "#3fd2ff"),
    );
    ring.name = "gizmo-ring";
    ring.rotation.x = -Math.PI / 2;
    const bead = new THREE.Mesh(
      geometry(new THREE.SphereGeometry(0.42, 16, 12)),
      material("gizmoBead", "#eaf9ff"),
    );
    bead.name = "gizmo-bead";

    /* Столбик-мерка высоты: опора растёт из земли ровно на рост травы, ручка —
       шарик на верхушке. Якорь геометрии перенесён в основание, чтобы масштаб
       по Y был ростом в метрах, а не расползанием вокруг середины. */
    const post = new THREE.Group();
    post.name = "gizmo-height";
    const column = new THREE.Mesh(
      geometry(
        new THREE.CylinderGeometry(0.05, 0.05, 1, 10).translate(0, 0.5, 0),
      ),
      material("gizmoPost", "#ffb02e"),
    );
    const knob = new THREE.Mesh(
      geometry(new THREE.SphereGeometry(0.17, 14, 10)),
      material("gizmoKnob", "#fff3d9"),
    );
    post.add(column, knob);
    post.position.set(HEIGHT_POST.x, 0, HEIGHT_POST.z);

    group.add(wind, ring, bead, post);
    built.root.add(group);
    gizmos = {
      group,
      wind,
      windShaft,
      windHead,
      ring,
      bead,
      post,
      column,
      knob,
    };

    /* Базовые цвета — чтобы подсветка наведения умела возвращаться назад. */
    for (const mesh of [windAnchor, windShaft, windHead, bead, column, knob])
      mesh.userData.baseColor = mesh.material.color.clone();
  }

  /**
   * Ручки едут за проектом: стрела — на румб и силу, кольцо — на дальность,
   * столбик — на высоту. Матриц травы это не трогает — двигаются сами ручки.
   */
  function tuneGizmos(ctx) {
    if (!gizmos || !built) return;
    const { grass } = project;
    const grassMetres = grass.height / 100;

    /* Стрела лежит над травой и по её волне: направление то же, каким шейдер
       гонит фронт (`windVector`), иначе ручка врёт про собственный жест. */
    const state = windArrowState(project);
    gizmos.wind.position.y =
      terrainHeight(WIND_ANCHOR.x, WIND_ANCHOR.z) + grassMetres + 0.45;
    gizmos.wind.rotation.y = state.radians;
    const headLength = 0.9;
    const shaftLength = Math.max(state.length - headLength, 0.4);
    gizmos.windShaft.scale.y = shaftLength;
    gizmos.windShaft.position.z = shaftLength / 2;
    gizmos.windHead.position.z = shaftLength + headLength / 2;

    /* Кольцо плоское, на высоте травы у бусины: рельефу оно не следует — этого
       достаточно, дальность читается по бусине и по кругу в целом. */
    const handle = ringHandleState(project);
    const ringY = terrainHeight(handle.x, handle.z) + grassMetres;
    gizmos.ring.position.y = ringY;
    gizmos.ring.scale.set(handle.distance, handle.distance, 1);
    gizmos.bead.position.set(handle.x, ringY, handle.z);

    /* Столбик-мерка: высота опоры и есть высота травы в метрах. */
    gizmos.post.position.y = terrainHeight(HEIGHT_POST.x, HEIGHT_POST.z);
    gizmos.knob.position.y = grassMetres;

    /* Видимый размер держится постоянным: ручка не тает при отходе камеры и не
       заслоняет поляну на подлёте. Ось длины стрелы не масштабируется — длина
       это сила ветра, то есть данные, а не оформление. */
    const camera = ctx?.camera;
    const scaleFor = (point) =>
      camera ? gizmoScale(camera.position.distanceTo(point)) : 1;
    const windScale = scaleFor(gizmos.wind.position);
    gizmos.wind.scale.set(windScale, windScale, 1);
    gizmos.bead.scale.setScalar(scaleFor(gizmos.bead.position));
    const postScale = scaleFor(gizmos.post.position);
    gizmos.column.scale.set(postScale, grassMetres, postScale);
    gizmos.knob.scale.setScalar(postScale);
  }

  /** Правка из жеста уходит тем же путём, что и ползунок инспектора. */
  function edit(values, label) {
    onEdit?.(values, label);
  }

  function setHover(next) {
    if (hovered === next) return;
    hovered = next;
    if (canvas) canvas.style.cursor = next ? "grab" : "";
    if (gizmos) {
      for (const [name, target] of [
        ["wind", gizmos.wind],
        ["distance", gizmos.bead],
        ["height", gizmos.post],
      ]) {
        target.traverse((mesh) => {
          if (!mesh.userData?.baseColor) return;
          mesh.material.color.copy(mesh.userData.baseColor);
          if (name === next) mesh.material.color.multiplyScalar(1.35);
        });
      }
    }
    context?.requestRender?.();
  }

  /*
   * Разбор указателя.
   *
   * Порядок тот же, что у воды: сцена смотрит, попал ли жест в её ручку, и
   * только тогда объявляет его своим — `ctx.claimPointer` плюс захват
   * указателя, чтобы протяжка за краем холста не оборвала правку. Пустое поле
   * и небо остаются окну — орбита работает как всегда.
   */
  function castGizmo(event) {
    if (!gizmos || !context?.camera || !canvas) return null;
    const { THREE } = context;
    const rect = canvas.getBoundingClientRect();
    if (!rect.width || !rect.height) return null;
    const ndc = new THREE.Vector2(
      ((event.clientX - rect.left) / rect.width) * 2 - 1,
      -((event.clientY - rect.top) / rect.height) * 2 + 1,
    );
    const ray = new THREE.Raycaster();
    ray.setFromCamera(ndc, context.camera);
    const [hit] = ray.intersectObjects(
      [gizmos.wind, gizmos.bead, gizmos.post],
      true,
    );
    if (!hit) return { ray, name: "" };
    let name = "";
    for (let node = hit.object; node; node = node.parent) {
      if (node === gizmos.wind) name = "wind";
      if (node === gizmos.bead) name = "distance";
      if (node === gizmos.post) name = "height";
    }
    return { ray, name };
  }

  function planePoint(ray, plane) {
    const point = new context.THREE.Vector3();
    return ray.ray.intersectPlane(plane, point) ? point : null;
  }

  /** Горизонтальная плоскость на данной высоте — по ней ходят стрела и бусина. */
  const levelPlane = (height) =>
    new context.THREE.Plane(new context.THREE.Vector3(0, 1, 0), -height);

  /* Вертикальная плоскость через столбик, развёрнутая к камере: только на ней
     вертикальный ход руки читается как сантиметры, а не как уход вглубь поля —
     ровно как у буя воды. */
  function postPlane() {
    const { THREE } = context;
    const camera = context.camera;
    const normal = new THREE.Vector3(
      camera.position.x - gizmos.post.position.x,
      0,
      camera.position.z - gizmos.post.position.z,
    );
    if (normal.lengthSq() < 1e-6) normal.set(0, 0, 1);
    normal.normalize();
    return new THREE.Plane().setFromNormalAndCoplanarPoint(
      normal,
      gizmos.post.position,
    );
  }

  function onPointerDown(event) {
    if (event.button !== 0 || !gizmos) return;
    const cast = castGizmo(event);
    if (!cast?.name) return;

    context.claimPointer?.(event);
    try {
      canvas.setPointerCapture(event.pointerId);
    } catch {
      /* указатель уже отпущен — протяжку доведёт захват браузера */
    }
    canvas.style.cursor = "grabbing";

    if (cast.name === "height") {
      const plane = postPlane();
      const grab = planePoint(cast.ray, plane);
      drag = {
        mode: "height",
        plane,
        grabY: grab
          ? grab.y
          : gizmos.post.position.y + project.grass.height / 100,
        startHeight: project.grass.height,
      };
      return;
    }
    /* Плоскость запоминается на весь жест: кольцо едет по высоте за рельефом у
       бусины, и плоскость, пересчитанная на каждом шаге, дёргала бы дальность
       обратной связью. Стреле то же самое даёт постоянная высота травы. */
    if (cast.name === "distance") {
      drag = { mode: "distance", plane: levelPlane(gizmos.bead.position.y) };
      return;
    }
    drag = { mode: "wind", plane: levelPlane(gizmos.wind.position.y) };
  }

  function onPointerMove(event) {
    if (!drag) {
      if (event.buttons) return;
      const cast = castGizmo(event);
      setHover(cast?.name || "");
      return;
    }
    const cast = castGizmo(event);
    if (!cast) return;
    const point = planePoint(cast.ray, drag.plane);
    if (!point) return;
    if (drag.mode === "height") {
      const height = postDragHeight(drag.startHeight, point.y - drag.grabY);
      if (height !== project.grass.height) edit({ height }, "grass:height");
      return;
    }
    if (drag.mode === "distance") {
      const distance = ringDragDistance({ x: point.x, z: point.z });
      if (distance !== project.grass.distance)
        edit({ distance }, "grass:distance");
      return;
    }
    edit(windArrowPatch({ x: point.x, z: point.z }), "wind:arrow");
  }

  function endDrag(event) {
    if (drag && canvas?.hasPointerCapture?.(event.pointerId)) {
      try {
        canvas.releasePointerCapture(event.pointerId);
      } catch {
        /* захват уже снят браузером */
      }
    }
    drag = null;
    if (canvas) canvas.style.cursor = hovered ? "grab" : "";
  }

  function attachPointer(ctx) {
    canvas = ctx.renderer?.domElement || null;
    if (!canvas) return;
    canvas.addEventListener("pointerdown", onPointerDown);
    canvas.addEventListener("pointermove", onPointerMove);
    canvas.addEventListener("pointerup", endDrag);
    canvas.addEventListener("pointercancel", endDrag);
  }

  function detachPointer() {
    if (!canvas) return;
    canvas.removeEventListener("pointerdown", onPointerDown);
    canvas.removeEventListener("pointermove", onPointerMove);
    canvas.removeEventListener("pointerup", endDrag);
    canvas.removeEventListener("pointercancel", endDrag);
    canvas.style.cursor = "";
    canvas = null;
  }

  /**
   * Униформы, счётчик экземпляров и земля.
   *
   * Всё здесь дешёвое, поэтому и делается каждый кадр: так ползунок догоняет
   * картинку без единой пересборки.
   */
  function tune(ctx, frame) {
    const { THREE } = ctx;
    const { materials, meshes } = built;
    const { grass, wind } = project;
    const cover = coverById(project.cover.kind);
    const elapsed = Number(frame?.elapsedSeconds) || 0;
    const litterRadius = Math.min(LITTER_RADIUS, grass.distance);

    /* Плотность — это счётчик, и только он. Ни одна матрица от неё не
       шевелится (см. пункт 2 в шапке файла). */
    meshes.grass.count = grassCount(grass);
    meshes.litter.count = litterCount(grass.distance);

    /*
     * Свет для просвечивания снимается с лампы окна, а не пересчитывается по
     * часу: лампа у окна одна и она уже переехала с солнца на луну по высоте
     * солнца. Направление — НА источник: three ставит лампу в точку и светит
     * из неё в цель, стоящую в нуле.
     */
    const sun = ctx.sun;
    if (sun?.position) {
      built.sunDir.copy(sun.position);
      if (built.sunDir.lengthSq() > 0) built.sunDir.normalize();
    }

    const [windX, windZ] = windVector(wind.direction);

    /* Подстилка обязана быть НИЖЕ травы над ней, а трава ходит от пяти
       сантиметров до полутора метров: постоянная высота делала бы из подстилки
       на газоне вторую траву, торчащую сквозь первую. */
    const litterHeight = Math.min(
      LITTER_HEIGHT,
      Math.max(0.08, (grass.height / 100) * 0.7),
    );

    const uniforms = [
      [materials.grass, grass.height / 100],
      [materials.litter, litterHeight],
      [materials.bush, 1],
      [materials.canopy, 1],
    ];
    for (const [material, height] of uniforms) {
      const values = material.userData.uniforms;
      values.uTime.value = elapsed;
      values.uWind.value = wind.strength / 100;
      /* Скорость на шесть: ползунок стоит в процентах «от штатного ветра», а
         штатный ветер — это примерно полколебания в секунду. Без множителя
         сотня процентов даёт одно колебание в десять секунд, и ползунок
         выглядит сломанным. */
      values.uWindSpeed.value = (wind.speed / 100) * 6;
      values.uWindDir.value.set(windX, windZ);
      values.uHeight.value = height;
      values.uAspect.value = material.userData.stretch
        ? cardAspect(material.map)
        : 1;
      values.uSunDir.value.copy(built.sunDir);
      values.uSunColour.value
        .copy(sun?.color || built.white)
        .multiplyScalar(Number(sun?.intensity) || 0);
    }

    const barkUniforms = materials.bark.userData.uniforms;
    barkUniforms.uTime.value = elapsed;
    barkUniforms.uWind.value = wind.strength / 100;
    barkUniforms.uWindSpeed.value = (wind.speed / 100) * 6;
    barkUniforms.uWindDir.value.set(windX, windZ);

    const grassUniforms = materials.grass.userData.uniforms;
    grassUniforms.uSpread.value = grass.spread / 100;
    grassUniforms.uTintSpread.value = grass.colourSpread / 100;
    /* Поле ровно той дальности, которую попросили: круг мест единичный, метры
       ему даёт эта строка. Дальше по ней же растворяется край — прореживанием,
       а не стрижкой, см. `astralPlant`. */
    grassUniforms.uField.value = grass.distance;
    grassUniforms.uDistance.value = grass.distance;
    tintFor(THREE, grassUniforms.uTint.value, grass.colour);

    const litterUniforms = materials.litter.userData.uniforms;
    litterUniforms.uSpread.value = Math.max(grass.spread / 100, 0.6);
    litterUniforms.uTintSpread.value = (grass.colourSpread / 100) * 0.8;
    litterUniforms.uField.value = litterRadius;
    litterUniforms.uDistance.value = litterRadius;
    tintFor(THREE, litterUniforms.uTint.value, grass.colour);
    /* Подстилка светлее травы над ней ровно настолько, насколько она сухая:
       иначе она сливается с газоном и её незачем было заводить. */
    litterUniforms.uTint.value.multiplyScalar(1.06);

    /* Кусты и кроны разброс по размеру берут из матрицы, а не из шейдера: по
       матрице строится их тень. В шейдере им остаётся только разброс цвета,
       и он вдвое мягче травяного — пятнистое дерево выглядит больным. */
    for (const material of [materials.bush, materials.canopy]) {
      const values = material.userData.uniforms;
      values.uSpread.value = 0;
      values.uTintSpread.value = (grass.colourSpread / 100) * 0.5;
      /* Дальность растворения им не пишется вовсе: она входит только в
         прореживание, а прореживание у куста и дерева выключено (uThin = 0) —
         их десятки, и потерять из них случайную половину значит потерять кадр.
         Строка «чтобы не пропадали от травяной дальности» здесь стояла и не
         делала ничего. */
      tintFor(THREE, values.uTint.value, grass.colour);
      /* Листва чуть темнее травы под ней: крона живёт в собственной тени.
         Сильнее гасить нельзя — против солнца она и так уходит в силуэт, а
         настоящий лист на просвет, наоборот, светится. */
      values.uTint.value.multiplyScalar(0.92);
    }

    /* Без зажима потолком намеренно: потолки выведены из этой же таблицы
       покровов (см. `BUSH_CAPACITY`), и просить больше, чем в ней есть, тут
       нечему. Зажим прятал бы расхождение вместо того, чтобы его не было. */
    meshes.bush.count = cover.bushes;
    meshes.trunk.count = cover.trees;
    meshes.canopy.count = cover.trees * CANOPY_PER_TREE;

    /*
     * Мягкий край силуэта — только когда у контекста есть многократная
     * выборка.
     *
     * Alpha-to-coverage переводит альфа-тест в частичное покрытие пикселя, и
     * без MSAA переводить его не во что: у профиля `low` контекст создан со
     * сглаживанием выключенным, и включённый там A2C даст не мягкий край, а
     * ореол в полпикселя поверх непрозрачного материала. Качество — геттер,
     * оно меняется на живом окне, поэтому читается каждый кадр, а материал
     * пересобирается только на смене.
     */
    const coverage = ctx.quality !== "low";
    if (coverage !== built.coverage) {
      built.coverage = coverage;
      for (const material of [
        materials.grass,
        materials.litter,
        materials.bush,
        materials.canopy,
      ]) {
        material.alphaToCoverage = coverage;
        material.needsUpdate = true;
      }
    }

    /*
     * Ближняя граница тумана идёт за дальностью травы.
     *
     * Прибитая двадцатью пятью метрами, она оставляла ВСЁ поле до начала
     * тумана: ближний и дальний край одинаково контрастны, и глубины в кадре
     * нет ничем. Треть дальности — то место, где дымка уже видна на дальнем
     * крае и ещё не трогает то, что под ногами. Зовём только на смене:
     * `setFogRange` пересчитывает освещение и купол целиком.
     */
    const fogNear = Math.max(5, Math.round(grass.distance * 0.35));
    if (fogNear !== built.fogNear) {
      built.fogNear = fogNear;
      ctx.setFogRange?.(fogNear, FOG_FAR);
    }

    /*
     * Земля дотягивается до тумана и читает его дальность каждый кадр.
     *
     * Дальность гуляет по погоде и часу (см. раздел про землю в шапке
     * `PreviewWindow.jsx`): посчитанная один раз при монтаже, она к вечеру
     * оставила бы по горизонту тёмный шов — земля кончилась, а неба на её
     * месте ещё нет.
     */
    const far = Number(ctx.fog?.far) || FOG_FAR;
    const span = Math.round(far * GROUND_SPAN);
    if (span !== built.groundSpan) {
      built.groundSpan = span;
      meshes.ground.scale.set(span, 1, span);
    }
    const repeat = span / built.groundTile;
    materials.ground.map?.repeat?.set(repeat, repeat);
    materials.ground.normalMap?.repeat?.set(repeat, repeat);
    /* Земля подкрашивается тем же цветом, но втрое слабее: поляна обязана
       читаться одним цветом сверху донизу, а перекрашенная в тон травы земля
       превращается в зелёный лист бумаги под зелёной травой. Ровно на треть, а
       не на четверть: чем бледнее земля за краем поля, тем резче кольцо на
       границе травы — а его и так видно. */
    tintFor(THREE, materials.ground.color, grass.colour);
    materials.ground.color.lerp(built.white, 0.62);

    const groundUniforms = materials.ground.userData.uniforms;
    groundUniforms.uFieldRadius.value = grass.distance;
    /* Под полем земля уходит в ТОН травы, а не в её яркость: нормируем на
       собственную светлоту, иначе тёмный выбор цвета гасил бы землю дважды —
       один раз краской, второй раз этим подмешиванием. */
    tintFor(THREE, groundUniforms.uFieldTint.value, grass.colour);
    const tint = groundUniforms.uFieldTint.value;
    const luma = tint.r * 0.2126 + tint.g * 0.7152 + tint.b * 0.0722 || 0.001;
    tint.multiplyScalar(1 / luma);

    /*
     * Кора не красится, но подсвечивается — и подсветка идёт за часом.
     *
     * Дубовая кора из игры покрашена под её собственный свет: под крону, в
     * которой всегда полутень. В нашем кадре ствол стоит на открытом поле, и
     * та же текстура читается чёрным силуэтом — дерево получается обугленным.
     * Постоянный множитель это чинил в полдень и оставлял ту же серость ночью;
     * теперь подъём идёт по доле дневного света, которую окно уже посчитало,
     * и ночью ствол темнеет вместе со всем остальным. Цвет травы на кору не
     * переносится: покрашенный в тон газона ствол выглядит крашеным столбом.
     */
    const daylight = Number(frame?.lighting?.daylight);
    const lift = 1.02 + 0.36 * (Number.isFinite(daylight) ? daylight : 1);
    materials.bark.color.setRGB(
      lift,
      lift * 0.985,
      lift * 0.955,
      THREE.LinearSRGBColorSpace,
    );
  }

  /**
   * Замеры кадра наверх. Не чаще четырёх раз в секунду — это состояние React.
   *
   * Часы браузера, а не часы сцены: часы сцены идут только пока рисуются кадры,
   * и при выключенном ветре они стоят. Замеры при этом обязаны доезжать —
   * человек как раз в этот момент двигает ползунок плотности и смотрит, во что
   * это обошлось.
   */
  function report(ctx) {
    if (!onStats) return;
    const now = Date.now();
    if (now - statsAt < 250) return;
    statsAt = now;
    onStats(readStats(ctx));
  }

  /**
   * Что стоит в кадре и во что это обошлось.
   *
   * Числа отрисовки берутся у рендерера и относятся к ПРЕДЫДУЩЕМУ кадру: three
   * обнуляет счётчики в начале отрисовки, а нас зовут до неё. Для показа
   * человеку разница в один кадр не значит ничего, а держать свой счётчик
   * значило бы считать то же самое второй раз и однажды разойтись.
   */
  function readStats(ctx) {
    const render = ctx?.renderer?.info?.render;
    const { meshes } = built || { meshes: {} };
    return {
      draws: render?.calls ?? 0,
      triangles: render?.triangles ?? 0,
      grass: meshes.grass?.count ?? 0,
      litter: meshes.litter?.count ?? 0,
      bushes: meshes.bush?.count ?? 0,
      trees: meshes.trunk?.count ?? 0,
      /* Вершины считаем сами: у рендерера их нет, а именно они дорожают от
         плотности. Восемь на травинку, по четыре на каждую карточку кома. */
      vertices:
        (meshes.grass?.count ?? 0) * GRASS_PLANES * 4 +
        (meshes.litter?.count ?? 0) * GRASS_PLANES * 4 +
        (meshes.bush?.count ?? 0) * BUSH_CARDS * 4 +
        (meshes.canopy?.count ?? 0) * CANOPY_CARDS * 4,
      source: assets.length ? "game" : "fallback",
    };
  }

  return {
    /**
     * Правка проекта. Что именно пересобирать, сцена решает сама.
     *
     * Кадр запрашивается здесь же: окно рисует по требованию, и без этой строки
     * правка на неподвижной камере доехала бы до картинки только тогда, когда
     * человек тронет мышью сцену.
     */
    apply(next) {
      project = createVegetationProject(next);
      context?.requestRender?.();
    },
    /**
     * С какого ракурса эту сцену надо открывать.
     *
     * Свойство, а не догадка хозяина окна: траву настраивают с высоты роста, а
     * не с вертолёта. Сверху не видно ни высоты, ни разброса, ни ветра — виден
     * только цвет, то есть единственная настройка, которую и так видно везде.
     */
    camera: "orbit",
    /** Что нашлось в установленной игре — редактор спрашивает после монтажа. */
    get assets() {
      return assets;
    },
    get project() {
      return project;
    },
    /** Замеры по требованию: ими редактор показывает цену кадра. */
    stats() {
      return readStats(context);
    },

    /*
     * Правка снаружи — для теста и для подписи: тем же путём идут и жесты по
     * ручкам. Сцена сама ничего не меняет — она только доносит правку до
     * редактора, а тот вернёт её через `apply`, как и с ползунков.
     */
    edit,

    mount(ctx) {
      context = ctx;
      assets = resolveVegetationAssets(ctx.assets);
      coverKey = "";
      build(ctx);
      buildGizmos(ctx);
      attachPointer(ctx);
      ensureCover(ctx);
      tune(ctx, { elapsedSeconds: 0 });
      tuneGizmos(ctx);

      /* Коробка теней по размеру того, что тени бросает, — и накрывающая ВСЁ,
         что их бросает: см. `SHADOW_EXTENT`. */
      ctx.setShadowExtent?.(SHADOW_EXTENT);
      /*
       * Камера на высоте роста.
       *
       * Трава читается только отсюда: с трёх метров разброс выглядит шумом, а
       * ветер — дрожанием. Цель взгляда поднята почти на метр, а не в ноль, —
       * иначе камера смотрит себе под ноги и половину кадра занимает земля.
       *
       * Пределы заданы, потому что поле у нас круглое и конечное: без верхнего
       * предела колесо уводит зрителя за край травы, откуда видно, что поляна
       * кончается, а без нижнего — внутрь травинки.
       */
      ctx.setOrbit?.({
        target: [0, 0.85, 0],
        radius: 7,
        yaw: 2.1,
        pitch: 0.1,
        minRadius: 2.5,
        maxRadius: 34,
        minPitch: 0.03,
        maxPitch: 0.85,
      });
      onAssets?.(assets);
    },

    update(ctx, frame) {
      if (!built) return;
      ensureCover(ctx);
      tune(ctx, frame);
      tuneGizmos(ctx);
      report(ctx);
      /*
       * Кадры просит только ветер.
       *
       * Окно рисует, когда есть что показать нового, и неподвижное поле — это
       * ноль кадров в секунду и ноль отнятых у игры ресурсов. Ветер — как раз
       * то новое, что происходит само; выключенный ветер обязан возвращать окно
       * в покой, а не оставлять цикл крутиться вхолостую.
       *
       * Проверяется одна сила, и только она: в шейдере всё отклонение умножено
       * на `uWind` (силу), и при нуле стоит всё — трава, кроны, стволы.
       * Скорость лишь масштабирует время и движения без силы не даёт, а ниже
       * десяти процентов ползунок её не пускает — условие `speed > 0` было
       * мёртвой проверкой, истинной всегда.
       */
      if (project.wind.strength > 0) {
        ctx.requestRender?.();
      }
    },

    dispose() {
      detachPointer();
      drag = null;
      hovered = "";
      gizmos = null;
      if (!built) return;
      const { root, scene, textures, geometries, materials, depth, meshes } =
        built;
      /*
       * Буфер матриц экземпляров лежит НЕ в `geometry.attributes`, и вместе с
       * геометрией не освобождается: снимает его только `InstancedMesh.dispose`,
       * по событию которого рендерер выкидывает `instanceMatrix` из
       * видеопамяти. Подстраховки от окна нет — `disposeSubtree` обходит
       * геометрии и материалы и до этих мешей всё равно не доходит, потому что
       * корень снят из сцены строкой ниже. Цена пропуска — без малого четыре
       * мегабайта на КАЖДОЕ открытие редактора, а открывают его за сеанс
       * десяток раз.
       */
      for (const mesh of Object.values(meshes)) mesh.dispose?.();
      for (const geometry of geometries) geometry.dispose?.();
      for (const texture of textures) texture.dispose?.();
      for (const material of Object.values(materials)) material.dispose?.();
      for (const material of depth) material.dispose?.();
      scene?.remove?.(root);
      built = null;
      context = null;
      coverKey = "";
    },
  };
}
