export const PLANT_FRAGMENT_HEAD = /* glsl */ `
uniform vec3 uSunColour;
uniform vec3 uSunDir;
uniform float uSunPower;
uniform float uTransmit;
uniform float uRootShade;
varying vec3 vAstralTint;
varying float vAstralHeight;
`;

/*
 * Цвет человека поверх текстуры игры.
 *
 * Текстура листвы покрашена до нас, и умножить её на выбранный зелёный значит
 * получить чёрный: два зелёных перемножаются в почти ноль. Поэтому картинка
 * сначала уводится к яркости, и уже к ней приложен выбранный цвет. Увод был
 * 72% — от богатой текстуры GTA оставалась форма и четверть тона; 45% хватает,
 * чтобы ползунок цвета работал в полную силу, и оставляет текстуре её
 * собственную тональную жизнь.
 *
 * Затенение у корня — одна строка, которая снимает «наклеенность» пучков
 * сильнее всего остального вместе взятого: раньше доля высоты во фрагмент не
 * доезжала вовсе, и пучки лежали на земле наклейками, а не росли из неё.
 */
export const PLANT_FRAGMENT_MAP = /* glsl */ `
  float astralLuma = dot(diffuseColor.rgb, vec3(0.2126, 0.7152, 0.0722));
  diffuseColor.rgb = mix(diffuseColor.rgb, vec3(astralLuma), 0.45) * vAstralTint;
  diffuseColor.rgb *= mix(uRootShade, 1.0, vAstralHeight);
`;

/*
 * Просвечивание.
 *
 * Ради него в редакторе и заведены четыре часа суток: настоящая зелень против
 * солнца не чернеет силуэтом, а загорается изнутри.
 *
 *
 * ПОЧЕМУ ПРЕЖНЯЯ ДОБАВКА НЕ ДОХОДИЛА ДО КАДРА
 *
 * Она была, считалась и попадала во фрагмент — и всё равно её не было видно.
 * Причина в том, ЧЕМ она красилась: `diffuseColor.rgb`, то есть альбедо листа,
 * уже потемневшее от затенения у корня и от тинта. У листвы это около 0.08 в
 * зелёном. Замер закатного кадра (19.2, EXTRASUNNY): ключ 20.9 при цвете
 * (1, 0.60, 0.40), небо на горизонте 2.3 в линейном свете. Полностью
 * освещённый лист даёт 0.08 · 20.9 / π ≈ 0.53 — вчетверо темнее неба за ним, и
 * прежнее просвечивание в лучшей своей точке давало РОВНО СТОЛЬКО ЖЕ. То есть
 * лист против солнца становился таким же, как лист под солнцем, и на фоне неба
 * оба оставались силуэтом. Тонмаппинг тут ни при чём: он одинаково жмёт и небо,
 * и лист, а разницы между ними не было ещё до него.
 *
 * Физически же цвет НА ПРОСВЕТ — это не цвет отражения. Свет проходит один
 * слой хлорофилла и выходит насыщенным и СВЕТЛЫМ; тёмным лист выглядит с
 * лицевой стороны, потому что там работает поверхностное рассеяние. Поэтому
 * здесь берётся только ТОН альбедо, нормированный по пиковому каналу, а
 * яркость даёт солнце. На том же закате это 12.6 / π · uTransmit — то есть
 * лист выходит в яркость неба, как на настоящем кадре.
 *
 *
 * ПОЧЕМУ ЛОБ СЧИТАЕТСЯ ЧЕРЕЗ НОРМАЛЬ, А НЕ ПРОСТО «ВЗГЛЯД ПРОТИВ СОЛНЦА»
 *
 * Голый `dot(V, -L)` — это ореол вокруг солнца, одинаковый на всей листве
 * кадра: форма кроны в нём не читается вовсе. Подмешивание нормали в
 * направление хода света (приём быстрой подповерхностки) сгибает лепесток
 * вслед за комом: обращённые к зрителю карточки светятся, уходящие вбок гаснут,
 * и крона получает объём. Второе слагаемое — широкое: сторона, отвёрнутая от
 * солнца, светится и тогда, когда солнце не в кадре. Без него крона при
 * боковом свете снова становится плоской.
 *
 * Свет берётся своими униформами из `ctx.sun`, а не из directionalLights[]:
 * иначе член зависел бы от того, сколько ламп скомпилировано в программе, а
 * это число окно вправе менять. В оси камеры его переводит `viewMatrix` — та
 * самая матрица, которой рисуется ЭТОТ кадр; посчитай мы поворот на процессоре,
 * ореол отставал бы на кадр, потому что окно двигает орбиту до отрисовки, а
 * `matrixWorldInverse` обновляется внутри неё. Делитель π — тот же, что у
 * ламбертовой BRDF в three: без него добавка живёт в других единицах, чем
 * остальной свет, и настраивать её пришлось бы заново на каждый час.
 *
 * Тень эту добавку не гасит намеренно: свет, рассеянный внутри листа, приходит
 * не по прямой от солнца, и вырезать его картой теней значило бы гасить крону
 * её собственной тенью.
 */
export const PLANT_FRAGMENT_LIGHT = /* glsl */ `
  vec3 astralSun = normalize((viewMatrix * vec4(uSunDir, 0.0)).xyz);
  /* geometryViewDir и geometryNormal заведены в lights_fragment_begin парой
     строк выше: у ламберта они уже есть, и считать их второй раз незачем.
     Имена здесь без обратных кавычек намеренно — весь блок лежит внутри
     шаблонной строки, и кавычка закрыла бы её посреди шейдера. */
  vec3 astralPath = normalize(astralSun + geometryNormal * 0.42);
  float astralTight = pow(max(dot(geometryViewDir, -astralPath), 0.0), uSunPower);
  float astralAway = max(-dot(geometryNormal, astralSun), 0.0);

  /* Тон без темноты: пиковый канал уводится в единицу, и вместе с ним уходит
     всё, чем альбедо успели притушить, — затенение у корня, тинт, вершинная
     подкраска кома. Лист на просвет не помнит, что он в глубине кроны. */
  float astralPeak = max(diffuseColor.r, max(diffuseColor.g, diffuseColor.b));
  vec3 astralThrough = diffuseColor.rgb / max(astralPeak, 1e-4);

  /* Кончик тоньше корня и просвечивает сильнее — это единственное, что здесь
     осталось от геометрии растения. */
  float astralThin = mix(0.4, 1.0, vAstralHeight);
  reflectedLight.directDiffuse += astralThrough * uSunColour
    * (uTransmit * astralThin * (astralTight + 0.24 * astralAway) * RECIPROCAL_PI);
`;

