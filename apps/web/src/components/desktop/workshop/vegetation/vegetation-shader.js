export const GROUND_HEAD = /* glsl */ `
varying vec3 vAstralGround;

${TERRAIN_GLSL}
`;

/*
 * Мировая точка считается из `position`, а не из `transformed`: нормаль three
 * забирает до того, как позиция вообще заведена.
 *
 * Масштаб плиты вносится ЗДЕСЬ, и без него весь этот счёт впустую.
 * `astralTerrainNormal` отвечает в мировых метрах, а `objectNormal` — величина
 * объектная: дальше three умножит её на `normalMatrix = transpose(inverse(mv))`,
 * то есть на ОБРАТНЫЙ масштаб. Плита растянута до `far * 2.4` (сотни метров), и
 * наклон рельефа, который и так всего около четырёх градусов, делится на эти
 * сотни — земля освещается идеально плоской, а функция нормали считается зря.
 * Умножение на длины столбцов `modelMatrix` — та же поправка, что получилась бы
 * из правила цепочки: по местной оси высота меняется во столько же раз быстрее,
 * во сколько плита растянута.
 */
export const GROUND_NORMAL = /* glsl */ `
  vec3 astralGroundAt = (modelMatrix * vec4(position, 1.0)).xyz;
  float astralSpanX = length(modelMatrix[0].xyz);
  float astralSpanZ = length(modelMatrix[2].xyz);
  vec3 astralGroundNormal = astralTerrainNormal(astralGroundAt.xz);
  objectNormal = normalize(vec3(
    astralGroundNormal.x * astralSpanX,
    astralGroundNormal.y,
    astralGroundNormal.z * astralSpanZ
  ));
`;

/*
 * Плита перестаёт быть столом.
 *
 * Раньше это была `PlaneGeometry(1, 1)` без единого сегмента, растянутая до
 * 2.4 дальности тумана: плита в шестьсот метров из ДВУХ треугольников, у
 * которой горизонт бритвенно прямой, а поле стоит на столе. Смещение вершин
 * идёт по местной оси Y и только потому, что геометрия повёрнута заранее, а
 * меш — нет: иначе «вверх» у плиты оказалось бы местным -Z.
 */
export const GROUND_APPLY = /* glsl */ `
  transformed.y += astralTerrain(astralGroundAt.xz);
  vAstralGround = astralGroundAt;
`;

/*
 * Макро-вариация поверх тайла.
 *
 * Земля повторяется двести раз на шестьсот метров, и с высоты роста под
 * скользящим углом сетка тайла видна до горизонта. Лечится это вторым, крупным
 * шумом, а не второй текстурой: ноль новых байт, ноль новых выборок.
 *
 * Сухость идёт по ДРУГОМУ шуму, чем яркость: совпади они — и пятна читались бы
 * освещением, то есть облаками, которых в кадре нет.
 *
 * Под полем земля темнее и уходит в тон травы. Это второй, дешёвый способ
 * растворить край поля: там, где пучки уже прорежены, земля ещё помнит, что
 * над ней была трава, и граница перестаёт быть линейкой.
 */
export const GROUND_FRAGMENT_HEAD = /* glsl */ `
uniform vec3 uFieldTint;
uniform float uFieldRadius;
varying vec3 vAstralGround;

${NOISE_GLSL}
`;

export const GROUND_FRAGMENT_BODY = /* glsl */ `
  float astralMacro = astralNoise(vAstralGround.xz * 0.055) * 0.6
    + astralNoise(vAstralGround.xz * 0.013) * 0.4;
  diffuseColor.rgb *= mix(0.58, 1.38, astralMacro);
  float astralDry = smoothstep(0.5, 0.88, astralNoise(vAstralGround.xz * 0.031 + 17.0));
  diffuseColor.rgb = mix(
    diffuseColor.rgb,
    diffuseColor.rgb * vec3(1.32, 1.14, 0.7),
    astralDry * 0.5
  );
  /* Растворение шире, чем сама трава: край поля гаснет между 0.58 и 1.0
     дальности, и если бы земля темнела теми же границами, обе линии легли бы
     друг на друга и вместо растворения получилось бы кольцо. Мерится оно от
     центра поля тем же счётом, что и прореживание пучков: пятно, привязанное к
     глазу, ездило бы за камерой по неподвижной траве. */
  float astralUnder = 1.0 - smoothstep(
    uFieldRadius * 0.3,
    uFieldRadius * 1.5,
    length(vAstralGround.xz)
  );
  diffuseColor.rgb = mix(diffuseColor.rgb, diffuseColor.rgb * uFieldTint * 0.68, astralUnder);
`;

/* ---------- ствол ---------- */

/*
 * Ветер доходит и до дерева.
 *
 * При сильном ветре поле волнуется, а деревья стоят столбами — глаз читает это
 * как поломку раньше, чем успевает разобрать, что именно не так. Качание у
 * ствола маленькое (см. `TRUNK_SWAY` в сцене) и в материал глубины не
 * заезжает: тень ствола — это пятно у его подножия, и полдециметра на верхушке
 * в ней не видно.
 */
export const TRUNK_HEAD = /* glsl */ `
uniform float uTime;
uniform float uWind;
uniform float uWindSpeed;
uniform float uSway;
uniform vec2 uWindDir;
`;

export const TRUNK_APPLY = /* glsl */ `
  vec3 astralTrunkAt = vec3(0.0);
  #ifdef USE_INSTANCING
    astralTrunkAt = instanceMatrix[3].xyz;
  #endif
  float astralTrunkPhase = astralTrunkAt.x * 0.21 + astralTrunkAt.z * 0.17;
  float astralTrunkGust = 0.5 + 0.5 * sin(uTime * uWindSpeed * 0.19 + astralTrunkPhase);
  transformed.xz += uWindDir
    * (transformed.y * transformed.y * uSway * uWind * astralTrunkGust);
`;
