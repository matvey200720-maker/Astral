/*
 * Значок типа погоды.
 *
 * Пятнадцать строк списка стояли с одним и тем же значком — солнцем за
 * облаком. Такой столбик не несёт ничего: глаз всё равно читает подписи, а
 * место под значок занято. Разные значки превращают список в то, что видно
 * боковым зрением, — «где-то тут снег, ниже праздники».
 *
 * Значки не выдуманы, а взяты по смыслу типа: гроза — молния, метель — ветер,
 * рождество — подарок, хеллоуин — привидение. Совпадений быть не должно: два
 * одинаковых значка на соседних строках хуже, чем ни одного, потому что
 * обещают различие и не дают его. Там, где смысл почти один (облачно и
 * пасмурно), различает толщина: пасмурное небо — залитое облако.
 *
 * Отдельным файлом, потому что значки нужны и списку погоды в редакторе, и
 * подписи в кадре: одна погода обязана выглядеть одинаково в обоих местах.
 */

import {
  Cloud,
  CloudFog,
  CloudLightning,
  CloudRain,
  CloudSnow,
  CloudSun,
  Ghost,
  Gift,
  Rainbow,
  Snowflake,
  Sun,
  SunDim,
  CircleHalf,
  Wind,
} from "../../ui/icons.jsx";

/** Значок и его толщина: тип погоды → как он выглядит в списке. */
const ICONS = {
  EXTRASUNNY: [Sun, "fill"],
  CLEAR: [Sun, "regular"],
  CLOUDS: [Cloud, "regular"],
  /* Смог — это не облака, а муть, сквозь которую светит притушенное солнце. */
  SMOG: [SunDim, "regular"],
  FOGGY: [CloudFog, "regular"],
  /* Пасмурно — то же облако, но сплошное: залитый значок и означает сплошное. */
  OVERCAST: [Cloud, "fill"],
  RAIN: [CloudRain, "regular"],
  THUNDER: [CloudLightning, "fill"],
  /* Проясняется — конец дождя. */
  CLEARING: [Rainbow, "regular"],
  /* Нейтральная погода — база под скрипты, а не состояние неба; отсюда и знак
     без погоды в нём. */
  NEUTRAL: [CircleHalf, "regular"],
  SNOW: [CloudSnow, "regular"],
  BLIZZARD: [Wind, "fill"],
  SNOWLIGHT: [Snowflake, "regular"],
  XMAS: [Gift, "fill"],
  HALLOWEEN: [Ghost, "fill"],
};

/**
 * Значок типа погоды. Неизвестный тип отдаёт солнце за облаком — тот самый
 * общий значок, который раньше стоял у всех: место занять надо, а врать про
 * погоду, которой нет в списке, нечем.
 */
export default function WeatherIcon({ weather, ...rest }) {
  const [Icon, weight] = ICONS[String(weather || "").toUpperCase()] || [
    CloudSun,
    "regular",
  ];
  return <Icon weight={weight} {...rest} />;
}
