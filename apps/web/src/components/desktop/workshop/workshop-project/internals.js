/* Глубокая копия через JSON — намеренно. Значения проекта переживают запись в
   localStorage, то есть заведомо сериализуемы, а structuredClone сохранял бы
   то, что запись всё равно потеряет. */
export const clone = (value) => JSON.parse(JSON.stringify(value));

export function projectId() {
  return `astral-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}
