
import { tr } from "../../../../../locales/ui.js";
/*
 * Ползунок инспектора. Группа «Внешний вид» стоит значением по умолчанию: она
 * у подавляющего большинства контролов, и выписывать её в каждом из двух с
 * половиной сотен вызовов значило бы утопить в шуме те немногие, у которых
 * группа своя.
 */
export const control = (key, label, type, extra = {}) => ({
  key,
  label,
  type,
  group: tr("Внешний вид"),
  ...extra,
});
