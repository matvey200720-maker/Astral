/*
 * «Убрать эффекты попаданий совсем» (ТЗ 17.10.2026, вечер): выключатель над
 * стопкой слоёв. Что игра рисует при попадании пули по игроку — кровь, искры,
 * пыль у раны, спереди и сзади, у головы и у тела, — не рисуется вовсе. Слои
 * работы лежат нетронутыми и вернутся вместе с эффектами.
 *
 * Здесь же сказано, что остаётся, — чтобы никто не ждал от выключателя того,
 * чего файл игры не умеет: следы и частицы пуль в стенах и машинах убирает
 * слой «Частицы от попаданий пуль» в разделе «Оптимизация» (его не
 * повторяем), вспышку на экране у себя — «Эффекты попадания на экране», а то, что
 * рисует сервер (RAGE:MP, alt:V), файлом игры не отключается.
 */

import Switch from "../../ui/Switch.jsx";
import { tr, useTr } from "../../../locales/ui.js";

export default function HitsOffSection({ removed, onChange }) {
  useTr();
  return (
    <section className="ui-panel fx-section" aria-label={tr("Убрать совсем")}>
      <div className="fx-switch-row">
        <Switch
          checked={removed}
          label={removed ? tr("Вернуть эффекты попаданий") : tr("Убрать эффекты попаданий совсем")}
          onChange={onChange}
        />
        <span>{tr("Убрать эффекты попаданий совсем")}</span>
      </div>
      {/* Одна подсказка: в две строки, щелчок раскрывает целиком. */}
      <p className="fx-hint">
        {removed
          ? tr("По игроку ничего не рисуется: ни кровь, ни искры, ни пыль — у головы и у тела. Ваши слои сохранены и вернутся, когда вернёте эффекты.")
          : tr("Уберёт всё, что игра рисует, когда пуля попадает в игрока: кровь, искры, пыль — у головы и у тела. Слои ниже сохранятся.")}{" "}
        {tr("Остаются: искры и пыль от пуль в стенах и машинах — их убирает слой «Частицы от попаданий пуль» в «Оптимизации»; вспышка на экране у вас — «Эффекты попадания на экране»; удары в ближнем бою и взрывы. Эффекты, которые рисует сервер, файлом игры не отключаются.")}
      </p>
    </section>
  );
}
