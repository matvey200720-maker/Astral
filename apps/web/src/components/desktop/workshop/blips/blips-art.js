/**
 * Треугольник направления у края радара.
 *
 * Он не заменяет значок, а стоит рядом с ним: в игре прижатый значок
 * превращается в стрелку и перестаёт говорить, что именно за краем, — а
 * редактор ровно для того и нужен, чтобы видеть набор целиком. Поэтому значок
 * остаётся собой, а куда идти показывает отдельная стрелка.
 */
export const BLIP_POINT_PATH = "M50 8L90 90H10Z";

/** Шеврон направления на маршруте. Смотрит вверх, как и стрелка у края. */
export const ROUTE_ARROW_PATH = "M50 18L86 82H14Z";

/** Форма пятна по имени. Незнакомое имя — круг, а не пустой значок. */
export function blipShapeArt(id) {
  return BLIP_SHAPE_ART[id] || BLIP_SHAPE_ART.circle;
}

/** Силуэт по имени. Незнакомое имя — метка: пустой значок хуже чужого. */
export function blipGlyphArt(id) {
  return BLIP_GLYPH_ART[id] || BLIP_GLYPH_ART.pin;
}

/**
 * Куда и как поставить силуэт внутри формы.
 *
 * Выведено отдельно, потому что этим же переносом рисуется значок и в кадре, и
 * в списке слева, и в пикере: три разных множителя дали бы три разных значка.
 */
export function glyphTransform(shape) {
  const place = blipShapeArt(shape).glyph;
  return `translate(${(place.x - 50 * place.s).toFixed(3)} ${(place.y - 50 * place.s).toFixed(3)}) scale(${place.s})`;
}

/**
 * Сколько единиц от края коробки до силуэта.
 *
 * Нужно канту: он идёт внутрь от края фигуры, и вопрос «дошёл ли он до
 * рисунка» — это вопрос о ближайшем крае коробки силуэта, а не о её половине.
 * Считать от центра нельзя: у капли силуэт сидит на сорока единицах, у
 * треугольника — на шестидесяти семи, и порог, выведенный из одного масштаба,
 * для них обоих неверен.
 */
export function glyphMargin(shape) {
  const place = blipShapeArt(shape).glyph;
  const half = 50 * place.s;
  return Math.min(
    place.x - half,
    100 - (place.x + half),
    place.y - half,
    100 - (place.y + half),
  );
}

/**
 * Толщина канта в единицах коробки 0…100.
 *
 * Обводка приходит в тех же единицах, что и `size`, — иначе кант оказывается
 * постоянной величиной экрана: рисунок живёт в коробке 0…100, и перевести в неё
 * пиксели можно только через настоящий размер значка. Штрих идёт по той же
 * фигуре и обрезается ею же, поэтому наружу уходит половина — отсюда двойка.
 */
export function outlineBand(outline, size) {
  const px = Number(outline) || 0;
  const box = Number(size) || 0;
  return box > 0 ? Math.max(0, (px / box) * 100) * 2 : 0;
}
