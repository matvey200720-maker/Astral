/*
 * Один значок как картинка.
 *
 * Единственное изображение значка на весь редактор: его рисует кадр, его же —
 * список типов слева, пикер силуэтов и линейка размеров в инспекторе. До этого
 * каждое из этих мест рисовало значок своим кодом, и три картинки одного и того
 * же значка не совпадали: в списке силуэт был захардкожен тёмным вместо
 * расчётного, скругление квадрата отличалось от кадрового, а обводка и
 * прозрачность не показывались вовсе.
 *
 * Порядок слоёв значащий: заливка, потом кант внутрь по обрезке той же фигурой,
 * потом силуэт. Силуэт рисуется последним и поэтому не исчезает ни при каком
 * сочетании ползунков — даже когда кант съел всю заливку, человек видит, что
 * именно у него получилось, а не пустое пятно цвета обводки.
 */

import { useId } from "react";
import { readableInk } from "./blips-model.js";
import {
  GLYPH_STROKE_MIN,
  blipGlyphArt,
  blipShapeArt,
  glyphMargin,
  glyphTransform,
  outlineBand,
} from "./blips-art.js";

/**
 * @param {object} props
 * @param {object} props.style Настройки типа: форма, силуэт, цвет, обводка,
 *   цвет обводки, прозрачность.
 * @param {number} props.size Настоящий размер значка в тех единицах, в которых
 *   он рисуется: пикселях макета в инспекторе и пикселях окна в кадре.
 * @param {number} [props.outline] Обводка В ТЕХ ЖЕ единицах, что и `size`.
 *   Отдельным свойством, а не из `style`: в кадре значок растёт от лупы и от
 *   масштаба окна, и обводка, взятая пикселями макета при размере в пикселях
 *   окна, превращалась в постоянную величину экрана — под лупой втрое тоньше
 *   положенной, в маленьком окне вдвое толще. По умолчанию — своя из настроек:
 *   там, где значок стоит один к одному, единицы и так совпадают.
 * @param {string} [props.glyph] Силуэт вместо своего: пикеру рисунков нужен
 *   один и тот же значок с разными силуэтами.
 * @param {number} [props.box] Занять столько точек, а не всю коробку родителя.
 *   Нужно линейке размеров: она ставит один значок рядом с собой же в других
 *   размерах, и коробки под каждый заводить незачем.
 */
export default function BlipArt({
  style,
  size = 24,
  outline = undefined,
  glyph,
  box = 0,
  className = "",
}) {
  /* Обрезка канта — свой элемент документа на каждый значок, и одинаковый
     идентификатор склеил бы их между собой: браузер ищет `url(#…)` по всему
     документу, а значков на кадре десяток. */
  const clip = useId();
  const shape = blipShapeArt(style.shape);
  const marks = blipGlyphArt(glyph || style.glyph);
  const band = outlineBand(
    outline === undefined ? style.outline : outline,
    size,
  );
  /*
   * Ореол вокруг силуэта цветом ПЯТНА — и только тогда, когда кант дошёл до
   * самого силуэта. Иначе он не нужен и вреден: штрих идёт по обе стороны
   * контура и подъедает просветы внутри рисунка, отчего колёса у машины
   * прилипают к кузову. А когда кант дошёл (обводка 6 на размере 12), цвет
   * силуэта, посчитанный от заливки, оказывается тёмным на тёмном, и значок
   * снова становится пустым пятном — вот там ореол и отделяет силуэт от канта.
   *
   * Кант идёт внутрь на половину штриха, поэтому сравнивается она, а не весь
   * штрих; и сравнивается с настоящим краем коробки силуэта, а не с половиной
   * его масштаба: у капли рисунок сидит выше центра коробки, и порог «от
   * середины» для неё вдвое велик — ореол приходил бы, когда кант давно съел
   * рисунок.
   */
  const reach = band / 2 > glyphMargin(style.shape);
  /* Ширина ореола — половина самого тонкого штриха силуэта: по обе стороны
     контура он съедает по четверти такого просвета и потому не закрывает его
     ни в одном рисунке. */
  const halo = GLYPH_STROKE_MIN / 2;
  return (
    <svg
      className={`blips-art${className ? ` ${className}` : ""}`}
      viewBox="0 0 100 100"
      aria-hidden="true"
      focusable="false"
      style={box > 0 ? { width: `${box}px`, height: `${box}px` } : undefined}
    >
      {band > 0 ? (
        <defs>
          <clipPath id={clip}>
            <path d={shape.d} />
          </clipPath>
        </defs>
      ) : null}
      {/* Прозрачность живёт на заливке, а не на значке целиком: в игре альфа
          гасит пятно, а тёмный кант и белый силуэт остаются — именно они и
          держат полупрозрачный значок на светлой карте. */}
      <path
        className="blips-art-fill"
        d={shape.d}
        fill={style.color}
        fillOpacity={style.opacity / 100}
      />
      {band > 0 ? (
        <path
          className="blips-art-edge"
          d={shape.d}
          fill="none"
          stroke={style.outlineColor}
          strokeWidth={band.toFixed(3)}
          clipPath={`url(#${clip})`}
        />
      ) : null}
      <g transform={glyphTransform(style.shape)}>
        {marks.map((d) => (
          <path
            key={d}
            className="blips-art-ink"
            d={d}
            fill={readableInk(style.color)}
            fillRule="evenodd"
            stroke={reach ? style.color : undefined}
            strokeWidth={reach ? halo : undefined}
            /* Ореол гаснет вместе с заливкой: иначе на двадцати процентах
               вокруг силуэта проступил бы цветной контур, которого в значке
               нет вовсе. */
            strokeOpacity={reach ? style.opacity / 100 : undefined}
            strokeLinejoin={reach ? "round" : undefined}
            paintOrder={reach ? "stroke" : undefined}
          />
        ))}
      </g>
    </svg>
  );
}
