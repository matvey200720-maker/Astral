/*
 * Модель ствола, что экран «Ганпак» уже прочитал, — редактору (04.11.2026, слова ведущей: «чтение ствола начинай с первого кадра подлёта, чтобы оно шло параллельно»).
 *
 * Экран держит адрес модели каждого ствола пака весь заход (`pack-models.js`, «возврат к паку ничего не читает заново»), и это та же модель, что откроет редактор ствола (его выбор модели
 * считается там же, `modelOf`). Раньше редактор после подлёта и монтажа читал её у Astral Desktop ещё раз: 6 МБ по IPC и новый blob-адрес при уже лежащем в окне. Теперь он берёт адрес экрана
 * сразу, как только замонтирован, — чтение у Desktop из цепочки «щелчок → ствол на экране» уходит совсем.
 *
 * Берутся только простые модели игры (без обвесов, вида из каталога и номера текстуры): у остальных ключ другой, они читаются, как прежде. Адрес — взаймы: его отзывает экран («Ганпак») при уходе,
 * редактор свой кэш адресов отзывает, пропуская чужие (`isLentModel`). Экран уходит — реестр пустеет.
 *
 * `globalThis.__astralNoHandoff` — выключатель стенда замеров (`scripts/perf/baseline/gun-pick.mjs --nohandoff`): сравнение «до/после» из одной сборки.
 */

const lent = new Map();

/** Экран прочитал модель `id` (идентификатор записи реестра), адрес — blob. */
export function lendModel(id, url) {
  if (id && typeof url === "string" && url.startsWith("blob:")) lent.set(id, url);
}

/** Адрес модели, что экран уже прочитал, или пустая строка — читать у Desktop. */
export function borrowModel(id) {
  if (globalThis.__astralNoHandoff) return "";
  return lent.get(id) || "";
}

/** Чей-то ли это адрес взаймы: его редактор не отзывает. */
export function isLentModel(url) {
  for (const value of lent.values()) if (value === url) return true;
  return false;
}

/** Экран уходит и отзывает свои адреса: взаймы больше нечего. */
export function recallModels(ids) {
  for (const id of ids) lent.delete(id);
}
