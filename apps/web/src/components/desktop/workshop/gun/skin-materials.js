/*
 * Кожа, которую каталог кладёт рядом с вещью в её модель, а не часть самой вещи (16.11.2026, «кисть красит только вещь», слово владельца).
 *
 * Модель вещи на карточке — GLB с нашего CDN — для бороды, усов и причёски несёт базовую голову: отдельный меш, материал `head`, свой лист 512 × 512 без альфы
 * (`packages/clothing/stock-body.js`, штатная голова игры; в разобранных `berd` и `hair` GTA 5 RP и Majestic она одинаковая: 1514 вершин, 2700 треугольников).
 * У накладок на кисть (`BlacknailsbyCarti`) рядом с ногтями лежит кусок штатной руки — материал `hand`. Это кожа: её лист не принадлежит файлу вещи, и красить
 * её студия не должна. Метки `astralBody`, которые ставит сборщик модели, в уже выложенных GLB отсутствуют — поэтому кожа узнаётся по имени материала.
 *
 * Только `head` и `hand`: у других частей тела (`torso`, `legs`, `feet`) имя совпадает с именем самой вещи, когда она встаёт на эту часть, и по имени их не разделить.
 * Тату («Части тела») красят материалы `tattoo_*`, подложка у них помечена `astralBody` и от этой проверки не зависит.
 *
 * Страховка от ложного срабатывания: кожей `head` и `hand` считаются, только если в модели есть сама вещь — хотя бы один материал, который не кожа и не подложка тела.
 * Если вся модель — материал `head` (карточка, где вещь и есть голова или её часть), красить можно как раньше.
 */
const SKIN_PART_MATERIALS = new Set(["head", "hand"]);

/** Материал — кожа из каталожной модели (голова под бородой и причёской, рука под ногтями), а не вещь. */
export const isSkinPartMaterial = (material) => SKIN_PART_MATERIALS.has(String(material?.name ?? "").trim().toLowerCase());

const isBodyUnderlay = (material) => Boolean(material?.userData?.astralUnderlay || material?.userData?.astralBody);

/**
 * В модели рядом с кожей есть сама вещь? `materialLists` — списки материалов всех сеток модели. Вещь — материал, который не кожа каталога и не подложка тела.
 * Пока вещи нет, `head` и `hand` красятся как обычные материалы.
 */
export const hasItemBesideSkin = (materialLists) =>
  [...(materialLists ?? [])].some((list) => [].concat(list).some((material) => material && !isSkinPartMaterial(material) && !isBodyUnderlay(material)));
