function humanize(value) {
  const text = String(value || "")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replaceAll("-", " ")
    .replaceAll("_", " ")
    .trim();
  return text ? text[0].toUpperCase() + text.slice(1) : text;
}

