/*
 * Готовые звуки: по шестнадцать на каждую группу стволов и на каждую часть
 * тела.
 *
 * С них начинают, а не заканчивают: готовый звук ставит источник и ручки, и
 * дальше человек подкручивает их под себя — плитка не «состояние», а
 * отправная точка, как готовые виды неба.
 *
 * ОРУЖИЕ. Самые скачиваемые звуковые моды для RP-серверов — не «новые
 * выстрелы», а тот же выстрел игры, только тише, глуше и «как с глушителем»
 * (Silenced Sounds, «Тихие звуки оружия», «Глухие звуки» — десятки тысяч
 * скачиваний каждый). Поэтому готовые звуки ствола — это его собственный
 * голос из игры игрока, обработанный: у каждого ствола он свой, а обработка
 * настроена по группе — дробовику «Мощный» даёт больше низа, снайперской
 * «Далёкий» — хвост вдвое длиннее.
 *
 * Вторая восьмёрка у каждой группы — выстрелы-фантазии (`sound-synth.js`):
 * бластер, лазер, плазма, рельсотрон, 8-бит, водяной пистолет и другие по
 * мотивам аркадных и мультяшных шутеров — для тех, кому нужно весело, а не
 * реалистично. Набор у группы свой: снайперской — рельсотрон и гром, ПП —
 * импульс и тесла, дробовику — пушка и конфетти, и тон подогнан под ствол.
 *
 * ПОПАДАНИЯ. Своей дорожки «попадания в голову» у игры нет — удар собран из
 * слоёв, и звук человека встаёт вместо них. Готовые звуки попадания — синтез
 * (`sound-synth.js`): колокольчик, дзынь каски, хитмаркер, треск щита, крит
 * и остальные по мотивам того, что просят в сообществе, собранные заново.
 */

const preset = (id, title, hint, source, fx = {}) =>
  Object.freeze({
    id,
    title,
    hint,
    source: Object.freeze(source),
    fx: Object.freeze(fx),
  });

