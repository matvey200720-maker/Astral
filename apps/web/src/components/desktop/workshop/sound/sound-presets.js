export const WEAPON_PRESETS = Object.freeze(
  Object.fromEntries(
    WEAPON_PRESET_GROUPS.map((group) => [
      group,
      Object.freeze([
        ...WEAPON_ARCHETYPES.map(([id, title, hint, fx]) => {
          const [ownTitle, ownHint] = GROUP_TITLES[group]?.[id] || [title, hint];
          return preset(
            `${group}:${id}`,
            ownTitle,
            ownHint,
            id === "blaster" ? synth("blaster") : ORIGINAL,
            { ...fx, ...(GROUP_TUNING[group]?.[id] || {}) },
          );
        }),
        ...WEAPON_FANTASIES[group].map(([recipe, title, hint, fx]) =>
          preset(`${group}:${recipe}`, title, hint, synth(recipe), fx),
        ),
      ]),
    ]),
  ),
);

