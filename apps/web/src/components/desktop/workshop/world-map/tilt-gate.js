import { mapColorSource } from "@modovik/vector-map";

/*
 * Где есть «Наклон радара» и настоящие 3D-здания в мини-карте (21.11.2026).
 *
 * Наклон «как в машине» — поля камеры радара в `minimap.ymt`; радар с 22.10 всегда векторный (перекраска плиток по парам цветов, растр под
 * ним не кладётся), поэтому наклон работает у любой карты: `TILT_FOR_PICTURE_MAPS = true`. Закрыть наклон для карт-картинок снова — одна
 * правка этой константы: строка «Наклон радара» исчезнет, а включённый наклон перестанет уходить в игру (`world-map-game.js`).
 *
 * Здания (`radarBuildings` в `@modovik/vector-map`) от этой константы не зависят: им нужны кварталы, а они есть только у карты из игры и у
 * векторных готовых карт (пак Akio и подобные). У снимка, своей картинки и растрового шаблона строка «3D-здания» говорит, что рисовать
 * нечего.
 */
export const TILT_FOR_PICTURE_MAPS = true;

/**
 * Рисуется ли радар по кварталам: подложка — карта из игры или векторная готовая карта. Геометрию радара окно берёт из игры (запасом — из
 * поставки), поэтому сцену редактора, в которой её может ещё не быть, правило не спрашивает. То же правило, что у `radarBuildings`.
 */
export function radarIsVector(config) {
  const source = mapColorSource(config, { geometry: true });
  return source === "game" || source === "pack";
}

/** Показывать ли строку «Наклон радара» и класть ли наклон в заявку на установку. */
export function tiltAvailable(config) {
  return TILT_FOR_PICTURE_MAPS || radarIsVector(config);
}
