/*
 * Строка про мини-карту в углу экрана — в итог установки большой карты.
 *
 * Установка отдаёт `radar: { asked, painted, reason, layers }`
 * (`installWorldMap`): спросили ли радар вообще (карта отличается от
 * игровой), встал ли он и, если нет, почему (`world-map-radar.js`). До 13.10 об этом не говорилось ни
 * слова: на паузе стояла новая карта, а в углу экрана — штатная, и человек не
 * мог понять, ошибка это или так задумано.
 */

import { tr } from "../../../locales/ui.js";

/* Причины читаются при вызове, а не при загрузке модуля: до смены языка
   словарь молчит, и перевод строки в константе остался бы русским. */
const REASON_TEXT = Object.freeze({
  unchanged:
    "Мини-карта в углу экрана осталась штатной: цвета карты не менялись, зон для неё нет (подписи, рисунок и текстура на мини-карту не попадают)",
  "no-picture": "Мини-карта в углу экрана осталась штатной: картинка карты не прочиталась",
  "no-geometry": "Мини-карта в углу экрана осталась штатной: геометрия радара игры не прочиталась",
  "no-colours": "Мини-карта в углу экрана осталась штатной: на картинке карты не нашлось цветов для радара",
  "no-palette": "Мини-карта в углу экрана осталась штатной: цвета радара из игры не прочитались",
});

/*
 * Слои большой карты на радаре (`radar.layers`, задача 28): зоны треугольниками.
 * Хост мог отказать — тогда радар перекрашен без зон, и человек слышит об этом.
 */
const NO_ZONES = "Зоны на мини-карту не легли — Astral оставил её без них";

/** Что сказать про радар; пусто — радар не просили, сказать нечего. */
export function radarDoneNote(radar) {
  if (!radar?.asked) return "";
  const layers = radar.layers;
  if (radar.painted) {
    const lead = layers?.ok
      ? tr(
          radar.colours
            ? layers.labels
              ? "Мини-карта в углу экрана перекрашена в цвета вашей карты, и на неё нанесены зоны и подписи"
              : "Мини-карта в углу экрана перекрашена в цвета вашей карты, и на неё нанесены зоны"
            : layers.labels
              ? "Мини-карта в углу экрана показывает зоны и подписи вашей карты"
              : "Мини-карта в углу экрана показывает зоны вашей карты",
        )
      : tr("Мини-карта в углу экрана перекрашена в цвета вашей карты");
    if (layers && !layers.ok) return `${lead}. ${tr(NO_ZONES)}`;
    /* Этап В: свои надписи, значки и картинки карты тоже на радаре; упрощены ли ради бюджета — тоже слышно. */
    const extra = [];
    if (layers?.pictures > 0) extra.push(tr("На мини-карту легли и свои надписи, значки и картинки карты"));
    if (layers?.pictures > 0 && layers.reduced) extra.push(tr("Часть из них упрощена, чтобы мини-карта не просела по кадрам"));
    return [lead, ...extra].join(". ");
  }
  const lead = tr(REASON_TEXT[radar.reason] || "Мини-карта в углу экрана осталась штатной");
  return layers && !layers.ok ? `${lead}. ${tr(NO_ZONES)}` : lead;
}

/** Итоговая строка установки с радаром в конце. */
export function withRadarNote(text, radar) {
  const note = radarDoneNote(radar);
  return note ? `${String(text).replace(/\.$/, "")}. ${note}` : text;
}

/*
 * Остров Кайо-Перико (19.10.2026): установка отдаёт `island: { asked, painted,
 * reason }`. Остров — отдельный фильм игры, и он виден на радаре и на карте
 * паузы только когда игра включает радар острова (игрок на нём), поэтому
 * строка говорит и об этом.
 */
const ISLAND_REASON_TEXT = Object.freeze({
  unchanged: "Остров Кайо-Перико остался штатным: цвета карты не менялись",
  "no-palette": "Остров Кайо-Перико остался штатным: его цвета из игры не прочитались",
  "no-base": "Остров Кайо-Перико остался штатным: в этой игре не нашёлся его файл",
});

/** Что сказать про остров; пусто — его не трогали. */
export function islandDoneNote(island) {
  if (!island?.asked) return "";
  if (island.painted)
    return tr("Остров Кайо-Перико перекрашен в цвета вашей карты — он виден, когда вы на острове");
  return tr(ISLAND_REASON_TEXT[island.reason] || "Остров Кайо-Перико остался штатным");
}

/** Итоговая строка установки с островом в конце. */
export function withIslandNote(text, island) {
  const note = islandDoneNote(island);
  return note ? `${String(text).replace(/\.$/, "")}. ${note}` : text;
}

/*
 * Размытие за картой паузы (15.10): установка отдаёт `pauseBlur: { removed,
 * reason }`, когда его просили убрать. Не вышло — карта всё равно стоит, а
 * человек слышит, почему за ней по-прежнему размыто.
 */
const BLUR_REASON_TEXT = Object.freeze({
  owned: "Размытие за картой осталось как в игре: файл эффектов экрана занят модом из каталога",
  unreadable: "Размытие за картой осталось как в игре: файл эффектов экрана не прочитался",
});

/** Что сказать про размытие за картой; пусто — его не трогали. */
export function pauseBlurDoneNote(pauseBlur) {
  if (!pauseBlur) return "";
  if (pauseBlur.removed) return tr("За картой паузы — без размытия");
  return tr(BLUR_REASON_TEXT[pauseBlur.reason] || "Размытие за картой осталось как в игре");
}

/** Итоговая строка установки с размытием за картой в конце. */
export function withPauseBlurNote(text, pauseBlur) {
  const note = pauseBlurDoneNote(pauseBlur);
  return note ? `${String(text).replace(/\.$/, "")}. ${note}` : text;
}
