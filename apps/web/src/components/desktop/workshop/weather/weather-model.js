/*
 * Погода сцены: чем её вывести из таймцикла.
 *
 * Отдельного редактора погоды больше нет, и это не потеря ручек, а исправление
 * ошибки. Погоду в игре задают файлы таймцикла — те самые, которые правит
 * редактор неба. Второй экран с собственными ползунками не мог ничего
 * установить и честно отправлял человека в редактор неба; смотреть на дождь
 * надо там же, где его настраивают. Поэтому здесь остался ровно один вопрос:
 * как из выбранного типа погоды получить то, чем сцена рисует его на земле.
 *
 * Ни одного значения «на глаз». Облачность, мягкость края гряды и дальность
 * тумана приезжают из пакета `@modovik/timecycle` — того же, по которому
 * редактор неба показывает свой купол. Придумать их заново означало бы землю,
 * не совпадающую с небом над ней в одном и том же кадре.
 *
 * Своя здесь ровно одна величина, и она — потому, что в таймцикле её нет:
 *
 *  • ВЫСОТА облаков. Генератор облаков в игре процедурный и живёт в куполе
 *    неба; высоты у него нет ни одним параметром. Значение выводится из
 *    плотности: тяжёлая облачность в игре читается низкой грядой, лёгкая —
 *    высокой. Правило одно и написано здесь, а не разбросано по сцене.
 *
 * Осадки и ветер той же природы — их в таймцикле тоже нет, — но они нужны и
 * куполу редактора неба, поэтому лежат в пакете (`weather-conditions.js`) и
 * приходят оттуда: одна погода на оба кадра.
 *
 * Дальность тумана здесь — та, которую видно в кадре, в метрах, а не масштаб
 * мира. Масштаб пересчитает сцена: окно умножает заданную ему дальность на
 * суточный ход тумана, и число, отданное масштабу, означало бы разную дымку в
 * полдень и в полночь при одном и том же тумане таймцикла. Умножение здесь и
 * деление в сцене — одна и та же величина, взятая с двух сторон.
 *
 * Часа у настройки нет намеренно. Всё, что от него зависело, — дальность
 * тумана, — сцена тут же делит на тот же суточный ход, и на выходе получается
 * одно и то же число в любой час. Суточный ход в кадр приносит окно: цвет
 * света, длину тени и густоту дымки на земле ведёт оно, ровно как и на куполе.
 */

import { findWeather, weatherConditions } from "@modovik/timecycle";
import { fogFalloff, previewLighting } from "../preview/preview-lighting.js";

const clamp = (value, min, max) => Math.min(Math.max(value, min), max);

/** Пределы величин настройки. Одни на вывод из таймцикла и на разбор чужого. */
export const WEATHER_RANGES = Object.freeze({
  cloudDensity: Object.freeze({ min: 0, max: 100 }),
  cloudHeight: Object.freeze({ min: 200, max: 3000 }),
  cloudSoftness: Object.freeze({ min: 2, max: 100 }),
  fogDistance: Object.freeze({ min: 40, max: 900 }),
  amount: Object.freeze({ min: 0, max: 100 }),
  windSpeed: Object.freeze({ min: 0, max: 100 }),
});

/*
 * Осадки, ветер и всё остальное, чего нет в таймцикле, приезжают одной
 * таблицей из пакета (`weather-conditions.js`), а не заводятся здесь.
 *
 * Раньше таблица стояла в этом файле, и та же погода понадобилась куполу
 * редактора неба: два кадра одного редактора о снеге и ветре должны говорить
 * одно и то же, иначе непонятно, какому верить. Таблица в пакете — общая для
 * обоих; здесь остаётся то, ради чего файл и заведён: как из погоды получается
 * настройка сцены.
 */

/*
 * Час, на котором снимаются числа погоды.
 *
 * Полдень, а не текущий час кадра. Из всего, что читается из таймцикла, по
 * часу гуляет одна дальность тумана, и её сцена тут же делит на тот же
 * суточный ход — то есть любой час дал бы одинаковый результат. Полдень выбран
 * потому, что по нему погоду и узнают: это тот час, в котором «пасмурно»
 * выглядит пасмурно.
 */
const REFERENCE_HOUR = 12;

/** Небо и свет часа — их же читает окно предпросмотра. */
export const lightingAt = (weatherId, hour) =>
  previewLighting({ weather: weatherId, timeOfDay: hour });

/** Облачность таймцикла в долях единицы: сила слоя, помноженная на плотность. */
export function cloudCover(sky) {
  return clamp(
    Math.max(sky.cloudStrength, 0) * Math.max(sky.cloudDensity, 0),
    0,
    1,
  );
}

/**
 * Дальность тумана этого неба в метрах.
 *
 * Окно считает суточный ход тумана множителем к дальности сцены (`fogFalloff`),
 * и `BASE_FOG_METRES` — та дальность, при которой множитель единица даёт
 * привычный открытый горизонт.
 */
export const BASE_FOG_METRES = 340;

export const fogDistanceOf = (sky) =>
  Math.round((BASE_FOG_METRES * fogFalloff(sky)) / 10) * 10;

/**
 * Настройка сцены для одного типа погоды.
 *
 * Единственный вход модели: тип погоды на входе, всё, чем сцена рисует его на
 * земле, — на выходе. Ею же поднимается сцена, когда своей настройки не
 * передали: и на стенде, и в витрине в кадре должна быть видна погода, а не
 * пустой горизонт.
 */
export function defaultSetup(weatherId = "CLOUDS") {
  const id = findWeather(weatherId)?.id || "EXTRASUNNY";
  const sky = lightingAt(id, REFERENCE_HOUR).sky;
  const cover = cloudCover(sky);
  const conditions = weatherConditions(id);

  return {
    weather: id,
    clouds: {
      density: Math.round(cover * 100),
      /* Чем плотнее гряда, тем ниже она висит — см. шапку файла. Шаг в 50 м:
         разницу мельче полусотни метров в кадре всё равно не отличить. */
      height: Math.round((2400 - 1600 * cover) / 50) * 50,
      softness: Math.round(clamp(sky.cloudGenSoftness, 0.02, 1) * 100),
    },
    fog: {
      distance: clamp(
        fogDistanceOf(sky),
        WEATHER_RANGES.fogDistance.min,
        WEATHER_RANGES.fogDistance.max,
      ),
    },
    precipitation: {
      kind: conditions.precipitation.kind,
      amount: conditions.precipitation.amount,
    },
    wind: { speed: conditions.wind, angle: conditions.windAngle },
  };
}

/*
 * Настройка, которой поднимается сцена без чужой.
 *
 * Дождь, а не «ясно»: сцену поднимают не только из редактора неба — её
 * открывают на стенде и снимают для витрины, и в обоих местах в кадре должна
 * быть видна погода. Ясное небо над сухой землёй ничем не отличается от сцены,
 * у которой погода вовсе не работает.
 */
export const defaultWeatherSetup = () => defaultSetup("RAIN");
