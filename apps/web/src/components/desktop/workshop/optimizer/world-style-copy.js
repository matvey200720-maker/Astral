/** Карточка стиля по имени стадии; `null` и неизвестное — «Без стиля». */
export const styleCard = (id) => STYLE_CARDS.find((card) => card.id === id) || STYLE_CARDS[0];

/*
 * Стиль на весь экран (ReShade, задача 38) называется так же, как стадия конвейера текстур, без приставки: пресет
 * `painted` — карточка `style-painted`. Кадр слева, имена и снятие прежнего стиля пакетом текстур говорят на языке
 * стадий, пресет ReShade — на языке пресетов.
 */
export const reshadeStyleOf = (cardId) => (cardId ? String(cardId).replace(/^style-/, "") : null);
export const textureStyleOf = (presetId) => {
  const card = presetId ? STYLE_CARDS.find((item) => item.id === `style-${presetId}`) : null;
  return card ? card.id : null;
};

/** Вес пакетов ЧБ-мира без стиля (МБ, как у карточек): 128 px — замер, 256 px — 0,96 от «рисованного». */
const GRAY_MEGABYTES = Object.freeze({ 128: 4940, 256: 8970 });

/**
 * Машины и оружие в тех же пакетах (задача 35 (б), замер на игре владельца, «комикс»): словари машин и деталей и штатное
 * оружие — +116 МБ на 128 px, +353 МБ на 256 px; у других стилей — в пределах пятнадцати процентов.
 */
const GEAR_MEGABYTES = Object.freeze({ 128: 120, 256: 360 });

/**
 * Дальние планы (LOD, SLOD, children) держат не меньше 512 px (ТЗ 24.10.2026, п. 2: `FAR_PLANE_CAP`): верхняя оценка добавки к
 * пакетам по индексу ступеней на игре владельца — 743 МБ на 256 px, около гигабайта на 128 px (предел ужимал 2 321 из 13 735 словарей
 * дальних планов с 1 174 МБ до 430 МБ на 256 px).
 */
const FAR_PLANE_MEGABYTES = Object.freeze({ 128: 1000, 256: 750 });

/** Вес пакетов (МБ) стиля и/или ЧБ-мира при чёткости `detail` (128 или 256); ничего не стоит — 0. */
export function lookMegabytes(style, gray, detail) {
  const key = detail === 256 ? 256 : 128;
  const base = style ? styleCard(style).megabytes[key] : gray ? GRAY_MEGABYTES[key] : 0;
  return base ? base + GEAR_MEGABYTES[key] + FAR_PLANE_MEGABYTES[key] : 0;
}
