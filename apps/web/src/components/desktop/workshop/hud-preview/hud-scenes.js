/*
 * Какие кадры общее окно умеет показать под слоем интерфейса.
 *
 * Список общий, и это осознанно: мини-карта, HUD и значки живут на одном и
 * том же экране игры, и если у них разные подложки, то договориться о
 * размерах и читаемости по двум разным картинкам нельзя. Кто кадр игры не
 * показывает вовсе — прицел, — берёт отсюда одну матовую сцену, а не список.
 *
 * Комплект «улицы» лежит в ассетах стрельбища эффектов — там он появился
 * первым, вместе с `PhotoRange.jsx`. Второй копии тех же полутора мегабайт в
 * репозитории быть не должно, поэтому здесь стоит ссылка, а не копия; путь
 * назван один раз и меняется в одном месте.
 */

import { tr } from "../../../../locales/ui.js";

/** Комплект живого кадра: `scene.json` рядом с видео и постером. */
export const HUD_STREET_SCENE =
  "/assets/workshop/fx-range/variant-1.scene.json";

/** Статичный кадр: тот самый, на котором раньше стоял прицел. */
export const HUD_RANGE_FRAME =
  "/assets/workshop/reticle/reticle-test-backdrop.png";

/**
 * Матовая сцена: студийная подложка вместо кадра игры.
 *
 * Ни картинки, ни видео у неё нет — окно рисует её материалом продукта
 * (`--dragon-matte-stage`, тот же, на котором стоят прозрачные рендеры оружия
 * в каталоге). Нужна она затем же, зачем фотографу серый фон: увидеть форму и
 * цвет самого слоя, а не то, как он спорит с кустами и небом.
 *
 * В общем списке она стоит третьей кнопкой рядом с кадрами игры: мини-карте
 * нужно видеть, как она ляжет на дорогу. Прицел же смотрят только на ней —
 * редактор прицела приносит свой список из одной этой сцены
 * (`RETICLE_SCENES` в `ReticleCustomizer.jsx`), и кадра игры под сеткой там
 * нет вовсе.
 */
export const HUD_MATTE_SCENE = Object.freeze({
  id: "matte",
  get label() {
    return tr("Матовый фон");
  },
  kind: "matte",
  /* Размер тот же, что у стоп-кадра: переключение между сценами не должно
     менять пропорцию коробки, иначе слой прыгнет, а «1:1» перестанет быть
     сравнимым. */
  size: [1672, 941],
});

/**
 * Порядок важен: первым идёт живой кадр.
 *
 * Человек открывает редактор и должен сразу увидеть слой поверх движущейся
 * картинки — на неподвижной подложке не видно, что мини-карта сливается с
 * дорогой. Неподвижный кадр остаётся вторым: на нём удобно вымерять пиксели.
 * Матовый — третьим: это лупа, а не игра.
 *
 * Это список по умолчанию, а не обязательный: потребитель вправе принести
 * свой. Прицел так и делает — берёт одну матовую сцену.
 */
export const HUD_SCENES = Object.freeze([
  Object.freeze({
    id: "street",
    get label() {
    return tr("Живой кадр");
  },
    scene: HUD_STREET_SCENE,
  }),
  Object.freeze({
    id: "range",
    get label() {
    return tr("Стоп-кадр");
  },
    kind: "image",
    src: HUD_RANGE_FRAME,
    size: [1672, 941],
    game: true,
  }),
  HUD_MATTE_SCENE,
]);
