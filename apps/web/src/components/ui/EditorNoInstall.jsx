import { Info } from "./icons.jsx";

/*
 * «Отсюда в игру пока не ставится» — одной строкой и одинаково везде.
 *
 * У трёх редакторов установки нет: у интерфейса, значков и дорог. Причины у
 * всех разные и все настоящие — у одного маршрут лежит в чужом редакторе, у
 * другого нужен разбор Scaleform, у третьего нет проверенного списка целей.
 * У оружия в игру не уезжает часть работы — брелоки и эффекты вокруг ствола:
 * строка стоит там, где о них говорят.
 *
 * Кнопка, которая ничего не делает, хуже её отсутствия: по нажатой кнопке
 * судят, что мод встал.
 *
 * Но молчание — тоже ответ, и неправильный. Человек красит ствол полчаса,
 * ищет «Применить» и не находит; сказать ему об этом должен экран, а не
 * догадка. У интерфейса и значков такая строка была своя, у дорог и оружия не
 * было никакой — отсюда одна на всех: одно место, одни слова, один вид.
 *
 * Три поля, и все обязательные, потому что без любого из них строка
 * бесполезна: `what` — что этот редактор правит; `reason` — почему в игру
 * пока не уезжает, конкретно, а не «не поддерживается»; `instead` — что с
 * работой можно сделать прямо сейчас.
 */
export default function EditorNoInstall({ what, reason, instead }) {
  return (
    <p className="ui-no-install" role="note">
      <Info weight="bold" aria-hidden="true" />
      <span>
        <b>{what}</b>
        <span>{reason}</span>
        <span className="ui-no-install-instead">{instead}</span>
      </span>
    </p>
  );
}
