// Экскурсии по редакторам: что подсветить и что сказать на каждом шаге.
//
// Экскурсия — это список шагов. Шаг описан строкой-кортежем: первое слово
// выбирает вид шага, остальное — его данные. Готовые шаги собирают маленькие
// сборщики ниже (ключи в шаге всегда идут в одном и том же порядке):
//   ["frame", заголовок, текст, цель?]            кадр: id "frame", placement "inside";
//   ["panel", id, заголовок, текст, инструмент?, цель?]
//                                                 панель инструмента в боковой панели;
//   ["tab", id, заголовок, текст]                 вкладка из ряда инструментов (id = data-tool);
//   ["part", id, цель, заголовок, текст]          произвольный элемент по своему селектору;
//   ["templates", текст?], ["apply", текст?]      обычные «Шаблоны» и «Применить».
// Порядок экскурсий и шагов — порядок показа; верхний уровень заморожен,
// внутри ничего не заморожено.

