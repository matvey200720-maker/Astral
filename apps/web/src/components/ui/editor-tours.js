const byLabel = (name) => `[aria-label="${name}"]`;
const inInspector = (selector) => `.ui-editor-inspector ${selector}`;
const toolTab = (name) => `.ui-editor-tools [data-tool="${name}"]`;

const frame = (title, text, target = "canvas") => ({ id: "frame", target, placement: "inside", title, text });
const panel = (id, title, text, tool = id, target = "inspector") => ({ id, tool, target, title, text });
const part = (id, target, title, text) => ({ id, target, title, text });
const tab = (id, title, text) => part(id, toolTab(id), title, text);
const templates = (text = TEMPLATES_TEXT) => tab("templates", "Шаблоны", text);
const apply = (text = APPLY_TEXT) => part("apply", APPLY_TARGET, "Применить", text);

const STEP_BUILDERS = { frame, panel, tab, part, templates, apply };

const tour = (...rows) => rows.map(([kind, ...args]) => STEP_BUILDERS[kind](...args));

