import { isPhotoShown } from "../../utils/shown-photos.js";

/*
 * Рывок по виртуальной сетке (30.10.2026, «чтобы быстро грузились фотки»).
 *
 * Сетка (`VirtualGrid.jsx`) помечает рывок — прокрутку быстрее ~3 px/мс (ползунок, End, колесо с разгона): карточки, что пролетают мимо, живут в документе по
 * несколько кадров, и каждая просила бы картинку у локального API, а тот — у CDN. Браузер запроса уже стоящей в очереди или идущей картинки не отменяет, а на
 * рывке в сто рядов их сотня, и картинки последнего экрана вставали в хвост (стенд, холодно: ~100 лишних запросов, последний экран через 7–8 с). Поэтому то, что
 * карточка делает сама (замер рисунка в потоке, `useFrameCrop`), на рывке ждёт его конца: не дождалась — карточка ушла, запроса не было.
 *
 * Исключение — картинка, которая в этом окне уже была показана (31.10.2026, `utils/shown-photos.js`): у неё в кэше браузера и на диске API готовый файл, холодного запроса не
 * будет, и ждать её нечего — иначе тот, кто листает свой уже загруженный каталог, видел бы пустые карточки и платил бы ожиданием конца рывка (стенд, тепло: +210 мс).
 *
 * Состояние одно на окно: в каталоге быстро листают одну сетку, а лишнее ожидание у соседней стоит не больше `FLING_CALM_MS` сетки.
 */

let flinging = false;
const waiting = new Set();

/** Идёт ли рывок. */
export const isVirtualFling = () => flinging;

/** Сетка сообщает, что рывок начался или кончился; кончился — ждавшие запускаются. */
export function setVirtualFling(next) {
  if (flinging === next) return;
  flinging = next;
  if (next) return;
  const ready = [...waiting];
  waiting.clear();
  for (const run of ready) run();
}

/**
 * Запускает `run` сразу, если рывка нет или картинка `url` уже была показана, а иначе — когда рывок кончится. Вернёт отмену: карточка ушла раньше.
 */
export function afterVirtualFling(run, { url = "" } = {}) {
  if (!flinging || isPhotoShown(url)) {
    run();
    return () => {};
  }
  waiting.add(run);
  return () => {
    waiting.delete(run);
  };
}
