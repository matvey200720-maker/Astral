import { tr, useTr } from "../../locales/ui.js";

/*
 * Запасной кадр страницы, чей кусок ещё едет (31.10.2026, холодный старт).
 *
 * Куски разделов подтягиваются в простое (`usePreloadWhenIdle`), но не раньше двух секунд после старта: щелчок по «Мастерской» в первые секунды получает кусок
 * по требованию. Раньше на месте страницы было `null` — пустой экран на время загрузки куска и ещё 300 мс, которые React придерживает за пустым запасным
 * кадром. Теперь на этом месте строка «Загружаю…».
 *
 * Строка появляется не сразу: первые `--astral-duration-snap` (100 мс) она прозрачна (`.ui-page-loading` в `editor-shell.css`), поэтому кусок, что приехал
 * быстрее, не мигает подписью. Подпись лежит в атрибуте и выходит псевдоэлементом, как у занавеса редактора (`ui-veil-label`).
 */
export default function PageLoading() {
  useTr();
  return (
    <div className="ui-page-loading" role="status" aria-busy="true" aria-live="polite">
      <p className="ui-veil-label" data-label={tr("Загружаю…")} />
    </div>
  );
}
