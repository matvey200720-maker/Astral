/*
 * Ошибка «файл другой работы Astral, поверх которого собираем, не читается» (21.11.2026): растительность, дороги и места собираются поверх копии соседа и при нечитаемой копии отказывают, а не берут штатный файл молча.
 * Текст один на три работы (слова окна узнают его по «Файл «…» поставлен другой работой Astral (…), но не читается: <кто> не может лечь поверх него», `rp-update-notes.js`).
 */
export const COMPOSED_WHO = Object.freeze({ vegetation: "растительность не может", roads: "дороги не могут", places: "эта работа не может" });

export const composedUnreadableError = (name, at, who = "vegetation") =>
  new Error(`Файл «${name}» поставлен другой работой Astral (${at}), но не читается: ${COMPOSED_WHO[who] ?? COMPOSED_WHO.places} лечь поверх него. Откройте «Починить» и повторите.`);
