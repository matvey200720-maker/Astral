/*
 * Кому из запросов мастерской одежды выдавать доверие каталога (ключ подписи, хосты пакетов, папка загрузок). Отдельный лёгкий модуль: IPC главного процесса зовёт его на каждый запрос,
 * а `clothing-character.js` живёт в потоке читателя игры и в главный процесс не грузится.
 */

/**
 * Нужен ли запросу персонажа пакет каталога: вещь каталога — сама вещь (`manifest` в запросе) или одна из вещей комплекта (`others[].manifest`). Прежде IPC смотрел только на
 * `manifest` верхнего уровня: в режиме «одеть» вещь каталога идёт в `others`, пакет не скачивался («Цифровая подпись недействительна» глоталась), и вещь на персонаже не
 * появлялась (31.10.2026).
 */
export const usesCatalogPackages = (input) =>
  Boolean(input?.manifest) || (Array.isArray(input?.others) && input.others.some((item) => Boolean(item?.manifest)));
