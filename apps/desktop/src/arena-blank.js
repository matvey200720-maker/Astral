/*
 * Модели-пустышки мода арены (24.10.2026).
 *
 * Редукс не умеет убирать модель игры иначе, чем подложить под её имя пустой файл: у 314 `v_62_bannersx.ydr` — 114 байт, `v_62_blinds.ydr` —
 * 304, звезда `v_62_fos_props01.ydr` — 528, кресла `v_ilev_chair02_ped.ydr` — 178, и так по десятку моделей зала; у Blink — `sp1_10_details2–7`,
 * у Sakura — `v_62_lobby_wall`, `v_62_signs01`. Игра читает такой файл как «моделей нет», а кадр каталога рисовал прежние модели сцены мастерской на
 * их месте — отсюда «звезда не меняется, баннеры не те». Пустышка — ресурс без геометрии: сетки в нём нет вовсе (не «маленькая настоящая» —
 * у настоящих моделей зала не меньше десятков килобайт, самая мелкая из мода — 1,4 КБ с двумя сетками).
 *
 * Здесь — только то, что нужно и главному процессу (какие файлы читать), и потоку читателя (как их разбирать): без зависимостей.
 */

export const BLANK_MODEL_FILE = /\.(ydr|yft|ydd)$/i;

/* Пустышка короче этого: больше килобайта-четырёх в ней не бывает (заголовок ресурса, таблица шейдеров, имя), а проверять на геометрию каждую настоящую
   модель зала (оболочка — 20 МБ) незачем. */
export const BLANK_MODEL_BYTES = 4096;

/** Файлы мода, которые могут быть пустышками: модель и не длиннее `BLANK_MODEL_BYTES`. */
export const blankCandidates = (files = []) =>
  files.filter(
    (file) =>
      BLANK_MODEL_FILE.test(String(file?.name || "")) &&
      Number(file?.bytes?.length ?? file?.size ?? Infinity) <= BLANK_MODEL_BYTES,
  );
