/*
 * Ссылка `astral://mods/<id>`: разбор аргументов и почтовый ящик «ссылка ждёт окна» — без `electron`, чтобы проверяться тестами ядра (`tests/deep-link-args.test.js`).
 * Приходит она тремя дорогами — аргументом запуска (холодный старт), аргументом второго запуска уже открытого приложения и системным событием `open-url`; все три сходятся
 * в `deep-link.js`, а здесь — то, что общее для них: что считается ссылкой и кто её помнит, пока окно не загрузилось.
 */

/** Ссылка на мод: `astral://mods/<id>` (id — до первого `/`, `?` или `#`). */
export const DEEP_LINK = /^astral:\/\/mods\/[^/?#]+/i;

/** Найти ссылку среди аргументов запуска; ничего не найдено — пустая строка. */
export function deepLinkFromArgs(args = []) {
  return args.find((value) => DEEP_LINK.test(String(value))) || "";
}

/**
 * Ящик: последняя пришедшая ссылка лежит, пока окно не загрузилось, и достаётся один раз — окно перезагружается (пробуждение после спячки, подъём после сбоя
 * рендерера), и та же ссылка снова открыла бы тот же мод поверх того, где человек остановился.
 */
export function createDeepLinkMailbox() {
  let pending = "";
  return {
    /** Запомнить ссылку, с которой приложение запустили (аргументы запуска). */
    remember(args) {
      pending = deepLinkFromArgs(args);
      return pending;
    },
    /** Положить ссылку, пришедшую открытому приложению: не ссылка — ящик не меняется. Ответ — принятая ссылка или пустая строка. */
    put(value) {
      const link = deepLinkFromArgs([value]);
      if (link) pending = link;
      return link;
    },
    /** Забрать ссылку (один раз) — окно загрузилось. */
    take() {
      const value = pending;
      pending = "";
      return value;
    },
    /** Ссылка уже отдана окну — ящик пуст. */
    clear() {
      pending = "";
    },
    peek: () => pending,
  };
}
